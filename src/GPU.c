static int
	SUBMIT_AND_WAIT(GPU *GPU_STATE)
{
	VULKAN_FUNCTION(vkEndCommandBuffer)(GPU_STATE->COMMAND_BUFFER);

	VkSubmitInfo	SUBMIT_INFO = {
		VKS_SUBMIT_INFO, NULL, 0, NULL, NULL, 1, &GPU_STATE->COMMAND_BUFFER, 0,
		NULL
	};

	if (VULKAN_FUNCTION(vkQueueSubmit)(GPU_STATE->QUEUE, 1, &SUBMIT_INFO, 0))
		return (-1);

	if (VULKAN_FUNCTION(vkQueueWaitIdle)(GPU_STATE->QUEUE))
		return (-1);

	return (0);
}

