{
#ifdef _WIN32
	return ((void *)LoadLibraryA("vulkan-1.dll"));
#else
	void	*LIBRARY_HANDLE = dlopen("libvulkan.so.1", RTLD_NOW);

	if (LIBRARY_HANDLE)
		return (LIBRARY_HANDLE);

	return (dlopen("libvulkan.so", RTLD_NOW));
#endif
}

