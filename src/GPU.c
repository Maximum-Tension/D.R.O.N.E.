void
	KERNEL_IF(
		KERNEL_BUILDER *BUILDER, uint32_t CONDITION, uint32_t *MERGE_LABEL
	)
{
	uint32_t	BODY_LABEL = KERNEL_NEW_LABEL(BUILDER);

	*MERGE_LABEL = KERNEL_NEW_LABEL(BUILDER);
	EMIT_OPERATION(4, 247, *MERGE_LABEL, 0);
	EMIT_OPERATION(4, 250, CONDITION, BODY_LABEL, *MERGE_LABEL);
	KERNEL_BIND_LABEL(BUILDER, BODY_LABEL);
}

