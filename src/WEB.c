static WEB
	*LOAD_ANY_VERSION(const char *PATH, int PLAY_ONLY)
{
	FILE	*STREAM = fopen(PATH, "rb");

	if (!STREAM)
		return (NULL);

	char	MAGIC[8];
	WEB		*NEURAL_WEB = NULL;

	if (fread(MAGIC, 1, 8, STREAM) != 8)
		goto READ_FAILED;

	if (!memcmp(MAGIC, "CODEWEB2", 8) || !memcmp(MAGIC, "CODEWEB3", 8))
	{
		if (PLAY_ONLY)
		{
			fclose(STREAM);
			fprintf(
				stderr,
				"old brain format: open it once with learning on to convert\n"
			);
			return (NULL);
		}

		return (LOAD_VERSION3(STREAM, PATH, !memcmp(MAGIC, "CODEWEB3", 8)));
	}

	if (memcmp(MAGIC, "CODEWEB4", 8) && memcmp(MAGIC, "CODEWEB5", 8))
		goto READ_FAILED;

	int		IS_VERSION_5 = !memcmp(MAGIC, "CODEWEB5", 8);
	int32_t	FILE_KERNEL_VERSION;
	READ_VALUE(FILE_KERNEL_VERSION);
	CONFIG	SAVED_CONFIG;
	READ_VALUE(SAVED_CONFIG);
	if (!CHECK_CONFIG(SAVED_CONFIG))
		goto READ_FAILED;

	NEURAL_WEB = ZERO_ALLOCATE(sizeof(WEB));
	NEURAL_WEB->CONFIGURATION = SAVED_CONFIG;
	SETUP_COMMON(NEURAL_WEB);
	READ_VALUE(NEURAL_WEB->WORD_COUNT);
	READ_VALUE(NEURAL_WEB->RANDOM_STATE);
	READ_VALUE(NEURAL_WEB->STEP);
	READ_VALUE(NEURAL_WEB->NEURON_COUNT);
	READ_VALUE(NEURAL_WEB->AREA_COUNT);
	if (
		NEURAL_WEB->NEURON_COUNT < 0 ||
		NEURAL_WEB->NEURON_COUNT > (1 << 24) ||
		NEURAL_WEB->AREA_COUNT != 2 * SAVED_CONFIG.LAYER_COUNT + 1 ||
		NEURAL_WEB->WORD_COUNT < 0 ||
		NEURAL_WEB->WORD_COUNT > SAVED_CONFIG.MAXIMUM_WORDS
	)
		goto READ_FAILED;

	NEURAL_WEB->NEURON_CAPACITY = NEURAL_WEB->NEURON_COUNT + 16;
	NEURAL_WEB->NEURONS =
		ZERO_ALLOCATE(NEURAL_WEB->NEURON_CAPACITY * sizeof(NEURON));

	if (
		fread(
			NEURAL_WEB->NEURONS, sizeof(NEURON), NEURAL_WEB->NEURON_COUNT,
			STREAM
		) != (size_t)NEURAL_WEB->NEURON_COUNT
	)
		goto READ_FAILED;

	NEURAL_WEB->AREAS = ZERO_ALLOCATE(NEURAL_WEB->AREA_COUNT * sizeof(AREA));

	int	INDEX;

	for (INDEX = 0; INDEX < NEURAL_WEB->AREA_COUNT; INDEX++)
	{
		AREA	*CURRENT_AREA = &NEURAL_WEB->AREAS[INDEX];
		READ_VALUE(CURRENT_AREA->KIND);
		READ_VALUE(CURRENT_AREA->INDEX);
		READ_VALUE(CURRENT_AREA->NORM_NEURON);
		READ_VALUE(CURRENT_AREA->ERROR_LEVEL);
		READ_VALUE(CURRENT_AREA->ERROR_SLOW);
		READ_VALUE(CURRENT_AREA->ERROR_BEST);
		READ_VALUE(CURRENT_AREA->LAST_GROWTH);
		READ_VALUE(CURRENT_AREA->GROWN_COUNT);
		READ_VALUE(CURRENT_AREA->MEMBER_COUNT);
		if (
			CURRENT_AREA->MEMBER_COUNT < 0 ||
			CURRENT_AREA->MEMBER_COUNT > NEURAL_WEB->NEURON_COUNT
		)
			goto READ_FAILED;

		CURRENT_AREA->MEMBER_CAPACITY = CURRENT_AREA->MEMBER_COUNT + 64;
		CURRENT_AREA->MEMBERS =
			ZERO_ALLOCATE(CURRENT_AREA->MEMBER_CAPACITY * sizeof(int32_t));

		if (
			fread(
				CURRENT_AREA->MEMBERS, sizeof(int32_t),
				CURRENT_AREA->MEMBER_COUNT, STREAM
			) != (size_t)CURRENT_AREA->MEMBER_COUNT
		)
			goto READ_FAILED;
	}

	if (
		fread(
			NEURAL_WEB->NORM_IDS, sizeof(int32_t),
			2 * SAVED_CONFIG.LAYER_COUNT + 1, STREAM
		) != (size_t)(2 * SAVED_CONFIG.LAYER_COUNT + 1)
	)
		goto READ_FAILED;

	if (
		fread(
			NEURAL_WEB->WORD_NEURONS, sizeof(int32_t), NEURAL_WEB->WORD_COUNT,
			STREAM
		) != (size_t)NEURAL_WEB->WORD_COUNT
	)
		goto READ_FAILED;
	READ_VALUE(NEURAL_WEB->ENTRY_ID);
	READ_VALUE(NEURAL_WEB->EXIT_ID);
	READ_VALUE(NEURAL_WEB->UPDATE_START_ID);
	READ_VALUE(NEURAL_WEB->INFERENCE_GATE_ID);
	READ_VALUE(NEURAL_WEB->LOSS_ID);
	READ_VALUE(NEURAL_WEB->EMBEDDING_ID);
	READ_VALUE(NEURAL_WEB->GROW_ID);
	READ_VALUE(NEURAL_WEB->EVALUATION_GATE_ID);
	READ_VALUE(NEURAL_WEB->COPY_ID);
	READ_VALUE(NEURAL_WEB->ADAM_ID);
	int64_t	PARAMETERS_USED;
	int64_t	ACTIVATIONS_USED;
	int64_t	TRAINING_USED;
	READ_VALUE(PARAMETERS_USED);
	READ_VALUE(ACTIVATIONS_USED);
	READ_VALUE(TRAINING_USED);
	if (
		PARAMETERS_USED < 0 ||
		PARAMETERS_USED > WORD_PLANE_OFFSET ||
		ACTIVATIONS_USED < 0 ||
		ACTIVATIONS_USED > TRAINING_REGION_OFFSET ||
		TRAINING_USED < 0 ||
		TRAINING_USED > LOGITS_OFFSET - TRAINING_REGION_OFFSET
	)
		goto READ_FAILED;

	NEURAL_WEB->PARAMETER_BYTES_USED = PARAMETERS_USED;
	NEURAL_WEB->ACTIVATION_BYTES_USED = ACTIVATIONS_USED;
	NEURAL_WEB->TRAINING_BYTES_USED = TRAINING_USED;
	NEURAL_WEB->KERNEL_STATE->WORD_COUNT = NEURAL_WEB->WORD_COUNT;
	WEB_COMMIT(NEURAL_WEB);
	READ_VALUE(NEURAL_WEB->TOKENS_OFFSET);
	READ_VALUE(NEURAL_WEB->TARGETS_OFFSET);
	READ_VALUE(NEURAL_WEB->LOSS_WEIGHTS_OFFSET);
	READ_VALUE(NEURAL_WEB->RESIDUAL_OFFSET);
	READ_VALUE(NEURAL_WEB->RESIDUAL_GRADIENT_OFFSET);
	READ_VALUE(NEURAL_WEB->NORMALIZED_OFFSET);
	READ_VALUE(NEURAL_WEB->NORMALIZED_GRADIENT_OFFSET);
	READ_VALUE(NEURAL_WEB->INVERSE_NORM_OFFSET);
	READ_VALUE(NEURAL_WEB->SOFTMAX_STATISTICS_OFFSET);
	READ_VALUE(NEURAL_WEB->TARGET_LOGIT_OFFSET);
	if (FILE_KERNEL_VERSION < 5)
	{
		int64_t	OLD_TRAINING_BASE;

		if (FILE_KERNEL_VERSION < 3)
			OLD_TRAINING_BASE =
				ACTIVATION_PLANE_VERSION2 + TRAINING_REGION_VERSION2;
		else
			OLD_TRAINING_BASE =
				ACTIVATION_PLANE_VERSION4 + TRAINING_REGION_VERSION4;

		int64_t	*OFFSET_FIELDS[6] = {
			&NEURAL_WEB->TARGETS_OFFSET, &NEURAL_WEB->LOSS_WEIGHTS_OFFSET,
			&NEURAL_WEB->RESIDUAL_GRADIENT_OFFSET,
			&NEURAL_WEB->NORMALIZED_GRADIENT_OFFSET,
			&NEURAL_WEB->SOFTMAX_STATISTICS_OFFSET,
			&NEURAL_WEB->TARGET_LOGIT_OFFSET
		};
		int		INDEX;

		for (INDEX = 0; INDEX < 6; INDEX++)
			if (*OFFSET_FIELDS[INDEX] >= OLD_TRAINING_BASE)
				*OFFSET_FIELDS[INDEX] = *OFFSET_FIELDS[INDEX] -
					OLD_TRAINING_BASE + ACTIVATION_PLANE +
					TRAINING_REGION_OFFSET;
	}
	READ_VALUE(NEURAL_WEB->KERNEL_STATE->LEARNING_RATE);
	READ_VALUE(NEURAL_WEB->KERNEL_STATE->WEIGHT_DECAY);
	READ_VALUE(NEURAL_WEB->GROWTH_STATE);
	if (IS_VERSION_5)
		READ_VALUE(NEURAL_WEB->WORD_LIMIT);

	if (FILE_KERNEL_VERSION >= 5)
	{
		READ_VALUE(NEURAL_WEB->KERNEL_STATE->NORM_EPSILON);
		int32_t	RECIPE_COUNT;
		READ_VALUE(RECIPE_COUNT);
		if (RECIPE_COUNT < 0 || RECIPE_COUNT > 4096)
			goto READ_FAILED;

		int	INDEX;

		for (INDEX = 0; INDEX < RECIPE_COUNT; INDEX++)
		{
			int32_t	RECIPE_LENGTH;
			READ_VALUE(RECIPE_LENGTH);
			if (RECIPE_LENGTH <= 0 || RECIPE_LENGTH > (1 << 20))
				goto READ_FAILED;

			char	*RECIPE_SOURCE = malloc(RECIPE_LENGTH + 1);
			char	ERROR_MESSAGE[200];

			if (
				fread(RECIPE_SOURCE, 1, RECIPE_LENGTH, STREAM) !=
					(size_t)RECIPE_LENGTH
			)
			{
				free(RECIPE_SOURCE);
				goto READ_FAILED;
			}

			RECIPE_SOURCE[RECIPE_LENGTH] = 0;

			int	RECIPE_ID = WEB_RECIPE_ADD(
				NEURAL_WEB, RECIPE_SOURCE, ERROR_MESSAGE, sizeof ERROR_MESSAGE
			);

			free(RECIPE_SOURCE);

			if (RECIPE_ID != INDEX)
			{
				fprintf(stderr, "recipe %d: %s\n", INDEX, ERROR_MESSAGE);
				goto READ_FAILED;
			}
		}
	}

	int32_t	LIVE_PIECE_COUNT;
	READ_VALUE(LIVE_PIECE_COUNT);
	int32_t	PIECE_NUMBER;

	for (PIECE_NUMBER = 0; PIECE_NUMBER < LIVE_PIECE_COUNT; PIECE_NUMBER++)
	{
		int32_t	PIECE_ID;
		int32_t	CODE_LENGTH;
		int32_t	PIECE_TAIL;
		int32_t	NEXT_PIECE;
		int32_t	RELOCATION_COUNT;
		int32_t	PIECE_GROUP;
		READ_VALUE(PIECE_ID);
		READ_VALUE(CODE_LENGTH);
		READ_VALUE(PIECE_TAIL);
		READ_VALUE(NEXT_PIECE);
		READ_VALUE(RELOCATION_COUNT);
		READ_VALUE(PIECE_GROUP);
		if (
			PIECE_ID < 0 ||
			PIECE_ID / 4 >= NEURAL_WEB->NEURON_COUNT ||
			CODE_LENGTH < 0 ||
			CODE_LENGTH > (1 << 24) ||
			RELOCATION_COUNT < 0 ||
			RELOCATION_COUNT > 1024
		)
			goto READ_FAILED;

		int32_t	*RELOCATION_POSITIONS =
			malloc((RELOCATION_COUNT + 1) * sizeof(int32_t));
		int32_t	*RELOCATION_TARGETS =
			malloc((RELOCATION_COUNT + 1) * sizeof(int32_t));
		uint8_t	*CODE_BYTES = malloc(CODE_LENGTH + 1);
		int		READ_SUCCESS =
			fread(
				RELOCATION_POSITIONS, sizeof(int32_t), RELOCATION_COUNT, STREAM
			) == (size_t)RELOCATION_COUNT &&
			fread(
				RELOCATION_TARGETS, sizeof(int32_t), RELOCATION_COUNT, STREAM
			) == (size_t)RELOCATION_COUNT &&
			fread(CODE_BYTES, 1, CODE_LENGTH, STREAM) == (size_t)CODE_LENGTH;

		if (READ_SUCCESS && !PLAY_ONLY)
		{
			int32_t	PIECE_SLOT = PLACE_CODE(
				NEURAL_WEB, PIECE_ID, PIECE_GROUP, CODE_BYTES, CODE_LENGTH,
				PIECE_TAIL, RELOCATION_COUNT, RELOCATION_POSITIONS,
				RELOCATION_TARGETS
			);

			NEURAL_WEB->PIECES[PIECE_SLOT].NEXT_ID = NEXT_PIECE;
		}

		free(RELOCATION_POSITIONS);
		free(RELOCATION_TARGETS);
		free(CODE_BYTES);

		if (!READ_SUCCESS)
			goto READ_FAILED;
	}

	if (!PLAY_ONLY)
		PATCH_ALL_JUMPS(NEURAL_WEB);

	uint8_t	HALF_PRECISION;
	READ_VALUE(HALF_PRECISION);
	if (PLAY_ONLY)
	{
		NEURAL_WEB->HALF_PRECISION = 1;
		WEB_COMMIT(NEURAL_WEB);

		if (READ_PLANE_PLAY(NEURAL_WEB, STREAM, HALF_PRECISION))
			goto READ_FAILED;

		fclose(STREAM);
		NEURAL_WEB->HALF_PRECISION = 1;
		WEB_RECOMPILE(NEURAL_WEB);
		return (NEURAL_WEB);
	}

	if (READ_PLANE(NEURAL_WEB, STREAM, 0, HALF_PRECISION))
		goto READ_FAILED;

	fclose(STREAM);

	if (FILE_KERNEL_VERSION != KERNEL_VERSION)
		WEB_RECOMPILE(NEURAL_WEB);

	return (NEURAL_WEB);

READ_FAILED:
	fclose(STREAM);

	if (NEURAL_WEB)
		WEB_FREE(NEURAL_WEB);

	fprintf(stderr, "cannot load %s\n", PATH);

	return (NULL);
}

static WEB
	*LOAD_VERSION3(FILE *STREAM, const char *PATH, int IS_VERSION_3)
{
	CONFIG		SAVED_CONFIG;
	int32_t		WORD_COUNT;
	int32_t		NEURON_COUNT;
	int32_t		AREA_COUNT;
	uint64_t	RANDOM_STATE;
	int64_t		STEP_COUNT;
	NEURON		*OLD_NEURONS = NULL;
	AREA		*OLD_AREAS = NULL;
	WEB			*NEURAL_WEB = NULL;
	float		**PARAMETER_ARRAYS = NULL;
	READ_VALUE(SAVED_CONFIG);
	READ_VALUE(WORD_COUNT);
	READ_VALUE(RANDOM_STATE);
	READ_VALUE(STEP_COUNT);
	READ_VALUE(NEURON_COUNT);
	READ_VALUE(AREA_COUNT);
	if (
		!CHECK_CONFIG(SAVED_CONFIG) ||
		NEURON_COUNT < 0 ||
		NEURON_COUNT > (1 << 24) ||
		AREA_COUNT != 2 * SAVED_CONFIG.LAYER_COUNT + 1
	)
		goto READ_FAILED;

	OLD_NEURONS = ZERO_ALLOCATE(NEURON_COUNT * sizeof(NEURON));

	if (
		fread(OLD_NEURONS, sizeof(NEURON), NEURON_COUNT, STREAM) !=
			(size_t)NEURON_COUNT
	)
		goto READ_FAILED;

	OLD_AREAS = ZERO_ALLOCATE(AREA_COUNT * sizeof(AREA));

	int	INDEX;

	for (INDEX = 0; INDEX < AREA_COUNT; INDEX++)
	{
		AREA	*CURRENT_AREA = &OLD_AREAS[INDEX];
		READ_VALUE(CURRENT_AREA->KIND);
		READ_VALUE(CURRENT_AREA->INDEX);
		READ_VALUE(CURRENT_AREA->NORM_NEURON);
		READ_VALUE(CURRENT_AREA->ERROR_LEVEL);
		READ_VALUE(CURRENT_AREA->ERROR_SLOW);
		READ_VALUE(CURRENT_AREA->ERROR_BEST);
		READ_VALUE(CURRENT_AREA->LAST_GROWTH);
		READ_VALUE(CURRENT_AREA->GROWN_COUNT);
		READ_VALUE(CURRENT_AREA->MEMBER_COUNT);
		int32_t	*TEMPORARY = malloc((CURRENT_AREA->MEMBER_COUNT + 1) * 4);
		size_t	READ_COUNT =
			fread(TEMPORARY, 4, CURRENT_AREA->MEMBER_COUNT, STREAM);

		free(TEMPORARY);

		if (READ_COUNT != (size_t)CURRENT_AREA->MEMBER_COUNT)
			goto READ_FAILED;
	}

	int32_t	*SKIP_BUFFER = malloc(
		(size_t)(2 * SAVED_CONFIG.LAYER_COUNT + 1 + WORD_COUNT + 16) * 4
	);
	int		READ_SUCCESS =
		fread(SKIP_BUFFER, 4, 2 * SAVED_CONFIG.LAYER_COUNT + 1, STREAM) ==
			(size_t)(2 * SAVED_CONFIG.LAYER_COUNT + 1) &&
		fread(SKIP_BUFFER, 4, WORD_COUNT, STREAM) == (size_t)WORD_COUNT;

	free(SKIP_BUFFER);

	if (!READ_SUCCESS)
		goto READ_FAILED;

	int32_t	SPECIAL_IDS[9];

	for (INDEX = 0; INDEX < 8; INDEX++)
		READ_VALUE(SPECIAL_IDS[INDEX]);

	SPECIAL_IDS[8] = -1;

	if (IS_VERSION_3)
		READ_VALUE(SPECIAL_IDS[8]);

	int64_t	WORD_BASE;
	int64_t	WORD_STRIDE;
	int64_t	PARAMETERS_USED;
	int64_t	ACTIVATIONS_USED;
	int64_t	ACTIVATION_OFFSETS[16];
	READ_VALUE(WORD_BASE);
	READ_VALUE(WORD_STRIDE);
	READ_VALUE(PARAMETERS_USED);
	READ_VALUE(ACTIVATIONS_USED);
	for (INDEX = 0; INDEX < 16; INDEX++)
		READ_VALUE(ACTIVATION_OFFSETS[INDEX]);

	float	LEARNING_RATE;
	float	WEIGHT_DECAY;
	GROWTH	GROWTH_STATE;
	READ_VALUE(LEARNING_RATE);
	READ_VALUE(WEIGHT_DECAY);
	READ_VALUE(GROWTH_STATE);
	int32_t	LIVE_PIECE_COUNT;
	READ_VALUE(LIVE_PIECE_COUNT);
	int32_t	NEURON_INDEX;

	for (NEURON_INDEX = 0; NEURON_INDEX < LIVE_PIECE_COUNT; NEURON_INDEX++)
	{
		int32_t	PIECE_ID;
		int32_t	CODE_LENGTH;
		int32_t	PIECE_TAIL;
		int32_t	NEXT_PIECE;
		int32_t	RELOCATION_COUNT;
		READ_VALUE(PIECE_ID);
		READ_VALUE(CODE_LENGTH);
		READ_VALUE(PIECE_TAIL);
		READ_VALUE(NEXT_PIECE);
		READ_VALUE(RELOCATION_COUNT);
		if (fseek(STREAM, (long)RELOCATION_COUNT * 8 + CODE_LENGTH, SEEK_CUR))
			goto READ_FAILED;
	}

	PARAMETER_ARRAYS = ZERO_ALLOCATE(NEURON_COUNT * sizeof(float *));

	for (NEURON_INDEX = 0; NEURON_INDEX < NEURON_COUNT; NEURON_INDEX++)
	{
		if (!OLD_NEURONS[NEURON_INDEX].PARAMETER_COUNT)
			continue ;

		PARAMETER_ARRAYS[NEURON_INDEX] = malloc(
			OLD_NEURONS[NEURON_INDEX].PARAMETER_COUNT * 3 * sizeof(float)
		);

		if (
			fread(
				PARAMETER_ARRAYS[NEURON_INDEX], sizeof(float),
				OLD_NEURONS[NEURON_INDEX].PARAMETER_COUNT * 3, STREAM
			) != (size_t)(OLD_NEURONS[NEURON_INDEX].PARAMETER_COUNT * 3)
		)
			goto READ_FAILED;
	}

	fclose(STREAM);
	STREAM = NULL;
	NEURAL_WEB = WEB_NEW_EMPTY(SAVED_CONFIG, RANDOM_STATE);
	WEB_SET_OPTIMIZER(NEURAL_WEB, 1);
	NEURAL_WEB->STEP = STEP_COUNT;
	NEURAL_WEB->KERNEL_STATE->LEARNING_RATE = LEARNING_RATE;
	NEURAL_WEB->KERNEL_STATE->WEIGHT_DECAY = WEIGHT_DECAY;
	NEURAL_WEB->GROWTH_STATE = GROWTH_STATE;

	int	AREA_INDEX;

	for (AREA_INDEX = 0; AREA_INDEX < AREA_COUNT; AREA_INDEX++)
	{
		NEURAL_WEB->AREAS[AREA_INDEX].ERROR_LEVEL =
			OLD_AREAS[AREA_INDEX].ERROR_LEVEL;
		NEURAL_WEB->AREAS[AREA_INDEX].ERROR_SLOW =
			OLD_AREAS[AREA_INDEX].ERROR_SLOW;
		NEURAL_WEB->AREAS[AREA_INDEX].ERROR_BEST =
			OLD_AREAS[AREA_INDEX].ERROR_BEST;
		NEURAL_WEB->AREAS[AREA_INDEX].LAST_GROWTH =
			OLD_AREAS[AREA_INDEX].LAST_GROWTH;
		NEURAL_WEB->AREAS[AREA_INDEX].GROWN_COUNT =
			OLD_AREAS[AREA_INDEX].GROWN_COUNT;
	}

	int32_t	*WORD_ORDER = malloc((WORD_COUNT + 1) * 4);

	for (NEURON_INDEX = 0; NEURON_INDEX < NEURON_COUNT; NEURON_INDEX++)
		if (
			OLD_NEURONS[NEURON_INDEX].KIND == KIND_WORD &&
			OLD_NEURONS[NEURON_INDEX].KIND_DETAIL >= 0 &&
			OLD_NEURONS[NEURON_INDEX].KIND_DETAIL < WORD_COUNT
		)
			WORD_ORDER[OLD_NEURONS[NEURON_INDEX].KIND_DETAIL] = NEURON_INDEX;

	for (NEURON_INDEX = 0; NEURON_INDEX < NEURON_COUNT; NEURON_INDEX++)
	{
		NEURON	*OLD_NEURON = &OLD_NEURONS[NEURON_INDEX];
		int32_t	NEW_NEURON_ID = -1;

		if (!OLD_NEURON->ALIVE || !OLD_NEURON->PARAMETER_COUNT)
			continue ;

		if (
			OLD_NEURON->KIND == KIND_FEED_FORWARD ||
			OLD_NEURON->KIND == KIND_ATTENTION_HEAD
		)
			NEW_NEURON_ID = WEB_ADD_NEURON(
				NEURAL_WEB, OLD_NEURON->KIND, OLD_NEURON->AREA_INDEX,
				OLD_NEURON->BIRTH_REASON, -1
			);
		else if (OLD_NEURON->KIND == KIND_EMBEDDING)
			NEW_NEURON_ID = NEURAL_WEB->EMBEDDING_ID;
		else if (OLD_NEURON->KIND == KIND_NORMALIZATION)
			NEW_NEURON_ID = NEURAL_WEB->NORM_IDS[OLD_NEURON->AREA_INDEX];
		else if (OLD_NEURON->KIND == KIND_COPY)
		{
			if (STEP_COUNT > 0)
				NEURAL_WEB->STEP = STEP_COUNT;
			else
				NEURAL_WEB->STEP = 1;

			NEW_NEURON_ID = WEB_ADD_COPY(NEURAL_WEB);
		}
		else
			continue ;

		NEURON	*NEW_NEURON = &NEURAL_WEB->NEURONS[NEW_NEURON_ID];

		memcpy(
			NEURON_PARAMETERS(NEURAL_WEB, NEW_NEURON_ID),
			PARAMETER_ARRAYS[NEURON_INDEX], NEW_NEURON->PARAMETER_COUNT * 4
		);
		memcpy(
			NEURON_MOMENTS(NEURAL_WEB, NEW_NEURON_ID, 0),
			PARAMETER_ARRAYS[NEURON_INDEX] + NEW_NEURON->PARAMETER_COUNT,
			NEW_NEURON->PARAMETER_COUNT * 4
		);
		memcpy(
			NEURON_MOMENTS(NEURAL_WEB, NEW_NEURON_ID, 1),
			PARAMETER_ARRAYS[NEURON_INDEX] + 2 * NEW_NEURON->PARAMETER_COUNT,
			NEW_NEURON->PARAMETER_COUNT * 4
		);
		NEW_NEURON->BIRTH_STEP = OLD_NEURON->BIRTH_STEP;
		NEW_NEURON->BIRTH_ERROR = OLD_NEURON->BIRTH_ERROR;
		NEW_NEURON->BIRTH_REASON = OLD_NEURON->BIRTH_REASON;
	}

	int32_t	WORD_INDEX;

	for (WORD_INDEX = 0; WORD_INDEX < WORD_COUNT; WORD_INDEX++)
	{
		NEURON	*OLD_NEURON = &OLD_NEURONS[WORD_ORDER[WORD_INDEX]];
		int		NEW_WORD = WEB_ADD_WORD(NEURAL_WEB);
		int32_t	NEW_NEURON_ID = NEURAL_WEB->WORD_NEURONS[NEW_WORD];

		memcpy(
			NEURON_PARAMETERS(NEURAL_WEB, NEW_NEURON_ID),
			PARAMETER_ARRAYS[WORD_ORDER[WORD_INDEX]],
			OLD_NEURON->PARAMETER_COUNT * 4
		);
		memcpy(
			NEURON_MOMENTS(NEURAL_WEB, NEW_NEURON_ID, 0),
			PARAMETER_ARRAYS[WORD_ORDER[WORD_INDEX]] +
				OLD_NEURON->PARAMETER_COUNT,
			OLD_NEURON->PARAMETER_COUNT * 4
		);
		memcpy(
			NEURON_MOMENTS(NEURAL_WEB, NEW_NEURON_ID, 1),
			PARAMETER_ARRAYS[WORD_ORDER[WORD_INDEX]] +
				2 * OLD_NEURON->PARAMETER_COUNT,
			OLD_NEURON->PARAMETER_COUNT * 4
		);
		NEURAL_WEB->NEURONS[NEW_NEURON_ID].BIRTH_REASON =
			OLD_NEURON->BIRTH_REASON;
		NEURAL_WEB->NEURONS[NEW_NEURON_ID].BIRTH_STEP = OLD_NEURON->BIRTH_STEP;
	}

	NEURAL_WEB->STEP = STEP_COUNT;
	WEB_RELINK(NEURAL_WEB);
	free(WORD_ORDER);

	for (NEURON_INDEX = 0; NEURON_INDEX < NEURON_COUNT; NEURON_INDEX++)
		free(PARAMETER_ARRAYS[NEURON_INDEX]);

	free(PARAMETER_ARRAYS);
	free(OLD_NEURONS);
	free(OLD_AREAS);
	NEURAL_WEB->OPTIMIZER_LOADED = 1;
	return (NEURAL_WEB);

READ_FAILED:
	if (STREAM)
		fclose(STREAM);

	free(OLD_NEURONS);
	free(OLD_AREAS);

	if (PARAMETER_ARRAYS)
	{
		int32_t	NEURON_INDEX;

		for (NEURON_INDEX = 0; NEURON_INDEX < NEURON_COUNT; NEURON_INDEX++)
			free(PARAMETER_ARRAYS[NEURON_INDEX]);

		free(PARAMETER_ARRAYS);
	}

	if (NEURAL_WEB)
		WEB_FREE(NEURAL_WEB);

	fprintf(stderr, "cannot convert %s\n", PATH);

	return (NULL);
}

int
	WEB_PRUNE_WORDS(
		WEB *NEURAL_WEB, const uint8_t *KEEP_FLAGS, int32_t *NEW_INDEX
	)
{
	int32_t	KEPT_COUNT = 0;
	int		WORD_AREA_INDEX = 2 * NEURAL_WEB->CONFIGURATION.LAYER_COUNT;
	int32_t	WORD_INDEX;

	for (WORD_INDEX = 0; WORD_INDEX < NEURAL_WEB->WORD_COUNT; WORD_INDEX++)
	{
		int32_t	NEURON_ID = NEURAL_WEB->WORD_NEURONS[WORD_INDEX];
		NEURON	*WORD_NEURON = &NEURAL_WEB->NEURONS[NEURON_ID];

		if (!KEEP_FLAGS[WORD_INDEX])
		{
			NEW_INDEX[WORD_INDEX] = -1;
			WORD_NEURON->ALIVE = 0;

			int	PIECE_ROLE;

			for (PIECE_ROLE = 0; PIECE_ROLE < 3; PIECE_ROLE++)
				if (WORD_NEURON->PIECE_IDS[PIECE_ROLE] >= 0)
				{
					int32_t	PIECE_SLOT = PIECE_INDEX(
						NEURAL_WEB, WORD_NEURON->PIECE_IDS[PIECE_ROLE]
					);

					if (PIECE_SLOT >= 0)
						CODE_FREE(NEURAL_WEB, &NEURAL_WEB->PIECES[PIECE_SLOT]);
				}

			continue ;
		}

		NEW_INDEX[WORD_INDEX] = KEPT_COUNT;

		if (KEPT_COUNT != WORD_INDEX)
		{
			int	PLANE_NUMBER;

			for (PLANE_NUMBER = 0; PLANE_NUMBER < 4; PLANE_NUMBER++)
			{
				if (PLANE_NUMBER == 1 && !NEURAL_WEB->TRAINING_ENABLED)
					continue ;

				if (PLANE_NUMBER >= 2 && !NEURAL_WEB->OPTIMIZER_ENABLED)
					continue ;

				uint8_t	*PLANE_BASE = (uint8_t *)NEURAL_WEB->PARAMETERS +
					PLANE_NUMBER * PARAMETER_PLANE + WORD_PLANE_OFFSET;

				memmove(
					PLANE_BASE + (int64_t)KEPT_COUNT * NEURAL_WEB->WORD_STRIDE,
					PLANE_BASE + (int64_t)WORD_INDEX * NEURAL_WEB->WORD_STRIDE,
					NEURAL_WEB->WORD_STRIDE
				);
			}

			WORD_NEURON->KIND_DETAIL = KEPT_COUNT;
			WORD_NEURON->PARAMETER_OFFSET = WORD_PLANE_OFFSET +
				(int64_t)KEPT_COUNT * NEURAL_WEB->WORD_STRIDE;
		}

		NEURAL_WEB->WORD_NEURONS[KEPT_COUNT] = NEURON_ID;
		KEPT_COUNT++;
	}

	int32_t	OLD_WORD_COUNT = NEURAL_WEB->WORD_COUNT;

	for (WORD_INDEX = KEPT_COUNT; WORD_INDEX < OLD_WORD_COUNT; WORD_INDEX++)
		ZERO_PLANES(
			NEURAL_WEB,
			WORD_PLANE_OFFSET + (int64_t)WORD_INDEX * NEURAL_WEB->WORD_STRIDE,
			NEURAL_WEB->WORD_STRIDE
		);

	AREA	*WORD_AREA = &NEURAL_WEB->AREAS[WORD_AREA_INDEX];
	int		WRITE_INDEX = 0;
	int		LIST_INDEX;

	for (LIST_INDEX = 0; LIST_INDEX < WORD_AREA->MEMBER_COUNT; LIST_INDEX++)
		if (NEURAL_WEB->NEURONS[WORD_AREA->MEMBERS[LIST_INDEX]].ALIVE)
			WORD_AREA->MEMBERS[WRITE_INDEX++] = WORD_AREA->MEMBERS[LIST_INDEX];

	WORD_AREA->MEMBER_COUNT = WRITE_INDEX;
	NEURAL_WEB->WORD_COUNT = KEPT_COUNT;
	NEURAL_WEB->KERNEL_STATE->WORD_COUNT = KEPT_COUNT;

	for (WORD_INDEX = 0; WORD_INDEX < KEPT_COUNT; WORD_INDEX++)
	{
		int32_t	NEURON_ID = NEURAL_WEB->WORD_NEURONS[WORD_INDEX];
		int		PIECE_ROLE;

		for (PIECE_ROLE = 0; PIECE_ROLE < 2; PIECE_ROLE++)
			COMPILE_PIECE(NEURAL_WEB, NEURON_ID, PIECE_ROLE);
	}

	WEB_RELINK(NEURAL_WEB);

	return (KEPT_COUNT);
}

REPLICA
	*REPLICA_NEW(WEB *NEURAL_WEB)
{
	REPLICA	*REPLICA_STATE = ZERO_ALLOCATE(sizeof(REPLICA));

	REPLICA_STATE->KERNEL_STATE_MEMORY =
		ZERO_ALLOCATE(sizeof(KERNEL_CONTEXT) + 64);
	REPLICA_STATE->KERNEL_STATE =
		(KERNEL_CONTEXT *)ALIGN_64_BYTES(REPLICA_STATE->KERNEL_STATE_MEMORY);
	SPACE_INITIALIZE(&REPLICA_STATE->PARAMETER_SPACE, 2 * PARAMETER_PLANE);
	SPACE_INITIALIZE(&REPLICA_STATE->ACTIVATION_SPACE, 2 * ACTIVATION_PLANE);
	REPLICA_STATE->PARAMETERS = (float *)REPLICA_STATE->PARAMETER_SPACE.BASE;
	REPLICA_STATE->ACTIVATIONS = REPLICA_STATE->ACTIVATION_SPACE.BASE;
	REPLICA_SYNCHRONIZE(NEURAL_WEB, REPLICA_STATE);

	return (REPLICA_STATE);
}

void
	REPLICA_FREE(REPLICA *REPLICA_STATE)
{
	if (!REPLICA_STATE)
		return ;

	VIRTUAL_RELEASE(
		REPLICA_STATE->PARAMETER_SPACE.BASE,
		REPLICA_STATE->PARAMETER_SPACE.RESERVED_BYTES
	);
	VIRTUAL_RELEASE(
		REPLICA_STATE->ACTIVATION_SPACE.BASE,
		REPLICA_STATE->ACTIVATION_SPACE.RESERVED_BYTES
	);
	free(REPLICA_STATE->KERNEL_STATE_MEMORY);
	free(REPLICA_STATE);
}

static void
	REPLICA_COMMIT(WEB *NEURAL_WEB, REPLICA *REPLICA_STATE)
{
	COMMIT_SPACES(
		NEURAL_WEB, &REPLICA_STATE->PARAMETER_SPACE,
		&REPLICA_STATE->ACTIVATION_SPACE, 1, 0
	);
}

void
	REPLICA_PREPARE(WEB *NEURAL_WEB, REPLICA *REPLICA_STATE)
{
	REPLICA_COMMIT(NEURAL_WEB, REPLICA_STATE);
	*REPLICA_STATE->KERNEL_STATE = *NEURAL_WEB->KERNEL_STATE;
	REPLICA_STATE->KERNEL_STATE->ACTIVATIONS = REPLICA_STATE->ACTIVATIONS;
	REPLICA_STATE->KERNEL_STATE->PARAMETERS = REPLICA_STATE->PARAMETERS;
}

void
	REPLICA_SYNCHRONIZE(WEB *NEURAL_WEB, REPLICA *REPLICA_STATE)
{
	REPLICA_COMMIT(NEURAL_WEB, REPLICA_STATE);
	memcpy(
		REPLICA_STATE->PARAMETERS, NEURAL_WEB->PARAMETERS,
		NEURAL_WEB->PARAMETER_BYTES_USED
	);
	memcpy(
		(uint8_t *)REPLICA_STATE->PARAMETERS + WORD_PLANE_OFFSET,
		(uint8_t *)NEURAL_WEB->PARAMETERS + WORD_PLANE_OFFSET,
		(int64_t)NEURAL_WEB->WORD_COUNT * NEURAL_WEB->WORD_STRIDE
	);
	*REPLICA_STATE->KERNEL_STATE = *NEURAL_WEB->KERNEL_STATE;
	REPLICA_STATE->KERNEL_STATE->ACTIVATIONS = REPLICA_STATE->ACTIVATIONS;
	REPLICA_STATE->KERNEL_STATE->PARAMETERS = REPLICA_STATE->PARAMETERS;
}

static void
	SLICE_RANGE(
		int64_t TOTAL_SIZE, int PART_INDEX, int PART_COUNT,
		int64_t *RANGE_START, int64_t *RANGE_END
	)
{
	int64_t	CHUNK_SIZE = (TOTAL_SIZE / 32 + PART_COUNT - 1) / PART_COUNT * 32;

	if (CHUNK_SIZE * PART_INDEX < TOTAL_SIZE)
		*RANGE_START = CHUNK_SIZE * PART_INDEX;
	else
		*RANGE_START = TOTAL_SIZE;

	if (CHUNK_SIZE * (PART_INDEX + 1) < TOTAL_SIZE)
		*RANGE_END = CHUNK_SIZE * (PART_INDEX + 1);
	else
		*RANGE_END = TOTAL_SIZE;
}

void
	REPLICA_SYNCHRONIZE_RANGE(
		WEB *NEURAL_WEB, REPLICA **REPLICAS, int REPLICA_COUNT, int PART_INDEX,
		int PART_COUNT
	)
{
	int64_t	RANGES[2][2] = {
		{ 0, NEURAL_WEB->PARAMETER_BYTES_USED },
		{
			WORD_PLANE_OFFSET,
			(int64_t)NEURAL_WEB->WORD_COUNT * NEURAL_WEB->WORD_STRIDE
		}
	};
	int		RANGE_INDEX;

	for (RANGE_INDEX = 0; RANGE_INDEX < 2; RANGE_INDEX++)
	{
		int64_t	RANGE_START;
		int64_t	RANGE_END;

		SLICE_RANGE(
			RANGES[RANGE_INDEX][1], PART_INDEX, PART_COUNT, &RANGE_START,
			&RANGE_END
		);

		int	REPLICA_INDEX;

		for (REPLICA_INDEX = 1; REPLICA_INDEX < REPLICA_COUNT; REPLICA_INDEX++)
			memcpy(
				(uint8_t *)REPLICAS[REPLICA_INDEX]->PARAMETERS +
					RANGES[RANGE_INDEX][0] + RANGE_START,
				(uint8_t *)NEURAL_WEB->PARAMETERS + RANGES[RANGE_INDEX][0] +
					RANGE_START,
				RANGE_END - RANGE_START
			);
	}
}

void
	REPLICA_REDUCE_RANGE(
		WEB *NEURAL_WEB, REPLICA **REPLICAS, int REPLICA_COUNT, int PART_INDEX,
		int PART_COUNT
	)
{
	int64_t	RANGES[2][2] = {
		{ 0, NEURAL_WEB->PARAMETER_BYTES_USED },
		{
			WORD_PLANE_OFFSET,
			(int64_t)NEURAL_WEB->WORD_COUNT * NEURAL_WEB->WORD_STRIDE
		}
	};
	int		RANGE_INDEX;

	for (RANGE_INDEX = 0; RANGE_INDEX < 2; RANGE_INDEX++)
	{
		int64_t	RANGE_START;
		int64_t	RANGE_END;

		SLICE_RANGE(
			RANGES[RANGE_INDEX][1], PART_INDEX, PART_COUNT, &RANGE_START,
			&RANGE_END
		);

		float	*GRADIENT =
			(float *)((uint8_t *)NEURAL_WEB->PARAMETERS + PARAMETER_PLANE +
				RANGES[RANGE_INDEX][0] + RANGE_START);
		int64_t	VALUE_COUNT = (RANGE_END - RANGE_START) / 4;
		int		REPLICA_INDEX;

		for (REPLICA_INDEX = 1; REPLICA_INDEX < REPLICA_COUNT; REPLICA_INDEX++)
		{
			float	*REPLICA_GRADIENT =
				(float *)((uint8_t *)REPLICAS[REPLICA_INDEX]->PARAMETERS +
					PARAMETER_PLANE + RANGES[RANGE_INDEX][0] +
					RANGE_START);
			int64_t	VALUE_INDEX;

			for (VALUE_INDEX = 0; VALUE_INDEX < VALUE_COUNT; VALUE_INDEX++)
			{
				GRADIENT[VALUE_INDEX] += REPLICA_GRADIENT[VALUE_INDEX];
				REPLICA_GRADIENT[VALUE_INDEX] = 0;
			}
		}
	}
}

void
	COPY_HEAD_OFFSETS(WEB *NEURAL_WEB, int64_t *OFFSETS)
{
	int64_t	MAX_POSITIONS = NEURAL_WEB->CONFIGURATION.MAXIMUM_LENGTH;
	int64_t	HEAD_SIZE = NEURAL_WEB->CONFIGURATION.HEAD_DIMENSION;
	int64_t	COPY_BASE =
		NEURAL_WEB->NEURONS[NEURAL_WEB->COPY_ID].ACTIVATION_OFFSET;

	OFFSETS[0] = COPY_BASE;
	OFFSETS[1] = OFFSETS[0] + MAX_POSITIONS * HEAD_SIZE * 4;
	OFFSETS[2] = OFFSETS[1] + MAX_POSITIONS * HEAD_SIZE * 4;
	OFFSETS[3] = OFFSETS[2] + MAX_POSITIONS * MAX_POSITIONS * 4;

	int	OFFSET_INDEX;

	for (OFFSET_INDEX = 0; OFFSET_INDEX < 6; OFFSET_INDEX++)
		OFFSETS[4 + OFFSET_INDEX] = ACTIVATION_PLANE + COPY_BASE +
			2 * MAX_POSITIONS * HEAD_SIZE * 4 +
			OFFSET_INDEX * MAX_POSITIONS * 4;
}

int32_t
	WEB_ADD_COPY(WEB *NEURAL_WEB)
{
	if (NEURAL_WEB->COPY_ID >= 0)
		return (NEURAL_WEB->COPY_ID);

	NEURAL_WEB->COPY_ID = NEURAL_WEB->NEURON_COUNT;

	int32_t	COPY_NEURON_ID = WEB_ADD_NEURON(
		NEURAL_WEB, KIND_COPY, 2 * NEURAL_WEB->CONFIGURATION.LAYER_COUNT,
		NEURAL_WEB->STEP > 0 ? WHY_GROWTH : WHY_SEED, -1
	);

	NEURAL_WEB->COPY_ID = COPY_NEURON_ID;
	COMPILE_PIECE(NEURAL_WEB, NEURAL_WEB->LOSS_ID, 0);
	WEB_RELINK(NEURAL_WEB);

	return (COPY_NEURON_ID);
}

float
	WEB_LOSS_AT(WEB *NEURAL_WEB, uint8_t *ACTIVATIONS, int POSITION)
{
	int	MAX_POSITIONS = NEURAL_WEB->CONFIGURATION.MAXIMUM_LENGTH;

	if (NEURAL_WEB->COPY_ID >= 0)
	{
		int64_t	OFFSETS[10];

		COPY_HEAD_OFFSETS(NEURAL_WEB, OFFSETS);

		float	PROBABILITY = ((float *)(ACTIVATIONS + OFFSETS[5]))[POSITION];

		if (PROBABILITY > (float)1e-30)
			return (-logf(PROBABILITY));

		return ((float)69.0);
	}

	float	*LOG_SUM_EXP =
		(float *)(ACTIVATIONS + NEURAL_WEB->SOFTMAX_STATISTICS_OFFSET);
	float	*TARGET_LOGITS =
		(float *)(ACTIVATIONS + NEURAL_WEB->TARGET_LOGIT_OFFSET);

	return (
		logf(LOG_SUM_EXP[MAX_POSITIONS + POSITION]) + LOG_SUM_EXP[POSITION] -
			TARGET_LOGITS[POSITION]
	);
}

float
	*WEB_COPY_ATTENTION_ROW(WEB *NEURAL_WEB, uint8_t *ACTIVATIONS, int POSITION)
{
	int64_t	OFFSETS[10];

	COPY_HEAD_OFFSETS(NEURAL_WEB, OFFSETS);

	return (
		(float *)(ACTIVATIONS + OFFSETS[2]) +
			(NEURAL_WEB->HALF_PRECISION ? 0
										: (int64_t)POSITION *
				NEURAL_WEB->CONFIGURATION.MAXIMUM_LENGTH)
	);
}

enum
{
	WIDEN_COPY,
	WIDEN_READ,
	WIDEN_WRITE,
	WIDEN_NORM
};

typedef struct
{
	int64_t	OLD_OFFSET;
	int64_t	NEW_OFFSET;
	int64_t	OLD_LENGTH;
	int64_t	NEW_LENGTH;
	int		MODE;
} WIDEN_SEGMENT;

static int
	WIDEN_SEGMENTS(
		WEB *NEURAL_WEB, WEB *OLD_WEB, int NEURON_KIND, WIDEN_SEGMENT *SEGMENTS
	)
{
	int64_t	OLD_WIDTH = OLD_WEB->CONFIGURATION.DIMENSION;
	int64_t	NEW_WIDTH = NEURAL_WEB->CONFIGURATION.DIMENSION;
	int64_t	HEAD_SIZE = NEURAL_WEB->CONFIGURATION.HEAD_DIMENSION;
	int64_t	SEGMENT_COUNT = 0;

	switch (NEURON_KIND)
	{
		case KIND_NORMALIZATION:
		{
			SEGMENTS[SEGMENT_COUNT++] =
				(WIDEN_SEGMENT){ 0, 0, OLD_WIDTH, NEW_WIDTH, WIDEN_NORM };
		}
		break ;
		case KIND_FEED_FORWARD:
		{
			SEGMENTS[SEGMENT_COUNT++] =
				(WIDEN_SEGMENT){ 0, 0, OLD_WIDTH, NEW_WIDTH, WIDEN_READ };
			SEGMENTS[SEGMENT_COUNT++] = (WIDEN_SEGMENT
			){ OLD_WIDTH, NEW_WIDTH, OLD_WIDTH, NEW_WIDTH, WIDEN_WRITE };
			SEGMENTS[SEGMENT_COUNT++] = (WIDEN_SEGMENT
			){ 2 * OLD_WIDTH, 2 * NEW_WIDTH, 8, 8, WIDEN_COPY };
		}
		break ;
		case KIND_ATTENTION_HEAD:
		{
			int	MATRIX_INDEX;

			for (MATRIX_INDEX = 0; MATRIX_INDEX < 4; MATRIX_INDEX++)
			{
				int	ROW_INDEX;

				for (ROW_INDEX = 0; ROW_INDEX < HEAD_SIZE; ROW_INDEX++)
					SEGMENTS[SEGMENT_COUNT++] = (WIDEN_SEGMENT
					){ (MATRIX_INDEX * HEAD_SIZE + ROW_INDEX) * OLD_WIDTH,
						(MATRIX_INDEX * HEAD_SIZE + ROW_INDEX) * NEW_WIDTH,
						OLD_WIDTH, NEW_WIDTH,
						MATRIX_INDEX < 3 ? WIDEN_READ : WIDEN_WRITE };
			}
		}
		break ;
		case KIND_WORD:
		{
			SEGMENTS[SEGMENT_COUNT++] =
				(WIDEN_SEGMENT){ 0, 0, OLD_WIDTH, NEW_WIDTH, WIDEN_WRITE };
			SEGMENTS[SEGMENT_COUNT++] =
				(WIDEN_SEGMENT){ OLD_WIDTH, NEW_WIDTH, 8, 8, WIDEN_COPY };
		}
		break ;
		case KIND_COPY:
		{
			int	ROW_INDEX;

			for (ROW_INDEX = 0; ROW_INDEX < 2 * HEAD_SIZE; ROW_INDEX++)
				SEGMENTS[SEGMENT_COUNT++] = (WIDEN_SEGMENT
				){ ROW_INDEX * OLD_WIDTH, ROW_INDEX * NEW_WIDTH, OLD_WIDTH,
					NEW_WIDTH, WIDEN_READ };

			SEGMENTS[SEGMENT_COUNT++] = (WIDEN_SEGMENT
			){ 2 * HEAD_SIZE * OLD_WIDTH, 2 * HEAD_SIZE * NEW_WIDTH, OLD_WIDTH,
				NEW_WIDTH, WIDEN_READ };
			SEGMENTS[SEGMENT_COUNT++] = (WIDEN_SEGMENT
			){ 2 * HEAD_SIZE * OLD_WIDTH + OLD_WIDTH,
				2 * HEAD_SIZE * NEW_WIDTH + NEW_WIDTH, 8, 8, WIDEN_COPY };
		}
		break ;
		default:
		{
			return (0);
		}
	}

	return ((int)SEGMENT_COUNT);
}

static void
	COPY_NEURON(
		WEB *NEURAL_WEB, int32_t NEURON_ID, WEB *OLD_WEB, int32_t OLD_NEURON_ID,
		int COPY_MOMENTS
	)
{
	NEURON	*NEW_NEURON = &NEURAL_WEB->NEURONS[NEURON_ID];
	NEURON	*OLD_NEURON = &OLD_WEB->NEURONS[OLD_NEURON_ID];

	NEW_NEURON->BIRTH_STEP = OLD_NEURON->BIRTH_STEP;
	NEW_NEURON->BIRTH_ERROR = OLD_NEURON->BIRTH_ERROR;
	NEW_NEURON->BIRTH_REASON = OLD_NEURON->BIRTH_REASON;

	if (NEURAL_WEB->CONFIGURATION.DIMENSION == OLD_WEB->CONFIGURATION.DIMENSION)
	{
		int64_t	VALUE_COUNT;

		if (NEW_NEURON->PARAMETER_COUNT < OLD_NEURON->PARAMETER_COUNT)
			VALUE_COUNT = NEW_NEURON->PARAMETER_COUNT;
		else
			VALUE_COUNT = OLD_NEURON->PARAMETER_COUNT;

		memcpy(
			NEURON_PARAMETERS(NEURAL_WEB, NEURON_ID),
			NEURON_PARAMETERS(OLD_WEB, OLD_NEURON_ID), VALUE_COUNT * 4
		);

		if (COPY_MOMENTS)
		{
			int	MOMENT_INDEX;

			for (MOMENT_INDEX = 0; MOMENT_INDEX < 2; MOMENT_INDEX++)
				memcpy(
					NEURON_MOMENTS(NEURAL_WEB, NEURON_ID, MOMENT_INDEX),
					NEURON_MOMENTS(OLD_WEB, OLD_NEURON_ID, MOMENT_INDEX),
					VALUE_COUNT * 4
				);
		}

		return ;
	}

	static WIDEN_SEGMENT	SEGMENTS[256];
	int						SEGMENT_COUNT =
		WIDEN_SEGMENTS(NEURAL_WEB, OLD_WEB, NEW_NEURON->KIND, SEGMENTS);
	float					SCALE = sqrtf(
		(float)OLD_WEB->CONFIGURATION.DIMENSION /
		(float)NEURAL_WEB->CONFIGURATION.DIMENSION
	);
	float					*NEW_PARAMETERS =
		NEURON_PARAMETERS(NEURAL_WEB, NEURON_ID);
	float					*OLD_PARAMETERS =
		NEURON_PARAMETERS(OLD_WEB, OLD_NEURON_ID);
	int						SEGMENT_INDEX;

	for (SEGMENT_INDEX = 0; SEGMENT_INDEX < SEGMENT_COUNT; SEGMENT_INDEX++)
	{
		WIDEN_SEGMENT	CURRENT_SEGMENT = SEGMENTS[SEGMENT_INDEX];
		int64_t			VALUE_INDEX;

		for (
			VALUE_INDEX = 0;
			VALUE_INDEX < CURRENT_SEGMENT.NEW_LENGTH;
			VALUE_INDEX++
		)
		{
			float	NEW_VALUE;

			if (VALUE_INDEX < CURRENT_SEGMENT.OLD_LENGTH)
			{
				if (CURRENT_SEGMENT.MODE == WIDEN_NORM)
					NEW_VALUE = OLD_PARAMETERS
									[CURRENT_SEGMENT.OLD_OFFSET + VALUE_INDEX] *
						SCALE;
				else
					NEW_VALUE = OLD_PARAMETERS
						[CURRENT_SEGMENT.OLD_OFFSET + VALUE_INDEX];
			}
			else
			{
				if (CURRENT_SEGMENT.MODE == WIDEN_READ)
					NEW_VALUE = (float)0.02 * WEB_GAUSSIAN(NEURAL_WEB);
				else if (CURRENT_SEGMENT.MODE == WIDEN_NORM)
					NEW_VALUE = SCALE;
				else
					NEW_VALUE = (float)0.0;
			}

			NEW_PARAMETERS[CURRENT_SEGMENT.NEW_OFFSET + VALUE_INDEX] =
				NEW_VALUE;

			if (COPY_MOMENTS)
			{
				int	MOMENT_INDEX;

				for (MOMENT_INDEX = 0; MOMENT_INDEX < 2; MOMENT_INDEX++)
					NEURON_MOMENTS(NEURAL_WEB, NEURON_ID, MOMENT_INDEX)
					[CURRENT_SEGMENT.NEW_OFFSET + VALUE_INDEX] =
						VALUE_INDEX < CURRENT_SEGMENT.OLD_LENGTH
						? NEURON_MOMENTS(
							OLD_WEB, OLD_NEURON_ID, MOMENT_INDEX
							)[CURRENT_SEGMENT.OLD_OFFSET + VALUE_INDEX]
						: (float)0.0;
			}
		}
	}
}

static void
	LAYER_PLAN(int OLD_LAYER_COUNT, int ADDED_LAYERS, int *OLD_LAYER_OF)
{
	int	POSITION = 0;
	int	OLD_LAYER;

	for (OLD_LAYER = -1; OLD_LAYER < OLD_LAYER_COUNT; OLD_LAYER++)
	{
		if (OLD_LAYER >= 0)
			OLD_LAYER_OF[POSITION++] = OLD_LAYER;

		int	ADDED_INDEX;

		for (ADDED_INDEX = 0; ADDED_INDEX < ADDED_LAYERS; ADDED_INDEX++)
		{
			int	INSERT_AFTER =
				(int)(((int64_t)(ADDED_INDEX + 1) * OLD_LAYER_COUNT) /
					ADDED_LAYERS) -
				1;

			if (INSERT_AFTER < -1)
				INSERT_AFTER = -1;

			if (INSERT_AFTER == OLD_LAYER)
				OLD_LAYER_OF[POSITION++] = -1;
		}
	}
}

WEB
	*WEB_RESHAPE_SHAPE(WEB *OLD_WEB, SHAPE SHAPE_REQUEST)
{
	CONFIG	NEW_CONFIG = OLD_WEB->CONFIGURATION;
	int		MAX_POSITIONS;

	if (SHAPE_REQUEST.MAXIMUM_LENGTH > 0)
		MAX_POSITIONS = SHAPE_REQUEST.MAXIMUM_LENGTH;
	else
		MAX_POSITIONS = OLD_WEB->CONFIGURATION.MAXIMUM_LENGTH;

	NEW_CONFIG.MAXIMUM_LENGTH = MAX_POSITIONS;

	if (SHAPE_REQUEST.MAXIMUM_WORDS > NEW_CONFIG.MAXIMUM_WORDS)
		NEW_CONFIG.MAXIMUM_WORDS = SHAPE_REQUEST.MAXIMUM_WORDS;

	if (SHAPE_REQUEST.DIMENSION > 0)
		NEW_CONFIG.DIMENSION = SHAPE_REQUEST.DIMENSION;

	if (SHAPE_REQUEST.ADD_LAYERS < 0)
		SHAPE_REQUEST.ADD_LAYERS = 0;

	NEW_CONFIG.LAYER_COUNT =
		OLD_WEB->CONFIGURATION.LAYER_COUNT + SHAPE_REQUEST.ADD_LAYERS;

	if (
		NEW_CONFIG.DIMENSION < OLD_WEB->CONFIGURATION.DIMENSION ||
		OLD_WEB->WORD_COUNT > NEW_CONFIG.MAXIMUM_WORDS ||
		!CHECK_CONFIG(NEW_CONFIG)
	)
	{
		fprintf(stderr, "reshape: bad size\n");
		return (NULL);
	}

	if (
		NEW_CONFIG.DIMENSION != OLD_WEB->CONFIGURATION.DIMENSION &&
		(
			WEB_COUNT_NEURONS(OLD_WEB, KIND_RECIPE, -1) ||
			WEB_COUNT_NEURONS(OLD_WEB, KIND_TREE, -1)
		)
	)
	{
		fprintf(
			stderr,
			"reshape: widening a brain that has recipe or tree neurons is not "
			"supported yet\n"
		);
		return (NULL);
	}

	int	COPY_MOMENTS = OLD_WEB->OPTIMIZER_ENABLED;
	WEB	*NEURAL_WEB = WEB_NEW_EMPTY(NEW_CONFIG, OLD_WEB->RANDOM_STATE);

	if (!NEURAL_WEB)
		return (NULL);

	if (COPY_MOMENTS)
		WEB_SET_OPTIMIZER(NEURAL_WEB, 1);

	NEURAL_WEB->STEP = OLD_WEB->STEP;
	NEURAL_WEB->OPTIMIZER_START_STEP = OLD_WEB->OPTIMIZER_START_STEP;

	int	INDEX;

	for (INDEX = 0; INDEX < OLD_WEB->RECIPE_COUNT; INDEX++)
	{
		char	ERROR_MESSAGE[200];

		if (
			WEB_RECIPE_ADD(
				NEURAL_WEB, OLD_WEB->RECIPES[INDEX].SOURCE, ERROR_MESSAGE,
				sizeof ERROR_MESSAGE
			) != INDEX
		)
		{
			fprintf(stderr, "reshape: %s\n", ERROR_MESSAGE);
			WEB_FREE(NEURAL_WEB);
			return (NULL);
		}
	}

	int	OLD_LAYER_COUNT = OLD_WEB->CONFIGURATION.LAYER_COUNT;
	int	NEW_LAYER_COUNT = NEW_CONFIG.LAYER_COUNT;
	int	*OLD_LAYER_OF = malloc(NEW_LAYER_COUNT * sizeof(int));

	LAYER_PLAN(OLD_LAYER_COUNT, SHAPE_REQUEST.ADD_LAYERS, OLD_LAYER_OF);

	int	LAYER_HEADS;

	if (SHAPE_REQUEST.LAYER_HEADS > 0)
		LAYER_HEADS = SHAPE_REQUEST.LAYER_HEADS;
	else
		LAYER_HEADS = 0;

	int	LAYER_FEED_FORWARD;

	if (SHAPE_REQUEST.LAYER_FEED_FORWARD > 0)
		LAYER_FEED_FORWARD = SHAPE_REQUEST.LAYER_FEED_FORWARD;
	else
		LAYER_FEED_FORWARD = 0;

	if (!LAYER_HEADS)
	{
		int	NEURON_COUNT = 0;
		int	AREA_INDEX;

		for (AREA_INDEX = 0; AREA_INDEX < 2 * OLD_LAYER_COUNT; AREA_INDEX += 2)
			NEURON_COUNT +=
				WEB_COUNT_NEURONS(OLD_WEB, KIND_ATTENTION_HEAD, AREA_INDEX);

		if (OLD_LAYER_COUNT)
			LAYER_HEADS =
				(NEURON_COUNT + OLD_LAYER_COUNT - 1) / OLD_LAYER_COUNT;
		else
			LAYER_HEADS = 1;
	}

	int	LAYER;

	for (LAYER = 0; LAYER < NEW_LAYER_COUNT; LAYER++)
	{
		int	SUBLAYER;

		for (SUBLAYER = 0; SUBLAYER < 2; SUBLAYER++)
		{
			int	AREA_INDEX = 2 * LAYER + SUBLAYER;
			int	OLD_AREA_INDEX;

			if (OLD_LAYER_OF[LAYER] >= 0)
				OLD_AREA_INDEX = 2 * OLD_LAYER_OF[LAYER] + SUBLAYER;
			else
				OLD_AREA_INDEX = -1;

			if (OLD_AREA_INDEX >= 0)
				COPY_NEURON(
					NEURAL_WEB, NEURAL_WEB->NORM_IDS[AREA_INDEX], OLD_WEB,
					OLD_WEB->NORM_IDS[OLD_AREA_INDEX], COPY_MOMENTS
				);
		}
	}

	COPY_NEURON(
		NEURAL_WEB, NEURAL_WEB->NORM_IDS[2 * NEW_LAYER_COUNT], OLD_WEB,
		OLD_WEB->NORM_IDS[2 * OLD_LAYER_COUNT], COPY_MOMENTS
	);

	{
		float	*NEW_EMBEDDING =
			NEURON_PARAMETERS(NEURAL_WEB, NEURAL_WEB->EMBEDDING_ID);
		float	*OLD_EMBEDDING =
			NEURON_PARAMETERS(OLD_WEB, OLD_WEB->EMBEDDING_ID);
		int		OLD_WIDTH = OLD_WEB->CONFIGURATION.DIMENSION;
		int		NEW_WIDTH = NEW_CONFIG.DIMENSION;
		int		OLD_MAX_POSITIONS = OLD_WEB->CONFIGURATION.MAXIMUM_LENGTH;
		int		POSITION;

		for (POSITION = 0; POSITION < MAX_POSITIONS; POSITION++)
		{
			int	SOURCE_POSITION;

			if (POSITION < OLD_MAX_POSITIONS)
				SOURCE_POSITION = POSITION;
			else
				SOURCE_POSITION = OLD_MAX_POSITIONS / 2 +
					(POSITION - OLD_MAX_POSITIONS / 2) %
						(OLD_MAX_POSITIONS / 2);

			memset(
				NEW_EMBEDDING + (int64_t)POSITION * NEW_WIDTH, 0, NEW_WIDTH * 4
			);
			memcpy(
				NEW_EMBEDDING + (int64_t)POSITION * NEW_WIDTH,
				OLD_EMBEDDING + (int64_t)SOURCE_POSITION * OLD_WIDTH,
				OLD_WIDTH * 4
			);

			if (COPY_MOMENTS)
			{
				int	AREA_INDEX;

				for (AREA_INDEX = 0; AREA_INDEX < 2; AREA_INDEX++)
				{
					memset(
						NEURON_MOMENTS(
							NEURAL_WEB, NEURAL_WEB->EMBEDDING_ID, AREA_INDEX
						) + (int64_t)POSITION * NEW_WIDTH,
						0, NEW_WIDTH * 4
					);
					memcpy(
						NEURON_MOMENTS(
							NEURAL_WEB, NEURAL_WEB->EMBEDDING_ID, AREA_INDEX
						) + (int64_t)POSITION * NEW_WIDTH,
						NEURON_MOMENTS(
							OLD_WEB, OLD_WEB->EMBEDDING_ID, AREA_INDEX
						) + (int64_t)SOURCE_POSITION * OLD_WIDTH,
						OLD_WIDTH * 4
					);
				}
			}
		}
	}

	for (LAYER = 0; LAYER < NEW_LAYER_COUNT; LAYER++)
	{
		int	SUBLAYER;

		for (SUBLAYER = 0; SUBLAYER < 2; SUBLAYER++)
		{
			int		AREA_INDEX = 2 * LAYER + SUBLAYER;
			AREA	*NEW_AREA = &NEURAL_WEB->AREAS[AREA_INDEX];

			if (OLD_LAYER_OF[LAYER] < 0)
			{
				int	NEURON_COUNT;

				if (NEW_AREA->KIND == KIND_ATTENTION_HEAD)
					NEURON_COUNT = LAYER_HEADS;
				else
					NEURON_COUNT = LAYER_FEED_FORWARD;

				int	INDEX;

				for (INDEX = 0; INDEX < NEURON_COUNT; INDEX++)
					WEB_ADD_NEURON(
						NEURAL_WEB, NEW_AREA->KIND, AREA_INDEX, WHY_GROWTH,
						NEW_AREA->KIND == KIND_ATTENTION_HEAD &&
								SHAPE_REQUEST.ROTARY
							? 1
							: -1
					);

				NEW_AREA->GROWN_COUNT = NEURON_COUNT;
				continue ;
			}

			int		OLD_AREA_INDEX = 2 * OLD_LAYER_OF[LAYER] + SUBLAYER;
			AREA	*OLD_AREA = &OLD_WEB->AREAS[OLD_AREA_INDEX];
			int		INDEX;

			for (INDEX = 0; INDEX < OLD_AREA->MEMBER_COUNT; INDEX++)
			{
				NEURON	*OLD_NEURON =
					&OLD_WEB->NEURONS[OLD_AREA->MEMBERS[INDEX]];

				if (!OLD_NEURON->ALIVE)
					continue ;

				int32_t	NEURON_ID = WEB_ADD_NEURON(
					NEURAL_WEB, OLD_NEURON->KIND, AREA_INDEX,
					OLD_NEURON->BIRTH_REASON,
					OLD_NEURON->KIND == KIND_RECIPE ||
							OLD_NEURON->KIND == KIND_ATTENTION_HEAD ||
							OLD_NEURON->KIND == KIND_TREE
						? OLD_NEURON->KIND_DETAIL
						: -1
				);

				COPY_NEURON(
					NEURAL_WEB, NEURON_ID, OLD_WEB, OLD_AREA->MEMBERS[INDEX],
					COPY_MOMENTS
				);
			}

			int	EXTRA_NEURONS;

			if (OLD_AREA->KIND == KIND_ATTENTION_HEAD)
				EXTRA_NEURONS = SHAPE_REQUEST.ADD_HEADS;
			else
				EXTRA_NEURONS = SHAPE_REQUEST.ADD_FEED_FORWARD;

			for (INDEX = 0; INDEX < EXTRA_NEURONS; INDEX++)
				WEB_ADD_NEURON(
					NEURAL_WEB, OLD_AREA->KIND, AREA_INDEX, WHY_GROWTH,
					OLD_AREA->KIND == KIND_ATTENTION_HEAD &&
							SHAPE_REQUEST.ROTARY
						? 1
						: -1
				);

			NEW_AREA->ERROR_LEVEL = OLD_AREA->ERROR_LEVEL;
			NEW_AREA->ERROR_SLOW = OLD_AREA->ERROR_SLOW;
			NEW_AREA->ERROR_BEST = OLD_AREA->ERROR_BEST;
			NEW_AREA->LAST_GROWTH = OLD_AREA->LAST_GROWTH;
			NEW_AREA->GROWN_COUNT = OLD_AREA->GROWN_COUNT + EXTRA_NEURONS;
		}
	}

	free(OLD_LAYER_OF);

	for (INDEX = 0; INDEX < OLD_WEB->WORD_COUNT; INDEX++)
	{
		WEB_ADD_WORD(NEURAL_WEB);
		COPY_NEURON(
			NEURAL_WEB, NEURAL_WEB->WORD_NEURONS[INDEX], OLD_WEB,
			OLD_WEB->WORD_NEURONS[INDEX], COPY_MOMENTS
		);
	}

	if (OLD_WEB->COPY_ID >= 0)
	{
		WEB_ADD_COPY(NEURAL_WEB);
		COPY_NEURON(
			NEURAL_WEB, NEURAL_WEB->COPY_ID, OLD_WEB, OLD_WEB->COPY_ID,
			COPY_MOMENTS
		);
	}

	NEURAL_WEB->GROWTH_STATE = OLD_WEB->GROWTH_STATE;
	NEURAL_WEB->WORD_LIMIT = OLD_WEB->WORD_LIMIT;
	NEURAL_WEB->KERNEL_STATE->LEARNING_RATE =
		OLD_WEB->KERNEL_STATE->LEARNING_RATE;
	NEURAL_WEB->KERNEL_STATE->WEIGHT_DECAY =
		OLD_WEB->KERNEL_STATE->WEIGHT_DECAY;
	NEURAL_WEB->KERNEL_STATE->NORM_EPSILON =
		OLD_WEB->KERNEL_STATE->NORM_EPSILON *
		(float)OLD_WEB->CONFIGURATION.DIMENSION / (float)NEW_CONFIG.DIMENSION;
	NEURAL_WEB->OPTIMIZER_LOADED = COPY_MOMENTS;
	WEB_RELINK(NEURAL_WEB);

	return (NEURAL_WEB);
}

WEB
	*WEB_RESHAPE(
		WEB *OLD_WEB, int MAX_POSITIONS, int MAX_WORDS, int ADD_FEED_FORWARD,
		int ADD_HEADS
	)
{
	SHAPE	SHAPE_REQUEST = {
		MAX_POSITIONS, MAX_WORDS, ADD_FEED_FORWARD, ADD_HEADS, 0, 0, 0, 0, 0
	};

	return (WEB_RESHAPE_SHAPE(OLD_WEB, SHAPE_REQUEST));
}
