void
	WEB_ROUND_TO_HALF(WEB *NEURAL_WEB)
{
	int64_t	PARAMETER_COUNT = NEURAL_WEB->PARAMETER_BYTES_USED / 4;
	int64_t	WORD_VALUE_COUNT =
		(int64_t)NEURAL_WEB->WORD_COUNT * NEURAL_WEB->WORD_STRIDE / 4;
	float	*PARAMETER_BLOCK = NEURAL_WEB->PARAMETERS;
	float	*WORD_BLOCK =
		(float *)((uint8_t *)NEURAL_WEB->PARAMETERS + WORD_PLANE_OFFSET);
	int64_t	VALUE_INDEX;

	for (VALUE_INDEX = 0; VALUE_INDEX < PARAMETER_COUNT; VALUE_INDEX++)
		PARAMETER_BLOCK[VALUE_INDEX] =
			HALF_TO_FLOAT(FLOAT_TO_HALF(PARAMETER_BLOCK[VALUE_INDEX]));

	for (VALUE_INDEX = 0; VALUE_INDEX < WORD_VALUE_COUNT; VALUE_INDEX++)
		WORD_BLOCK[VALUE_INDEX] =
			HALF_TO_FLOAT(FLOAT_TO_HALF(WORD_BLOCK[VALUE_INDEX]));
}

#define WRITE_VALUE(VALUE) fwrite(&(VALUE), sizeof(VALUE), 1, STREAM)
#define READ_VALUE(VALUE) \
	if (fread(&(VALUE), sizeof(VALUE), 1, STREAM) != 1) \
	goto READ_FAILED

int
	WEB_SAVE(WEB *NEURAL_WEB, const char *PATH, int WITH_OPTIMIZER)
{
	if (NEURAL_WEB->HALF_PRECISION)
		return (-1);

	char	TEMPORARY_PATH[1100];

	snprintf(TEMPORARY_PATH, sizeof TEMPORARY_PATH, "%s.tmp", PATH);

	FILE	*STREAM = fopen(TEMPORARY_PATH, "wb");

	if (!STREAM)
		return (-1);

	fwrite("CODEWEB5", 1, 8, STREAM);

	int32_t	FILE_FORMAT_VERSION = KERNEL_VERSION;
	WRITE_VALUE(FILE_FORMAT_VERSION);
	WRITE_VALUE(NEURAL_WEB->CONFIGURATION);
	WRITE_VALUE(NEURAL_WEB->WORD_COUNT);
	WRITE_VALUE(NEURAL_WEB->RANDOM_STATE);
	WRITE_VALUE(NEURAL_WEB->STEP);
	WRITE_VALUE(NEURAL_WEB->NEURON_COUNT);
	WRITE_VALUE(NEURAL_WEB->AREA_COUNT);
	fwrite(
		NEURAL_WEB->NEURONS, sizeof(NEURON), NEURAL_WEB->NEURON_COUNT, STREAM
	);

	int	ITEM_INDEX;

	for (ITEM_INDEX = 0; ITEM_INDEX < NEURAL_WEB->AREA_COUNT; ITEM_INDEX++)
	{
		AREA	*LAYER_AREA = &NEURAL_WEB->AREAS[ITEM_INDEX];
		WRITE_VALUE(LAYER_AREA->KIND);
		WRITE_VALUE(LAYER_AREA->INDEX);
		WRITE_VALUE(LAYER_AREA->NORM_NEURON);
		WRITE_VALUE(LAYER_AREA->ERROR_LEVEL);
		WRITE_VALUE(LAYER_AREA->ERROR_SLOW);
		WRITE_VALUE(LAYER_AREA->ERROR_BEST);
		WRITE_VALUE(LAYER_AREA->LAST_GROWTH);
		WRITE_VALUE(LAYER_AREA->GROWN_COUNT);
		WRITE_VALUE(LAYER_AREA->MEMBER_COUNT);
		fwrite(
			LAYER_AREA->MEMBERS, sizeof(int32_t), LAYER_AREA->MEMBER_COUNT,
			STREAM
		);
	}

	fwrite(
		NEURAL_WEB->NORM_IDS, sizeof(int32_t),
		2 * NEURAL_WEB->CONFIGURATION.LAYER_COUNT + 1, STREAM
	);
	fwrite(
		NEURAL_WEB->WORD_NEURONS, sizeof(int32_t), NEURAL_WEB->WORD_COUNT,
		STREAM
	);
	WRITE_VALUE(NEURAL_WEB->ENTRY_ID);
	WRITE_VALUE(NEURAL_WEB->EXIT_ID);
	WRITE_VALUE(NEURAL_WEB->UPDATE_START_ID);
	WRITE_VALUE(NEURAL_WEB->INFERENCE_GATE_ID);
	WRITE_VALUE(NEURAL_WEB->LOSS_ID);
	WRITE_VALUE(NEURAL_WEB->EMBEDDING_ID);
	WRITE_VALUE(NEURAL_WEB->GROW_ID);
	WRITE_VALUE(NEURAL_WEB->EVALUATION_GATE_ID);
	WRITE_VALUE(NEURAL_WEB->COPY_ID);
	WRITE_VALUE(NEURAL_WEB->ADAM_ID);
	WRITE_VALUE(NEURAL_WEB->PARAMETER_BYTES_USED);
	WRITE_VALUE(NEURAL_WEB->ACTIVATION_BYTES_USED);
	WRITE_VALUE(NEURAL_WEB->TRAINING_BYTES_USED);
	WRITE_VALUE(NEURAL_WEB->TOKENS_OFFSET);
	WRITE_VALUE(NEURAL_WEB->TARGETS_OFFSET);
	WRITE_VALUE(NEURAL_WEB->LOSS_WEIGHTS_OFFSET);
	WRITE_VALUE(NEURAL_WEB->RESIDUAL_OFFSET);
	WRITE_VALUE(NEURAL_WEB->RESIDUAL_GRADIENT_OFFSET);
	WRITE_VALUE(NEURAL_WEB->NORMALIZED_OFFSET);
	WRITE_VALUE(NEURAL_WEB->NORMALIZED_GRADIENT_OFFSET);
	WRITE_VALUE(NEURAL_WEB->INVERSE_NORM_OFFSET);
	WRITE_VALUE(NEURAL_WEB->SOFTMAX_STATISTICS_OFFSET);
	WRITE_VALUE(NEURAL_WEB->TARGET_LOGIT_OFFSET);
	WRITE_VALUE(NEURAL_WEB->KERNEL_STATE->LEARNING_RATE);
	WRITE_VALUE(NEURAL_WEB->KERNEL_STATE->WEIGHT_DECAY);
	WRITE_VALUE(NEURAL_WEB->GROWTH_STATE);
	WRITE_VALUE(NEURAL_WEB->WORD_LIMIT);
	WRITE_VALUE(NEURAL_WEB->KERNEL_STATE->NORM_EPSILON);
	WRITE_VALUE(NEURAL_WEB->RECIPE_COUNT);
	for (ITEM_INDEX = 0; ITEM_INDEX < NEURAL_WEB->RECIPE_COUNT; ITEM_INDEX++)
	{
		int32_t	SOURCE_LENGTH =
			(int32_t)strlen(NEURAL_WEB->RECIPES[ITEM_INDEX].SOURCE);
		WRITE_VALUE(SOURCE_LENGTH);
		fwrite(
			NEURAL_WEB->RECIPES[ITEM_INDEX].SOURCE, 1, SOURCE_LENGTH, STREAM
		);
	}

	int32_t	LIVE_COUNT = 0;
	int32_t	PIECE_SLOT;

	for (PIECE_SLOT = 0; PIECE_SLOT < NEURAL_WEB->PIECE_COUNT; PIECE_SLOT++)
		if (NEURAL_WEB->NEURONS[NEURAL_WEB->PIECES[PIECE_SLOT].ID / 4].ALIVE)
			LIVE_COUNT++;
	WRITE_VALUE(LIVE_COUNT);
	for (PIECE_SLOT = 0; PIECE_SLOT < NEURAL_WEB->PIECE_COUNT; PIECE_SLOT++)
	{
		CODE_PIECE	*PIECE_RECORD = &NEURAL_WEB->PIECES[PIECE_SLOT];

		if (!NEURAL_WEB->NEURONS[PIECE_RECORD->ID / 4].ALIVE)
			continue ;

		int32_t	CODE_GROUP =
			NEURAL_WEB->SEGMENTS[PIECE_RECORD->SEGMENT_INDEX].GROUP;
		WRITE_VALUE(PIECE_RECORD->ID);
		WRITE_VALUE(PIECE_RECORD->LENGTH);
		WRITE_VALUE(PIECE_RECORD->TAIL_POSITION);
		WRITE_VALUE(PIECE_RECORD->NEXT_ID);
		WRITE_VALUE(PIECE_RECORD->RELOCATION_COUNT);
		WRITE_VALUE(CODE_GROUP);
		fwrite(
			PIECE_POSITIONS(PIECE_RECORD), sizeof(int32_t),
			PIECE_RECORD->RELOCATION_COUNT, STREAM
		);
		fwrite(
			PIECE_TARGETS(PIECE_RECORD), sizeof(int32_t),
			PIECE_RECORD->RELOCATION_COUNT, STREAM
		);
		fwrite(
			NEURAL_WEB->EXECUTABLE + PIECE_RECORD->OFFSET, 1,
			PIECE_RECORD->LENGTH, STREAM
		);
	}

	uint8_t	HALF_FLAG = 1;
	WRITE_VALUE(HALF_FLAG);
	WRITE_PLANE(NEURAL_WEB, STREAM, 0, 1);

	int	SUCCESS = ferror(STREAM) == 0;

	fclose(STREAM);
	remove(PATH);

	if (!SUCCESS || rename(TEMPORARY_PATH, PATH))
		return (-1);

	char	OPTIMIZER_PATH[1024];

	snprintf(OPTIMIZER_PATH, sizeof OPTIMIZER_PATH, "%s.opt", PATH);

	if (WITH_OPTIMIZER && NEURAL_WEB->OPTIMIZER_ENABLED)
	{
		snprintf(
			TEMPORARY_PATH, sizeof TEMPORARY_PATH, "%s.tmp", OPTIMIZER_PATH
		);
		STREAM = fopen(TEMPORARY_PATH, "wb");

		if (!STREAM)
			return (-1);

		fwrite("CODEOPT2", 1, 8, STREAM);
		WRITE_VALUE(NEURAL_WEB->STEP);
		WRITE_VALUE(NEURAL_WEB->PARAMETER_BYTES_USED);
		WRITE_VALUE(NEURAL_WEB->WORD_COUNT);
		int64_t	OPTIMIZER_AGE =
			NEURAL_WEB->STEP - NEURAL_WEB->OPTIMIZER_START_STEP;
		WRITE_VALUE(OPTIMIZER_AGE);
		WRITE_PLANE(NEURAL_WEB, STREAM, 0, 0);
		WRITE_PLANE(NEURAL_WEB, STREAM, 2, 0);
		WRITE_PLANE(NEURAL_WEB, STREAM, 3, 0);
		SUCCESS = ferror(STREAM) == 0;
		fclose(STREAM);
		remove(OPTIMIZER_PATH);

		if (!SUCCESS || rename(TEMPORARY_PATH, OPTIMIZER_PATH))
			return (-1);
	}
	else
		remove(OPTIMIZER_PATH);

	return (0);
}

int
	WEB_LOAD_OPTIMIZER(WEB *NEURAL_WEB, const char *PATH)
{
	char	OPTIMIZER_PATH[1024];

	snprintf(OPTIMIZER_PATH, sizeof OPTIMIZER_PATH, "%s.opt", PATH);

	FILE	*STREAM = fopen(OPTIMIZER_PATH, "rb");

	WEB_SET_OPTIMIZER(NEURAL_WEB, 1);

	if (!STREAM)
		return (-1);

	char	MAGIC_BYTES[8];
	int64_t	SAVED_STEP;
	int64_t	SAVED_PARAMETER_USE;
	int32_t	SAVED_WORD_COUNT;

	if (
		fread(MAGIC_BYTES, 1, 8, STREAM) != 8 ||
		(
			memcmp(MAGIC_BYTES, "CODEOPT1", 8) &&
			memcmp(MAGIC_BYTES, "CODEOPT2", 8)
		)
	)
		goto READ_FAILED;
	READ_VALUE(SAVED_STEP);
	READ_VALUE(SAVED_PARAMETER_USE);
	READ_VALUE(SAVED_WORD_COUNT);
	int64_t	OPTIMIZER_AGE = SAVED_STEP;

	if (!memcmp(MAGIC_BYTES, "CODEOPT2", 8))
		READ_VALUE(OPTIMIZER_AGE);

	if (
		SAVED_STEP != NEURAL_WEB->STEP ||
		SAVED_PARAMETER_USE != NEURAL_WEB->PARAMETER_BYTES_USED ||
		SAVED_WORD_COUNT != NEURAL_WEB->WORD_COUNT
	)
		goto READ_FAILED;

	if (
		READ_PLANE(NEURAL_WEB, STREAM, 0, 0) ||
		READ_PLANE(NEURAL_WEB, STREAM, 2, 0) ||
		READ_PLANE(NEURAL_WEB, STREAM, 3, 0)
	)
		goto READ_FAILED;

	fclose(STREAM);
	NEURAL_WEB->OPTIMIZER_LOADED = 1;
	NEURAL_WEB->OPTIMIZER_START_STEP = NEURAL_WEB->STEP - OPTIMIZER_AGE;
	return (0);

READ_FAILED:
	fclose(STREAM);

	fprintf(
		stderr,
		"note: %s does not match the brain, training state starts fresh\n",
		OPTIMIZER_PATH
	);

	return (-1);
}

