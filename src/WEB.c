static void
	*ZERO_ALLOCATE(size_t BYTE_COUNT)
{
	void	*MEMORY_BLOCK = calloc(1, BYTE_COUNT ? BYTE_COUNT : 1);

	if (!MEMORY_BLOCK)
	{
		fprintf(stderr, "out of memory\n");
		exit(1);
	}

	return (MEMORY_BLOCK);
}

static uint8_t
	*ALIGN_64_BYTES(void *RAW_ADDRESS)
{
	return ((uint8_t *)(((uintptr_t)RAW_ADDRESS + 63) & ~(uintptr_t)63));
}

static int64_t
	ROUND_UP(int64_t VALUE, int64_t ALIGNMENT)
{
	return ((VALUE + ALIGNMENT - 1) / ALIGNMENT * ALIGNMENT);
}

uint64_t
	RANDOM_NEXT(uint64_t *SEED_STATE)
{
	uint64_t	STATE_VALUE = *SEED_STATE;

	STATE_VALUE ^= STATE_VALUE >> 12;
	STATE_VALUE ^= STATE_VALUE << 25;
	STATE_VALUE ^= STATE_VALUE >> 27;
	*SEED_STATE = STATE_VALUE;

	return (STATE_VALUE * (unsigned long long)0X2545F4914F6CDD1D);
}

float
	WEB_RANDOM(WEB *NEURAL_WEB)
{
	return (
		(float)((RANDOM_NEXT(&NEURAL_WEB->RANDOM_STATE) >> 40) *
				(1.0 / 16777216.0))
	);
}

float
	WEB_GAUSSIAN(WEB *NEURAL_WEB)
{
	float	UNIFORM_FIRST = WEB_RANDOM(NEURAL_WEB) + (float)1e-7;
	float	UNIFORM_SECOND = WEB_RANDOM(NEURAL_WEB);

	return (
		sqrtf(-(float)2.0 * logf(UNIFORM_FIRST)) *
			cosf((float)6.2831853 * UNIFORM_SECOND)
	);
}

uint16_t
	FLOAT_TO_HALF(float SINGLE_VALUE)
{
	uint32_t	SINGLE_BITS;

	memcpy(&SINGLE_BITS, &SINGLE_VALUE, 4);

	uint32_t	SIGN_BIT = (SINGLE_BITS >> 16) & 0X8000;
	uint32_t	EXPONENT = (SINGLE_BITS >> 23) & 255;
	uint32_t	MANTISSA = SINGLE_BITS & 0X7FFFFF;

	if (EXPONENT == 255)
		return ((uint16_t)(SIGN_BIT | 0X7C00 | (MANTISSA ? 0X200 : 0)));

	int	HALF_EXPONENT = (int)EXPONENT - 127 + 15;

	if (HALF_EXPONENT >= 31)
		return ((uint16_t)(SIGN_BIT | 0X7C00));

	if (HALF_EXPONENT <= 0)
	{
		if (HALF_EXPONENT < -10)
			return ((uint16_t)SIGN_BIT);

		MANTISSA |= 0X800000;

		int			SHIFT_AMOUNT = 14 - HALF_EXPONENT;
		uint32_t	HALF_BITS = MANTISSA >> SHIFT_AMOUNT;
		uint32_t	REMAINDER_BITS =
			MANTISSA & (((unsigned int)1 << SHIFT_AMOUNT) - 1);
		uint32_t	HALFWAY_POINT = (unsigned int)1 << (SHIFT_AMOUNT - 1);

		if (
			REMAINDER_BITS > HALFWAY_POINT ||
			(REMAINDER_BITS == HALFWAY_POINT && (HALF_BITS & 1))
		)
			HALF_BITS++;

		return ((uint16_t)(SIGN_BIT | HALF_BITS));
	}

	uint32_t	HALF_BITS = ((uint32_t)HALF_EXPONENT << 10) | (MANTISSA >> 13);
	uint32_t	REMAINDER_BITS = MANTISSA & 0X1FFF;

	if (
		REMAINDER_BITS > 0X1000 ||
		(REMAINDER_BITS == 0X1000 && (HALF_BITS & 1))
	)
		HALF_BITS++;

	return ((uint16_t)(SIGN_BIT | HALF_BITS));
}

float
	HALF_TO_FLOAT(uint16_t HALF_BITS)
{
	uint32_t	SIGN_BIT = (uint32_t)(HALF_BITS & 0X8000) << 16;
	uint32_t	EXPONENT = (HALF_BITS >> 10) & 31;
	uint32_t	MANTISSA = HALF_BITS & 0X3FF;
	uint32_t	SINGLE_BITS;

	if (EXPONENT == 0)
	{
		if (!MANTISSA)
			SINGLE_BITS = SIGN_BIT;
		else
		{
			EXPONENT = 127 - 15 + 1;

			while (!(MANTISSA & 0X400))
			{
				MANTISSA <<= 1;
				EXPONENT--;
			}

			MANTISSA &= 0X3FF;
			SINGLE_BITS = SIGN_BIT | (EXPONENT << 23) | (MANTISSA << 13);
		}
	}
	else if (EXPONENT == 31)
		SINGLE_BITS = SIGN_BIT | 0X7F800000 | (MANTISSA << 13);
	else
		SINGLE_BITS =
			SIGN_BIT | ((EXPONENT - 15 + 127) << 23) | (MANTISSA << 13);

	float	SINGLE_VALUE;

	memcpy(&SINGLE_VALUE, &SINGLE_BITS, 4);

	return (SINGLE_VALUE);
}

