static int32_t
	PIECE_INDEX(WEB *NEURAL_WEB, int32_t PIECE_ID)
{
	if (PIECE_ID >= 0 && PIECE_ID < NEURAL_WEB->PIECE_MAP_CAPACITY)
		return (NEURAL_WEB->PIECE_MAP[PIECE_ID]);

	return (-1);
}

static void
	PIECE_SET_MAP(WEB *NEURAL_WEB, int32_t PIECE_ID, int32_t PIECE_SLOT)
{
	if (PIECE_ID >= NEURAL_WEB->PIECE_MAP_CAPACITY)
	{
		int32_t	NEW_CAPACITY;

		if (NEURAL_WEB->PIECE_MAP_CAPACITY)
			NEW_CAPACITY = NEURAL_WEB->PIECE_MAP_CAPACITY;
		else
			NEW_CAPACITY = 1024;

		while (PIECE_ID >= NEW_CAPACITY)
			NEW_CAPACITY *= 2;

		NEURAL_WEB->PIECE_MAP =
			realloc(NEURAL_WEB->PIECE_MAP, NEW_CAPACITY * sizeof(int32_t));

		int32_t	MAP_INDEX;

		for (
			MAP_INDEX = NEURAL_WEB->PIECE_MAP_CAPACITY;
			MAP_INDEX < NEW_CAPACITY;
			MAP_INDEX++
		)
			NEURAL_WEB->PIECE_MAP[MAP_INDEX] = -1;

		NEURAL_WEB->PIECE_MAP_CAPACITY = NEW_CAPACITY;
	}

	NEURAL_WEB->PIECE_MAP[PIECE_ID] = PIECE_SLOT;
}

static int32_t
	PLACE_CODE(
		WEB *NEURAL_WEB, int32_t PIECE_ID, int CODE_GROUP,
		const uint8_t *MACHINE_CODE, int32_t CODE_LENGTH, int32_t TAIL_OFFSET,
		int32_t RELOCATION_COUNT, const int32_t *RELOCATION_POSITIONS,
		const int32_t *RELOCATION_TARGETS
	)
{
	CODE_UNLOCK(NEURAL_WEB);

	int32_t	PIECE_SLOT = PIECE_INDEX(NEURAL_WEB, PIECE_ID);

	if (PIECE_SLOT < 0)
	{
		if (NEURAL_WEB->PIECE_COUNT >= NEURAL_WEB->PIECE_CAPACITY)
		{
			if (NEURAL_WEB->PIECE_CAPACITY)
				NEURAL_WEB->PIECE_CAPACITY = NEURAL_WEB->PIECE_CAPACITY * 2;
			else
				NEURAL_WEB->PIECE_CAPACITY = 1024;

			NEURAL_WEB->PIECES = realloc(
				NEURAL_WEB->PIECES,
				NEURAL_WEB->PIECE_CAPACITY * sizeof(CODE_PIECE)
			);
		}

		PIECE_SLOT = NEURAL_WEB->PIECE_COUNT++;
		memset(&NEURAL_WEB->PIECES[PIECE_SLOT], 0, sizeof(CODE_PIECE));
		PIECE_SET_MAP(NEURAL_WEB, PIECE_ID, PIECE_SLOT);
	}
	else
	{
		CODE_FREE(NEURAL_WEB, &NEURAL_WEB->PIECES[PIECE_SLOT]);

		if (NEURAL_WEB->PIECES[PIECE_SLOT].RELOCATION_COUNT > 2)
		{
			free(NEURAL_WEB->PIECES[PIECE_SLOT].RELOCATION_POSITIONS);
			free(NEURAL_WEB->PIECES[PIECE_SLOT].RELOCATION_TARGETS);
		}
	}

	CODE_PIECE	*PIECE_RECORD = &NEURAL_WEB->PIECES[PIECE_SLOT];
	int32_t		SEGMENT_INDEX;
	int32_t		CODE_OFFSET =
		CODE_ALLOCATE(NEURAL_WEB, CODE_GROUP, CODE_LENGTH, &SEGMENT_INDEX);

	CODE_UNLOCK(NEURAL_WEB);
	PIECE_RECORD->ID = PIECE_ID;
	PIECE_RECORD->OFFSET = CODE_OFFSET;
	PIECE_RECORD->SEGMENT_INDEX = SEGMENT_INDEX;
	PIECE_RECORD->LENGTH = CODE_LENGTH;
	PIECE_RECORD->TAIL_POSITION = TAIL_OFFSET;
	PIECE_RECORD->NEXT_ID = -1;
	PIECE_RECORD->RELOCATION_COUNT = RELOCATION_COUNT;
	PIECE_RECORD->RELOCATION_POSITIONS = PIECE_RECORD->RELOCATION_TARGETS =
		NULL;

	if (RELOCATION_COUNT > 2)
	{
		PIECE_RECORD->RELOCATION_POSITIONS =
			malloc(RELOCATION_COUNT * sizeof(int32_t));
		PIECE_RECORD->RELOCATION_TARGETS =
			malloc(RELOCATION_COUNT * sizeof(int32_t));
	}

	if (RELOCATION_COUNT)
	{
		memcpy(
			PIECE_POSITIONS(PIECE_RECORD), RELOCATION_POSITIONS,
			RELOCATION_COUNT * sizeof(int32_t)
		);
		memcpy(
			PIECE_TARGETS(PIECE_RECORD), RELOCATION_TARGETS,
			RELOCATION_COUNT * sizeof(int32_t)
		);
	}

	memcpy(
		NEURAL_WEB->EXECUTABLE + PIECE_RECORD->OFFSET, MACHINE_CODE, CODE_LENGTH
	);

	return (PIECE_SLOT);
}

static void
	COMPILE_PIECE(WEB *NEURAL_WEB, int32_t NEURON_ID, int PIECE_ROLE)
{
	ASSEMBLER	ASSEMBLY;

	ASSEMBLER_INITIALIZE(&ASSEMBLY);

	int	TAIL_OFFSET = GENERATE_PIECE(
		NEURAL_WEB, &ASSEMBLY, &NEURAL_WEB->NEURONS[NEURON_ID], PIECE_ROLE
	);

	if (TAIL_OFFSET == -1)
	{
		ASSEMBLER_EMIT_BYTE(&ASSEMBLY, 0XE9);
		TAIL_OFFSET = ASSEMBLY.BYTE_COUNT;
		ASSEMBLER_EMIT_INTEGER32(&ASSEMBLY, 0);
	}

	if (ASSEMBLER_FINISH(&ASSEMBLY))
	{
		fprintf(stderr, "jit: unbound label in neuron %d\n", NEURON_ID);
		exit(1);
	}

	int32_t	PIECE_ID = NEURON_ID * 4 + PIECE_ROLE;

	PLACE_CODE(
		NEURAL_WEB, PIECE_ID, CODE_GROUP_OF(&NEURAL_WEB->NEURONS[NEURON_ID]),
		ASSEMBLY.BYTES, ASSEMBLY.BYTE_COUNT, TAIL_OFFSET < 0 ? -1 : TAIL_OFFSET,
		ASSEMBLY.EXTERNAL_COUNT, ASSEMBLY.EXTERNAL_POSITIONS,
		ASSEMBLY.EXTERNAL_TARGETS
	);
	NEURAL_WEB->NEURONS[NEURON_ID].PIECE_IDS[PIECE_ROLE] = PIECE_ID;
	ASSEMBLER_FREE(&ASSEMBLY);
}

static int
	HAS_ROLE(int NEURON_KIND, int PIECE_ROLE)
{
	switch (NEURON_KIND)
	{
		case KIND_EMBEDDING:
		case KIND_NORMALIZATION:
		case KIND_FEED_FORWARD:
		case KIND_ATTENTION_HEAD:
		case KIND_WORD:
		case KIND_COPY:
		case KIND_ORGAN:
		case KIND_RECIPE:
		case KIND_TREE:
		{
			return (PIECE_ROLE != ROLE_UPDATE);
		}
		default:
		{
			return (PIECE_ROLE == ROLE_FORWARD);
		}
	}
}

static int64_t
	KIND_PARAMETER_COUNT(WEB *NEURAL_WEB, int NEURON_KIND, int KIND_VARIANT)
{
	CONFIG	*WEB_CONFIG = &NEURAL_WEB->CONFIGURATION;

	switch (NEURON_KIND)
	{
		case KIND_RECIPE:
		{
			return (NEURAL_WEB->RECIPES[KIND_VARIANT].PARAMETER_TOTAL);
		}
		case KIND_TREE:
		{
			return (
				(((int64_t)1 << (KIND_VARIANT + 1)) - 1) *
					(2 * WEB_CONFIG->DIMENSION + 8)
			);
		}
		case KIND_EMBEDDING:
		{
			return (
				(int64_t)WEB_CONFIG->MAXIMUM_LENGTH * WEB_CONFIG->DIMENSION
			);
		}
		case KIND_NORMALIZATION:
		{
			return (WEB_CONFIG->DIMENSION);
		}
		case KIND_FEED_FORWARD:
		{
			return (2 * WEB_CONFIG->DIMENSION + 8);
		}
		case KIND_ATTENTION_HEAD:
		{
			return (
				(long long)4 * WEB_CONFIG->HEAD_DIMENSION *
					WEB_CONFIG->DIMENSION
			);
		}
		case KIND_WORD:
		{
			return (WEB_CONFIG->DIMENSION + 8);
		}
		case KIND_COPY:
		{
			return (
				(long long)2 * WEB_CONFIG->HEAD_DIMENSION *
						WEB_CONFIG->DIMENSION +
					WEB_CONFIG->DIMENSION + 8
			);
		}
		default:
		{
			return (0);
		}
	}
}

static int64_t
	KIND_ACTIVATION_BYTES(WEB *NEURAL_WEB, int NEURON_KIND, int KIND_VARIANT)
{
	CONFIG	*WEB_CONFIG = &NEURAL_WEB->CONFIGURATION;

	switch (NEURON_KIND)
	{
		case KIND_RECIPE:
		{
			return (
				(int64_t) WEB_CONFIG->MAXIMUM_LENGTH *
					NEURAL_WEB->RECIPES[KIND_VARIANT].VALUE_STRIDE
			);
		}
		case KIND_TREE:
		{
			return (
				(int64_t)WEB_CONFIG->MAXIMUM_LENGTH * (KIND_VARIANT + 1) * 8
			);
		}
		case KIND_FEED_FORWARD:
		{
			return ((int64_t)WEB_CONFIG->MAXIMUM_LENGTH * 4);
		}
		case KIND_ATTENTION_HEAD:
		{
			return (
				(long long)4 * WEB_CONFIG->MAXIMUM_LENGTH *
						WEB_CONFIG->HEAD_DIMENSION * 4 +
					(int64_t)WEB_CONFIG->MAXIMUM_LENGTH *
						WEB_CONFIG->MAXIMUM_LENGTH * 4
			);
		}
		case KIND_COPY:
		{
			return (
				(long long)2 * WEB_CONFIG->MAXIMUM_LENGTH *
						WEB_CONFIG->HEAD_DIMENSION * 4 +
					(int64_t)WEB_CONFIG->MAXIMUM_LENGTH *
						WEB_CONFIG->MAXIMUM_LENGTH * 4 +
					(int64_t)WEB_CONFIG->MAXIMUM_LENGTH * 4
			);
		}
		default:
		{
			return (0);
		}
	}
}

static void
	INITIALIZE_PARAMETERS(WEB *NEURAL_WEB, NEURON *NEURON_RECORD)
{
	float	*PARAMETERS = NEURON_PARAMETERS(NEURAL_WEB, NEURON_RECORD->ID);
	CONFIG	*WEB_CONFIG = &NEURAL_WEB->CONFIGURATION;
	float	RESIDUAL_SCALE =
		(float)0.02 / sqrtf((float)2.0 * WEB_CONFIG->LAYER_COUNT);
	int64_t	PARAMETER_INDEX;

	switch (NEURON_RECORD->KIND)
	{
		case KIND_EMBEDDING:
		{
			for (
				PARAMETER_INDEX = 0;
				PARAMETER_INDEX < NEURON_RECORD->PARAMETER_COUNT;
				PARAMETER_INDEX++
			)
				PARAMETERS[PARAMETER_INDEX] =
					(float)0.02 * WEB_GAUSSIAN(NEURAL_WEB);
		}
		break ;
		case KIND_NORMALIZATION:
		{
			for (
				PARAMETER_INDEX = 0;
				PARAMETER_INDEX < NEURON_RECORD->PARAMETER_COUNT;
				PARAMETER_INDEX++
			)
				PARAMETERS[PARAMETER_INDEX] = (float)1.0;
		}
		break ;
		case KIND_FEED_FORWARD:
		{
			for (
				PARAMETER_INDEX = 0;
				PARAMETER_INDEX < WEB_CONFIG->DIMENSION;
				PARAMETER_INDEX++
			)
				PARAMETERS[PARAMETER_INDEX] =
					(float)0.02 * WEB_GAUSSIAN(NEURAL_WEB);

			for (
				PARAMETER_INDEX = 0;
				PARAMETER_INDEX < WEB_CONFIG->DIMENSION;
				PARAMETER_INDEX++
			)
				PARAMETERS[WEB_CONFIG->DIMENSION + PARAMETER_INDEX] =
					(NEURON_RECORD->BIRTH_REASON == WHY_GROWTH ||
						NEURON_RECORD->BIRTH_REASON == WHY_PERSONAL)
					? (float)0.0
					: RESIDUAL_SCALE * WEB_GAUSSIAN(NEURAL_WEB);
		}
		break ;
		case KIND_ATTENTION_HEAD:
		{
			for (
				PARAMETER_INDEX = 0;
				PARAMETER_INDEX < (long long)3 * WEB_CONFIG->HEAD_DIMENSION *
						WEB_CONFIG->DIMENSION;
				PARAMETER_INDEX++
			)
				PARAMETERS[PARAMETER_INDEX] =
					(float)0.02 * WEB_GAUSSIAN(NEURAL_WEB);

			for (
				;
				PARAMETER_INDEX < NEURON_RECORD->PARAMETER_COUNT;
				PARAMETER_INDEX++
			)
			{
				if (
					NEURON_RECORD->BIRTH_REASON == WHY_GROWTH ||
					NEURON_RECORD->BIRTH_REASON == WHY_PERSONAL
				)
					PARAMETERS[PARAMETER_INDEX] = (float)0.0;
				else
					PARAMETERS[PARAMETER_INDEX] =
						RESIDUAL_SCALE * WEB_GAUSSIAN(NEURAL_WEB);
			}
		}
		break ;
		case KIND_WORD:
		{
			for (
				PARAMETER_INDEX = 0;
				PARAMETER_INDEX < WEB_CONFIG->DIMENSION;
				PARAMETER_INDEX++
			)
				PARAMETERS[PARAMETER_INDEX] =
					(float)0.02 * WEB_GAUSSIAN(NEURAL_WEB);
		}
		break ;
		case KIND_COPY:
		{
			for (
				PARAMETER_INDEX = 0;
				PARAMETER_INDEX < (long long)2 * WEB_CONFIG->HEAD_DIMENSION *
						WEB_CONFIG->DIMENSION;
				PARAMETER_INDEX++
			)
				PARAMETERS[PARAMETER_INDEX] =
					(float)0.02 * WEB_GAUSSIAN(NEURAL_WEB);

			PARAMETERS
				[(long long)2 * WEB_CONFIG->HEAD_DIMENSION *
					WEB_CONFIG->DIMENSION +
					WEB_CONFIG->DIMENSION] = -(float)4.0;
		}
		break ;
		case KIND_TREE:
		{
			int64_t	NODE_COUNT =
				((int64_t)1 << (NEURON_RECORD->KIND_DETAIL + 1)) - 1;
			int64_t	NODE_STRIDE = 2 * WEB_CONFIG->DIMENSION + 8;
			int64_t	NODE_INDEX;

			for (NODE_INDEX = 0; NODE_INDEX < NODE_COUNT; NODE_INDEX++)
			{
				float	*BLOCK_PARAMETERS =
					PARAMETERS + NODE_INDEX * NODE_STRIDE;

				for (
					PARAMETER_INDEX = 0;
					PARAMETER_INDEX < WEB_CONFIG->DIMENSION;
					PARAMETER_INDEX++
				)
					BLOCK_PARAMETERS[PARAMETER_INDEX] =
						(float)0.02 * WEB_GAUSSIAN(NEURAL_WEB);

				for (
					PARAMETER_INDEX = 0;
					PARAMETER_INDEX < WEB_CONFIG->DIMENSION;
					PARAMETER_INDEX++
				)
					BLOCK_PARAMETERS[WEB_CONFIG->DIMENSION + PARAMETER_INDEX] =
						(NEURON_RECORD->BIRTH_REASON == WHY_GROWTH ||
							NEURON_RECORD->BIRTH_REASON == WHY_PERSONAL)
						? (float)0.0
						: RESIDUAL_SCALE * WEB_GAUSSIAN(NEURAL_WEB);

				for (
					PARAMETER_INDEX = 2 * WEB_CONFIG->DIMENSION;
					PARAMETER_INDEX < NODE_STRIDE;
					PARAMETER_INDEX++
				)
					BLOCK_PARAMETERS[PARAMETER_INDEX] = (float)0.0;
			}
		}
		break ;
		case KIND_RECIPE:
		{
			RECIPE	*ACTIVE_RECIPE =
				&NEURAL_WEB->RECIPES[NEURON_RECORD->KIND_DETAIL];
			int		PARAMETER_SLOT;

			for (
				PARAMETER_SLOT = 0;
				PARAMETER_SLOT < ACTIVE_RECIPE->PARAMETER_COUNT;
				PARAMETER_SLOT++
			)
			{
				RECIPE_PARAMETER	*PARAMETER_SPEC =
					&ACTIVE_RECIPE->PARAMETERS[PARAMETER_SLOT];
				int64_t				ELEMENT_COUNT =
					(int64_t)PARAMETER_SPEC->ROWS * PARAMETER_SPEC->COLUMNS;
				float				*BLOCK_PARAMETERS =
					PARAMETERS + PARAMETER_SPEC->OFFSET;

				for (
					PARAMETER_INDEX = 0;
					PARAMETER_INDEX < ELEMENT_COUNT;
					PARAMETER_INDEX++
				)
				{
					if (PARAMETER_SPEC->INITIALIZATION == INITIALIZE_READ)
						BLOCK_PARAMETERS[PARAMETER_INDEX] =
							(float)0.02 * WEB_GAUSSIAN(NEURAL_WEB);
					else if (PARAMETER_SPEC->INITIALIZATION == INITIALIZE_ONE)
						BLOCK_PARAMETERS[PARAMETER_INDEX] = (float)1.0;
					else if (
						PARAMETER_SPEC->INITIALIZATION == INITIALIZE_WRITE &&
						NEURON_RECORD->BIRTH_REASON != WHY_GROWTH
					)
						BLOCK_PARAMETERS[PARAMETER_INDEX] =
							RESIDUAL_SCALE * WEB_GAUSSIAN(NEURAL_WEB);
					else
						BLOCK_PARAMETERS[PARAMETER_INDEX] = (float)0.0;
				}
			}
		}
		break ;
		default:
			break ;
	}
}

static void
	ZERO_PLANES(WEB *NEURAL_WEB, int64_t PARAMETER_OFFSET, int64_t BYTE_COUNT)
{
	int	PLANE_INDEX;

	for (PLANE_INDEX = 0; PLANE_INDEX < 4; PLANE_INDEX++)
	{
		if (PLANE_INDEX == 1 && !NEURAL_WEB->TRAINING_ENABLED)
			continue ;

		if (PLANE_INDEX >= 2 && !NEURAL_WEB->OPTIMIZER_ENABLED)
			continue ;

		memset(
			(uint8_t *)NEURAL_WEB->PARAMETERS + PLANE_INDEX * PARAMETER_PLANE +
				PARAMETER_OFFSET,
			0, BYTE_COUNT
		);
	}
}

static int32_t
	NEW_NEURON_RECORD(
		WEB *NEURAL_WEB, int NEURON_KIND, int AREA_INDEX, int GROWTH_REASON,
		int KIND_VARIANT
	)
{
	if (NEURAL_WEB->NEURON_COUNT >= NEURAL_WEB->NEURON_CAPACITY)
	{
		if (NEURAL_WEB->NEURON_CAPACITY)
			NEURAL_WEB->NEURON_CAPACITY = NEURAL_WEB->NEURON_CAPACITY * 2;
		else
			NEURAL_WEB->NEURON_CAPACITY = 256;

		NEURAL_WEB->NEURONS = realloc(
			NEURAL_WEB->NEURONS, NEURAL_WEB->NEURON_CAPACITY * sizeof(NEURON)
		);
	}

	int32_t	NEURON_ID = NEURAL_WEB->NEURON_COUNT++;
	NEURON	*NEURON_RECORD = &NEURAL_WEB->NEURONS[NEURON_ID];

	memset(NEURON_RECORD, 0, sizeof *NEURON_RECORD);
	NEURON_RECORD->ID = NEURON_ID;
	NEURON_RECORD->KIND = NEURON_KIND;
	NEURON_RECORD->AREA_INDEX = AREA_INDEX;
	NEURON_RECORD->BIRTH_REASON = GROWTH_REASON;
	NEURON_RECORD->BIRTH_STEP = (int32_t)NEURAL_WEB->STEP;
	NEURON_RECORD->KIND_DETAIL = KIND_VARIANT;
	NEURON_RECORD->ALIVE = 1;
	NEURON_RECORD->PIECE_IDS[0] = NEURON_RECORD->PIECE_IDS[1] =
		NEURON_RECORD->PIECE_IDS[2] = -1;

	if (AREA_INDEX >= 0 && AREA_INDEX < NEURAL_WEB->AREA_COUNT)
		NEURON_RECORD->BIRTH_ERROR = NEURAL_WEB->AREAS[AREA_INDEX].ERROR_LEVEL;
	else
		NEURON_RECORD->BIRTH_ERROR = (float)0.0;

	return (NEURON_ID);
}

static int32_t
	ORGAN_FOR(WEB *NEURAL_WEB, int ORGAN_KIND, int AREA_INDEX)
{
	int32_t	NEURON_INDEX;

	for (
		NEURON_INDEX = 0;
		NEURON_INDEX < NEURAL_WEB->NEURON_COUNT;
		NEURON_INDEX++
	)
		if (
			NEURAL_WEB->NEURONS[NEURON_INDEX].KIND == KIND_ORGAN &&
			NEURAL_WEB->NEURONS[NEURON_INDEX].ALIVE &&
			NEURAL_WEB->NEURONS[NEURON_INDEX].KIND_DETAIL == ORGAN_KIND &&
			NEURAL_WEB->NEURONS[NEURON_INDEX].AREA_INDEX == AREA_INDEX
		)
			return (NEURON_INDEX);

	int32_t	NEURON_ID = NEW_NEURON_RECORD(
		NEURAL_WEB, KIND_ORGAN, AREA_INDEX, WHY_CONTROL, ORGAN_KIND
	);

	COMPILE_PIECE(NEURAL_WEB, NEURON_ID, ROLE_FORWARD);
	COMPILE_PIECE(NEURAL_WEB, NEURON_ID, ROLE_BACKWARD);

	return (NEURON_ID);
}

int32_t
	WEB_ORGAN(WEB *NEURAL_WEB, int ORGAN_KIND, int AREA_INDEX)
{
	return (ORGAN_FOR(NEURAL_WEB, ORGAN_KIND, AREA_INDEX));
}

int
	ORGAN_KEY(int NEURON_KIND, int KIND_VARIANT)
{
	if (NEURON_KIND == KIND_RECIPE)
		return (ORGAN_RECIPE_BASE + KIND_VARIANT);

	if (NEURON_KIND == KIND_TREE)
		return (ORGAN_TREE_BASE + KIND_VARIANT);

	if (NEURON_KIND == KIND_ATTENTION_HEAD && KIND_VARIANT == 1)
		return (ORGAN_ROTARY_HEAD);

	return (NEURON_KIND);
}

int32_t
	WEB_ADD_NEURON(
		WEB *NEURAL_WEB, int NEURON_KIND, int AREA_INDEX, int GROWTH_REASON,
		int KIND_VARIANT
	)
{
	if (
		NEURON_KIND == KIND_FEED_FORWARD ||
		NEURON_KIND == KIND_ATTENTION_HEAD ||
		NEURON_KIND == KIND_WORD ||
		NEURON_KIND == KIND_RECIPE ||
		NEURON_KIND == KIND_TREE
	)
		ORGAN_FOR(NEURAL_WEB, ORGAN_KEY(NEURON_KIND, KIND_VARIANT), AREA_INDEX);

	int32_t	NEURON_ID = NEW_NEURON_RECORD(
		NEURAL_WEB, NEURON_KIND, AREA_INDEX, GROWTH_REASON, KIND_VARIANT
	);
	NEURON	*NEURON_RECORD = &NEURAL_WEB->NEURONS[NEURON_ID];

	NEURON_RECORD->PARAMETER_COUNT =
		KIND_PARAMETER_COUNT(NEURAL_WEB, NEURON_KIND, KIND_VARIANT);

	if (NEURON_KIND == KIND_WORD)
		NEURON_RECORD->PARAMETER_OFFSET =
			WORD_PLANE_OFFSET + (int64_t)KIND_VARIANT * NEURAL_WEB->WORD_STRIDE;
	else if (NEURON_RECORD->PARAMETER_COUNT)
		NEURON_RECORD->PARAMETER_OFFSET =
			ALLOCATE_PARAMETERS(NEURAL_WEB, NEURON_RECORD->PARAMETER_COUNT);

	NEURON_RECORD = &NEURAL_WEB->NEURONS[NEURON_ID];
	NEURON_RECORD->ACTIVATION_BYTES =
		KIND_ACTIVATION_BYTES(NEURAL_WEB, NEURON_KIND, KIND_VARIANT);

	if (NEURON_RECORD->ACTIVATION_BYTES)
		NEURON_RECORD->ACTIVATION_OFFSET =
			ALLOCATE_ACTIVATIONS(NEURAL_WEB, NEURON_RECORD->ACTIVATION_BYTES);

	if (NEURON_RECORD->PARAMETER_COUNT)
	{
		ZERO_PLANES(
			NEURAL_WEB, NEURON_RECORD->PARAMETER_OFFSET,
			NEURON_RECORD->PARAMETER_COUNT * 4
		);
		INITIALIZE_PARAMETERS(NEURAL_WEB, NEURON_RECORD);
	}

	if (
		AREA_INDEX >= 0 &&
		AREA_INDEX < NEURAL_WEB->AREA_COUNT &&
		(
			NEURON_KIND == KIND_FEED_FORWARD ||
			NEURON_KIND == KIND_ATTENTION_HEAD ||
			NEURON_KIND == KIND_WORD ||
			NEURON_KIND == KIND_RECIPE ||
			NEURON_KIND == KIND_TREE
		)
	)
	{
		AREA	*LAYER_AREA = &NEURAL_WEB->AREAS[AREA_INDEX];

		if (LAYER_AREA->MEMBER_COUNT >= LAYER_AREA->MEMBER_CAPACITY)
		{
			if (LAYER_AREA->MEMBER_CAPACITY)
				LAYER_AREA->MEMBER_CAPACITY = LAYER_AREA->MEMBER_CAPACITY * 2;
			else
				LAYER_AREA->MEMBER_CAPACITY = 64;

			LAYER_AREA->MEMBERS = realloc(
				LAYER_AREA->MEMBERS,
				LAYER_AREA->MEMBER_CAPACITY * sizeof(int32_t)
			);
		}

		LAYER_AREA->MEMBERS[LAYER_AREA->MEMBER_COUNT++] = NEURON_ID;
	}

	int	ROLE_INDEX;

	for (ROLE_INDEX = 0; ROLE_INDEX < 3; ROLE_INDEX++)
		if (HAS_ROLE(NEURON_KIND, ROLE_INDEX))
			COMPILE_PIECE(NEURAL_WEB, NEURON_ID, ROLE_INDEX);

	return (NEURON_ID);
}

typedef struct
{
	int32_t	*IDS;
	int		COUNT;
	int		CAPACITY;
} ID_LIST;

static void
	ID_LIST_PUSH(ID_LIST *CHAIN_LIST, int32_t PIECE_ID)
{
	if (PIECE_ID < 0)
		return ;

	if (CHAIN_LIST->COUNT >= CHAIN_LIST->CAPACITY)
	{
		if (CHAIN_LIST->CAPACITY)
			CHAIN_LIST->CAPACITY = CHAIN_LIST->CAPACITY * 2;
		else
			CHAIN_LIST->CAPACITY = 1024;

		CHAIN_LIST->IDS =
			realloc(CHAIN_LIST->IDS, CHAIN_LIST->CAPACITY * sizeof(int32_t));
	}

	CHAIN_LIST->IDS[CHAIN_LIST->COUNT++] = PIECE_ID;
}

static void
	PATCH_JUMP(
		WEB *NEURAL_WEB, CODE_PIECE *PIECE_RECORD, int32_t PATCH_POSITION,
		int32_t TARGET_PIECE_ID
	)
{
	int32_t	TARGET_INDEX = PIECE_INDEX(NEURAL_WEB, TARGET_PIECE_ID);

	if (TARGET_INDEX < 0)
	{
		fprintf(stderr, "link: missing piece %d\n", TARGET_PIECE_ID);
		exit(1);
	}

	int64_t	PATCH_SITE = PIECE_RECORD->OFFSET + PATCH_POSITION;
	int32_t	RELATIVE_OFFSET =
		(int32_t)(NEURAL_WEB->PIECES[TARGET_INDEX].OFFSET - (PATCH_SITE + 4));

	memcpy(NEURAL_WEB->EXECUTABLE + PATCH_SITE, &RELATIVE_OFFSET, 4);
}

static void
	PATCH_ALL_JUMPS(WEB *NEURAL_WEB)
{
	CODE_UNLOCK(NEURAL_WEB);

	int32_t	PIECE_SLOT;

	for (PIECE_SLOT = 0; PIECE_SLOT < NEURAL_WEB->PIECE_COUNT; PIECE_SLOT++)
	{
		CODE_PIECE	*PIECE_RECORD = &NEURAL_WEB->PIECES[PIECE_SLOT];

		if (!NEURAL_WEB->NEURONS[PIECE_RECORD->ID / 4].ALIVE)
			continue ;

		if (PIECE_RECORD->TAIL_POSITION >= 0 && PIECE_RECORD->NEXT_ID >= 0)
			PATCH_JUMP(
				NEURAL_WEB, PIECE_RECORD, PIECE_RECORD->TAIL_POSITION,
				PIECE_RECORD->NEXT_ID
			);

		int	RELOCATION_INDEX;

		for (
			RELOCATION_INDEX = 0;
			RELOCATION_INDEX < PIECE_RECORD->RELOCATION_COUNT;
			RELOCATION_INDEX++
		)
			PATCH_JUMP(
				NEURAL_WEB, PIECE_RECORD,
				PIECE_POSITIONS(PIECE_RECORD)[RELOCATION_INDEX],
				PIECE_TARGETS(PIECE_RECORD)[RELOCATION_INDEX]
			);
	}

	CODE_LOCK(NEURAL_WEB);
}

void
	WEB_RELINK(WEB *NEURAL_WEB)
{
	ID_LIST	FORWARD_CHAIN = { 0 };
	ID_LIST	UPDATE_CHAIN = { 0 };
	int		LAST_AREA = 2 * NEURAL_WEB->CONFIGURATION.LAYER_COUNT;

	ID_LIST_PUSH(
		&FORWARD_CHAIN, NEURAL_WEB->NEURONS[NEURAL_WEB->ENTRY_ID].PIECE_IDS[0]
	);
	ID_LIST_PUSH(
		&FORWARD_CHAIN,
		NEURAL_WEB->NEURONS[NEURAL_WEB->EMBEDDING_ID].PIECE_IDS[0]
	);

	int	AREA_INDEX;

	for (AREA_INDEX = 0; AREA_INDEX <= LAST_AREA; AREA_INDEX++)
	{
		ID_LIST_PUSH(
			&FORWARD_CHAIN,
			NEURAL_WEB->NEURONS[NEURAL_WEB->NORM_IDS[AREA_INDEX]].PIECE_IDS[0]
		);

		AREA	*LAYER_AREA = &NEURAL_WEB->AREAS[AREA_INDEX];
		int		ITEM_INDEX;

		for (
			ITEM_INDEX = 0;
			ITEM_INDEX < LAYER_AREA->MEMBER_COUNT;
			ITEM_INDEX++
		)
			if (NEURAL_WEB->NEURONS[LAYER_AREA->MEMBERS[ITEM_INDEX]].ALIVE)
				ID_LIST_PUSH(
					&FORWARD_CHAIN,
					NEURAL_WEB->NEURONS[LAYER_AREA->MEMBERS[ITEM_INDEX]]
						.PIECE_IDS[0]
				);
	}

	if (NEURAL_WEB->COPY_ID >= 0)
		ID_LIST_PUSH(
			&FORWARD_CHAIN,
			NEURAL_WEB->NEURONS[NEURAL_WEB->COPY_ID].PIECE_IDS[0]
		);

	ID_LIST_PUSH(
		&FORWARD_CHAIN,
		NEURAL_WEB->NEURONS[NEURAL_WEB->INFERENCE_GATE_ID].PIECE_IDS[0]
	);

	if (!NEURAL_WEB->HALF_PRECISION)
		ID_LIST_PUSH(
			&FORWARD_CHAIN,
			NEURAL_WEB->NEURONS[NEURAL_WEB->LOSS_ID].PIECE_IDS[0]
		);

	ID_LIST_PUSH(
		&FORWARD_CHAIN,
		NEURAL_WEB->NEURONS[NEURAL_WEB->EVALUATION_GATE_ID].PIECE_IDS[0]
	);

	if (NEURAL_WEB->COPY_ID >= 0)
		ID_LIST_PUSH(
			&FORWARD_CHAIN,
			NEURAL_WEB->NEURONS[NEURAL_WEB->COPY_ID].PIECE_IDS[1]
		);

	for (AREA_INDEX = LAST_AREA; AREA_INDEX >= 0; AREA_INDEX--)
	{
		AREA	*LAYER_AREA = &NEURAL_WEB->AREAS[AREA_INDEX];
		int		ITEM_INDEX;

		for (
			ITEM_INDEX = LAYER_AREA->MEMBER_COUNT - 1;
			ITEM_INDEX >= 0;
			ITEM_INDEX--
		)
			if (NEURAL_WEB->NEURONS[LAYER_AREA->MEMBERS[ITEM_INDEX]].ALIVE)
				ID_LIST_PUSH(
					&FORWARD_CHAIN,
					NEURAL_WEB->NEURONS[LAYER_AREA->MEMBERS[ITEM_INDEX]]
						.PIECE_IDS[1]
				);

		ID_LIST_PUSH(
			&FORWARD_CHAIN,
			NEURAL_WEB->NEURONS[NEURAL_WEB->NORM_IDS[AREA_INDEX]].PIECE_IDS[1]
		);
	}

	ID_LIST_PUSH(
		&FORWARD_CHAIN,
		NEURAL_WEB->NEURONS[NEURAL_WEB->EMBEDDING_ID].PIECE_IDS[1]
	);
	ID_LIST_PUSH(
		&FORWARD_CHAIN, NEURAL_WEB->NEURONS[NEURAL_WEB->EXIT_ID].PIECE_IDS[0]
	);
	ID_LIST_PUSH(
		&UPDATE_CHAIN,
		NEURAL_WEB->NEURONS[NEURAL_WEB->UPDATE_START_ID].PIECE_IDS[0]
	);
	ID_LIST_PUSH(
		&UPDATE_CHAIN, NEURAL_WEB->NEURONS[NEURAL_WEB->ADAM_ID].PIECE_IDS[0]
	);
	ID_LIST_PUSH(
		&UPDATE_CHAIN, NEURAL_WEB->NEURONS[NEURAL_WEB->GROW_ID].PIECE_IDS[0]
	);
	ID_LIST_PUSH(
		&UPDATE_CHAIN, NEURAL_WEB->NEURONS[NEURAL_WEB->EXIT_ID].PIECE_IDS[0]
	);

	ID_LIST	*CHAINS[2] = { &FORWARD_CHAIN, &UPDATE_CHAIN };
	int		CHAIN_INDEX;

	for (CHAIN_INDEX = 0; CHAIN_INDEX < 2; CHAIN_INDEX++)
	{
		int	ITEM_INDEX;

		for (
			ITEM_INDEX = 0;
			ITEM_INDEX + 1 < CHAINS[CHAIN_INDEX]->COUNT;
			ITEM_INDEX++
		)
			NEURAL_WEB
				->PIECES[PIECE_INDEX(
					NEURAL_WEB, CHAINS[CHAIN_INDEX]->IDS[ITEM_INDEX]
				)]
				.NEXT_ID = CHAINS[CHAIN_INDEX]->IDS[ITEM_INDEX + 1];
	}

	PATCH_ALL_JUMPS(NEURAL_WEB);
	free(FORWARD_CHAIN.IDS);
	free(UPDATE_CHAIN.IDS);
}

static int
	PLAY_NEEDS_ROLE(NEURON *NEURON_RECORD, int PIECE_ROLE)
{
	if (PIECE_ROLE != ROLE_FORWARD)
		return (0);

	switch (NEURON_RECORD->KIND)
	{
		case KIND_LOSS:
		case KIND_EVALUATION_GATE:
		case KIND_ADAM:
		case KIND_GROW:
		{
			return (0);
		}
		default:
		{
			return (1);
		}
	}
}

void
	WEB_RECOMPILE(WEB *NEURAL_WEB)
{
	int32_t	NEURON_INDEX;

	for (
		NEURON_INDEX = 0;
		NEURON_INDEX < NEURAL_WEB->NEURON_COUNT;
		NEURON_INDEX++
	)
	{
		NEURON	*NEURON_RECORD = &NEURAL_WEB->NEURONS[NEURON_INDEX];

		if (!NEURON_RECORD->ALIVE)
			continue ;

		int	ROLE_INDEX;

		for (ROLE_INDEX = 0; ROLE_INDEX < 3; ROLE_INDEX++)
		{
			if (!HAS_ROLE(NEURON_RECORD->KIND, ROLE_INDEX))
				continue ;

			if (
				NEURAL_WEB->HALF_PRECISION &&
				!PLAY_NEEDS_ROLE(NEURON_RECORD, ROLE_INDEX)
			)
			{
				NEURON_RECORD->PIECE_IDS[ROLE_INDEX] = -1;
				continue ;
			}

			COMPILE_PIECE(NEURAL_WEB, NEURON_INDEX, ROLE_INDEX);
		}
	}

	WEB_RELINK(NEURAL_WEB);
}

static void
	SERVE_READ(KERNEL_CONTEXT *KERNEL_STATE)
{
	WEB	*NEURAL_WEB = KERNEL_STATE->OWNER;

	KERNEL_STATE->SCRATCH[0] = ((float *)((uint8_t *)NEURAL_WEB->PARAMETERS +
		KERNEL_STATE->REQUEST_ARGUMENT))[0];
}

static void
	SERVE_WRITE(KERNEL_CONTEXT *KERNEL_STATE)
{
	WEB	*NEURAL_WEB = KERNEL_STATE->OWNER;

	((float *)((uint8_t *)NEURAL_WEB->PARAMETERS +
		KERNEL_STATE->REQUEST_ARGUMENT))[0] = KERNEL_STATE->SCRATCH[0];
}

static void
	SERVE_CONNECT(KERNEL_CONTEXT *KERNEL_STATE)
{
	WEB_RELINK((WEB *)KERNEL_STATE->OWNER);
}

static void
	SERVE_TRACE(KERNEL_CONTEXT *KERNEL_STATE)
{
	KERNEL_STATE->FIRE_COUNT++;
}

static void
	SERVE_CREATE(KERNEL_CONTEXT *KERNEL_STATE)
{
	WEB		*NEURAL_WEB = KERNEL_STATE->OWNER;
	int32_t	NEURON_ID = -1;
	int64_t	CREATE_COUNT;

	if (KERNEL_STATE->REQUEST_ARGUMENT > 0)
		CREATE_COUNT = KERNEL_STATE->REQUEST_ARGUMENT;
	else
		CREATE_COUNT = 1;

	int64_t	CREATE_INDEX;

	for (CREATE_INDEX = 0; CREATE_INDEX < CREATE_COUNT; CREATE_INDEX++)
		NEURON_ID = WEB_ADD_NEURON(
			NEURAL_WEB, (int)KERNEL_STATE->REQUEST_KIND,
			(int)KERNEL_STATE->REQUEST_AREA, WHY_GROWTH,
			KERNEL_STATE->REQUEST_KIND == KIND_RECIPE
				? NEURAL_WEB->GROWTH_RECIPE
				: KERNEL_STATE->REQUEST_KIND == KIND_ATTENTION_HEAD &&
					NEURAL_WEB->GROWTH_ROTARY
				? 1
				: -1
		);

	WEB_RELINK(NEURAL_WEB);
	KERNEL_STATE->REQUEST_RESULT = NEURON_ID;
	KERNEL_STATE->REQUEST_AREA = -1;
	KERNEL_STATE->REQUEST_ARGUMENT = 0;
}

