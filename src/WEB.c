static void
	SETUP_COMMON(WEB *NEURAL_WEB)
{
	NEURAL_WEB->KERNEL_STATE_MEMORY =
		ZERO_ALLOCATE(sizeof(KERNEL_CONTEXT) + 64);
	NEURAL_WEB->KERNEL_STATE =
		(KERNEL_CONTEXT *)ALIGN_64_BYTES(NEURAL_WEB->KERNEL_STATE_MEMORY);
	INITIALIZE_CONSTANTS(NEURAL_WEB->KERNEL_STATE);
	NEURAL_WEB->SERVICE_TABLE[SERVICE_READ] = (void *)SERVE_READ;
	NEURAL_WEB->SERVICE_TABLE[SERVICE_WRITE] = (void *)SERVE_WRITE;
	NEURAL_WEB->SERVICE_TABLE[SERVICE_CREATE] = (void *)SERVE_CREATE;
	NEURAL_WEB->SERVICE_TABLE[SERVICE_CONNECT] = (void *)SERVE_CONNECT;
	NEURAL_WEB->SERVICE_TABLE[SERVICE_TRACE] = (void *)SERVE_TRACE;
	NEURAL_WEB->KERNEL_STATE->SERVICE_TABLE = NEURAL_WEB->SERVICE_TABLE;
	NEURAL_WEB->KERNEL_STATE->OWNER = NEURAL_WEB;
	NEURAL_WEB->KERNEL_STATE->MAXIMUM_LENGTH =
		NEURAL_WEB->CONFIGURATION.MAXIMUM_LENGTH;
	NEURAL_WEB->KERNEL_STATE->DIMENSION = NEURAL_WEB->CONFIGURATION.DIMENSION;
	NEURAL_WEB->KERNEL_STATE->INVERSE_DIMENSION =
		(float)1.0 / NEURAL_WEB->CONFIGURATION.DIMENSION;
	NEURAL_WEB->KERNEL_STATE->ATTENTION_SCALE =
		(float)1.0 / sqrtf((float)NEURAL_WEB->CONFIGURATION.HEAD_DIMENSION);
	NEURAL_WEB->NORM_IDS = ZERO_ALLOCATE(
		(2 * NEURAL_WEB->CONFIGURATION.LAYER_COUNT + 1) * sizeof(int32_t)
	);
	NEURAL_WEB->WORD_NEURONS = ZERO_ALLOCATE(
		NEURAL_WEB->CONFIGURATION.MAXIMUM_WORDS * sizeof(int32_t)
	);
	NEURAL_WEB->WORD_STRIDE =
		(int64_t)(NEURAL_WEB->CONFIGURATION.DIMENSION + 8) * 4;
	SPACE_INITIALIZE(&NEURAL_WEB->PARAMETER_SPACE, 4 * PARAMETER_PLANE);
	SPACE_INITIALIZE(&NEURAL_WEB->ACTIVATION_SPACE, 2 * ACTIVATION_PLANE);
	NEURAL_WEB->PARAMETERS = (float *)NEURAL_WEB->PARAMETER_SPACE.BASE;
	NEURAL_WEB->ACTIVATIONS = NEURAL_WEB->ACTIVATION_SPACE.BASE;
	NEURAL_WEB->KERNEL_STATE->PARAMETERS = NEURAL_WEB->PARAMETERS;
	NEURAL_WEB->KERNEL_STATE->ACTIVATIONS = NEURAL_WEB->ACTIVATIONS;
	NEURAL_WEB->EXECUTABLE = VIRTUAL_RESERVE(CODE_RESERVE_BYTES);

	if (!NEURAL_WEB->EXECUTABLE)
	{
		fprintf(stderr, "cannot reserve code space\n");
		exit(1);
	}

	NEURAL_WEB->COPY_ID = -1;
	NEURAL_WEB->GROWTH_RECIPE = -1;

	{
		int	SEQUENCE_LENGTH = NEURAL_WEB->CONFIGURATION.MAXIMUM_LENGTH;
		int	HEAD_WIDTH = NEURAL_WEB->CONFIGURATION.HEAD_DIMENSION;

		NEURAL_WEB->ROTARY_TABLE =
			ZERO_ALLOCATE((size_t)SEQUENCE_LENGTH * HEAD_WIDTH * 2 * 4 + 64);

		int	POSITION_INDEX;

		for (
			POSITION_INDEX = 0;
			POSITION_INDEX < SEQUENCE_LENGTH;
			POSITION_INDEX++
		)
		{
			int	PAIR_INDEX;

			for (PAIR_INDEX = 0; PAIR_INDEX < HEAD_WIDTH / 2; PAIR_INDEX++)
			{
				double	ROTATION_ANGLE = POSITION_INDEX *
					pow(10000.0, -2.0 * PAIR_INDEX / HEAD_WIDTH);
				float	ANGLE_COSINE = (float)cos(ROTATION_ANGLE);
				float	ANGLE_SINE = (float)sin(ROTATION_ANGLE);

				NEURAL_WEB->ROTARY_TABLE
					[(int64_t)POSITION_INDEX * 2 * HEAD_WIDTH +
						2 * PAIR_INDEX] = ANGLE_COSINE;
				NEURAL_WEB->ROTARY_TABLE
					[(int64_t)POSITION_INDEX * 2 * HEAD_WIDTH + 2 * PAIR_INDEX +
						1] = ANGLE_COSINE;
				NEURAL_WEB->ROTARY_TABLE
					[(int64_t)POSITION_INDEX * 2 * HEAD_WIDTH + HEAD_WIDTH +
						2 * PAIR_INDEX] = -ANGLE_SINE;
				NEURAL_WEB->ROTARY_TABLE
					[(int64_t)POSITION_INDEX * 2 * HEAD_WIDTH + HEAD_WIDTH +
						2 * PAIR_INDEX + 1] = ANGLE_SINE;
			}
		}

		NEURAL_WEB->KERNEL_STATE->ROTARY_TABLE = NEURAL_WEB->ROTARY_TABLE;
	}
}

static int
	CHECK_CONFIG(CONFIG CANDIDATE_CONFIG)
{
	if (
		CANDIDATE_CONFIG.DIMENSION % 32 ||
		CANDIDATE_CONFIG.DIMENSION < 32 ||
		CANDIDATE_CONFIG.DIMENSION > 2048
	)
		return (0);

	if (
		CANDIDATE_CONFIG.HEAD_DIMENSION != 8 &&
		CANDIDATE_CONFIG.HEAD_DIMENSION != 16 &&
		CANDIDATE_CONFIG.HEAD_DIMENSION != 32
	)
		return (0);

	if (
		CANDIDATE_CONFIG.MAXIMUM_LENGTH % 8 ||
		CANDIDATE_CONFIG.MAXIMUM_LENGTH < 8 ||
		CANDIDATE_CONFIG.MAXIMUM_LENGTH > 4096
	)
		return (0);

	if (
		(int64_t
		) CANDIDATE_CONFIG.MAXIMUM_WORDS *CANDIDATE_CONFIG.MAXIMUM_LENGTH *
				4 >
			ACTIVATION_PLANE / 4
	)
		return (0);

	if (
		(int64_t
		) CANDIDATE_CONFIG.MAXIMUM_WORDS *(CANDIDATE_CONFIG.DIMENSION + 8) *
				4 >
			PARAMETER_PLANE / 2
	)
		return (0);

	return (
		CANDIDATE_CONFIG.LAYER_COUNT >= 1 &&
		CANDIDATE_CONFIG.LAYER_COUNT <= 64 &&
		CANDIDATE_CONFIG.MAXIMUM_WORDS >= 8
	);
}

WEB
	*WEB_NEW_EMPTY(CONFIG WEB_CONFIG, uint64_t RANDOM_SEED)
{
	if (!CHECK_CONFIG(WEB_CONFIG))
	{
		fprintf(stderr, "bad config\n");
		return (NULL);
	}

	WEB	*NEURAL_WEB = ZERO_ALLOCATE(sizeof(WEB));

	NEURAL_WEB->CONFIGURATION = WEB_CONFIG;

	if (RANDOM_SEED)
		NEURAL_WEB->RANDOM_STATE = RANDOM_SEED;
	else
		NEURAL_WEB->RANDOM_STATE = (unsigned long long)0X9E3779B97F4A7C15;

	SETUP_COMMON(NEURAL_WEB);
	LAYOUT_ACTIVATIONS(NEURAL_WEB);

	int	LAST_AREA = 2 * WEB_CONFIG.LAYER_COUNT;

	NEURAL_WEB->AREA_COUNT = LAST_AREA + 1;
	NEURAL_WEB->AREAS = ZERO_ALLOCATE(NEURAL_WEB->AREA_COUNT * sizeof(AREA));

	int	AREA_INDEX;

	for (AREA_INDEX = 0; AREA_INDEX <= LAST_AREA; AREA_INDEX++)
	{
		NEURAL_WEB->AREAS[AREA_INDEX].INDEX = AREA_INDEX;

		if (AREA_INDEX == LAST_AREA)
			NEURAL_WEB->AREAS[AREA_INDEX].KIND = KIND_WORD;
		else if (AREA_INDEX % 2 == 0)
			NEURAL_WEB->AREAS[AREA_INDEX].KIND = KIND_ATTENTION_HEAD;
		else
			NEURAL_WEB->AREAS[AREA_INDEX].KIND = KIND_FEED_FORWARD;
	}

	NEURAL_WEB->ENTRY_ID = 0;
	NEURAL_WEB->EXIT_ID = 1;
	NEURAL_WEB->UPDATE_START_ID = 2;
	NEURAL_WEB->INFERENCE_GATE_ID = 3;
	NEURAL_WEB->LOSS_ID = 4;
	NEURAL_WEB->GROW_ID = 5;
	NEURAL_WEB->EMBEDDING_ID = 6;
	NEURAL_WEB->EVALUATION_GATE_ID = 7;
	NEURAL_WEB->ADAM_ID = 8;
	WEB_ADD_NEURON(NEURAL_WEB, KIND_ENTRY, -1, WHY_CONTROL, -1);
	WEB_ADD_NEURON(NEURAL_WEB, KIND_EXIT, -1, WHY_CONTROL, -1);
	WEB_ADD_NEURON(NEURAL_WEB, KIND_UPDATE_START, -1, WHY_CONTROL, -1);
	WEB_ADD_NEURON(NEURAL_WEB, KIND_INFERENCE_GATE, -1, WHY_CONTROL, -1);
	WEB_ADD_NEURON(NEURAL_WEB, KIND_LOSS, -1, WHY_CONTROL, -1);
	WEB_ADD_NEURON(NEURAL_WEB, KIND_GROW, -1, WHY_CONTROL, -1);
	WEB_ADD_NEURON(NEURAL_WEB, KIND_EMBEDDING, -1, WHY_CONTROL, -1);
	WEB_ADD_NEURON(NEURAL_WEB, KIND_EVALUATION_GATE, -1, WHY_CONTROL, -1);
	WEB_ADD_NEURON(NEURAL_WEB, KIND_ADAM, -1, WHY_CONTROL, -1);

	for (AREA_INDEX = 0; AREA_INDEX <= LAST_AREA; AREA_INDEX++)
	{
		NEURAL_WEB->NORM_IDS[AREA_INDEX] = WEB_ADD_NEURON(
			NEURAL_WEB, KIND_NORMALIZATION, AREA_INDEX, WHY_CONTROL, -1
		);
		NEURAL_WEB->AREAS[AREA_INDEX].NORM_NEURON =
			NEURAL_WEB->NORM_IDS[AREA_INDEX];
	}

	return (NEURAL_WEB);
}

WEB
	*WEB_NEW(CONFIG WEB_CONFIG, uint64_t RANDOM_SEED)
{
	WEB	*NEURAL_WEB = WEB_NEW_EMPTY(WEB_CONFIG, RANDOM_SEED);

	if (!NEURAL_WEB)
		return (NULL);

	int	AREA_INDEX;

	for (AREA_INDEX = 0; AREA_INDEX < 2 * WEB_CONFIG.LAYER_COUNT; AREA_INDEX++)
	{
		int	AREA_KIND = NEURAL_WEB->AREAS[AREA_INDEX].KIND;
		int	SEED_COUNT;

		if (AREA_KIND == KIND_ATTENTION_HEAD)
			SEED_COUNT = WEB_CONFIG.INITIAL_HEADS;
		else
			SEED_COUNT = WEB_CONFIG.INITIAL_FEED_FORWARD;

		int	SEED_INDEX;

		for (SEED_INDEX = 0; SEED_INDEX < SEED_COUNT; SEED_INDEX++)
			WEB_ADD_NEURON(NEURAL_WEB, AREA_KIND, AREA_INDEX, WHY_SEED, -1);
	}

	WEB_RELINK(NEURAL_WEB);

	return (NEURAL_WEB);
}

int
	WEB_RECIPE_FIND(WEB *NEURAL_WEB, const char *RECIPE_NAME)
{
	int	RECIPE_INDEX;

	for (
		RECIPE_INDEX = 0;
		RECIPE_INDEX < NEURAL_WEB->RECIPE_COUNT;
		RECIPE_INDEX++
	)
		if (!strcmp(NEURAL_WEB->RECIPES[RECIPE_INDEX].NAME, RECIPE_NAME))
			return (RECIPE_INDEX);

	return (-1);
}

int
	WEB_RECIPE_ADD(
		WEB *NEURAL_WEB, const char *RECIPE_SOURCE, char *ERROR_MESSAGE,
		int ERROR_MESSAGE_SIZE
	)
{
	RECIPE	PARSED_RECIPE;

	if (
		RECIPE_PARSE(
			&PARSED_RECIPE, RECIPE_SOURCE, NEURAL_WEB->CONFIGURATION.DIMENSION,
			ERROR_MESSAGE, ERROR_MESSAGE_SIZE
		)
	)
		return (-1);

	int	EXISTING_INDEX = WEB_RECIPE_FIND(NEURAL_WEB, PARSED_RECIPE.NAME);

	if (EXISTING_INDEX >= 0)
	{
		int	IS_IDENTICAL = !strcmp(
			NEURAL_WEB->RECIPES[EXISTING_INDEX].SOURCE, PARSED_RECIPE.SOURCE
		);

		RECIPE_FREE(&PARSED_RECIPE);

		if (IS_IDENTICAL)
			return (EXISTING_INDEX);

		snprintf(
			ERROR_MESSAGE, ERROR_MESSAGE_SIZE,
			"a different recipe named %s is already in this brain",
			NEURAL_WEB->RECIPES[EXISTING_INDEX].NAME
		);
		return (-1);
	}

	if (NEURAL_WEB->RECIPE_COUNT >= NEURAL_WEB->RECIPE_CAPACITY)
	{
		if (NEURAL_WEB->RECIPE_CAPACITY)
			NEURAL_WEB->RECIPE_CAPACITY = NEURAL_WEB->RECIPE_CAPACITY * 2;
		else
			NEURAL_WEB->RECIPE_CAPACITY = 8;

		NEURAL_WEB->RECIPES = realloc(
			NEURAL_WEB->RECIPES, NEURAL_WEB->RECIPE_CAPACITY * sizeof(RECIPE)
		);
	}

	NEURAL_WEB->RECIPES[NEURAL_WEB->RECIPE_COUNT] = PARSED_RECIPE;

	return (NEURAL_WEB->RECIPE_COUNT++);
}

int
	WEB_ADD_WORD(WEB *NEURAL_WEB)
{
	if (NEURAL_WEB->WORD_COUNT >= NEURAL_WEB->CONFIGURATION.MAXIMUM_WORDS)
		return (-1);

	int	WORD_INDEX = NEURAL_WEB->WORD_COUNT;
	int	GROWTH_REASON;

	if (NEURAL_WEB->STEP > 0)
		GROWTH_REASON = WHY_NEW_WORD;
	else
		GROWTH_REASON = WHY_SEED;

	NEURAL_WEB->WORD_COUNT++;
	NEURAL_WEB->KERNEL_STATE->WORD_COUNT = NEURAL_WEB->WORD_COUNT;
	WEB_COMMIT(NEURAL_WEB);

	int32_t	NEURON_ID = WEB_ADD_NEURON(
		NEURAL_WEB, KIND_WORD, 2 * NEURAL_WEB->CONFIGURATION.LAYER_COUNT,
		GROWTH_REASON, WORD_INDEX
	);

	NEURAL_WEB->WORD_NEURONS[WORD_INDEX] = NEURON_ID;

	if (GROWTH_REASON == WHY_NEW_WORD && NEURAL_WEB->WORD_COUNT > 1)
	{
		float	LOWEST_BIAS = (float)1e30;
		int		OTHER_WORD;

		for (
			OTHER_WORD = 0;
			OTHER_WORD < NEURAL_WEB->WORD_COUNT - 1;
			OTHER_WORD++
		)
		{
			float	WORD_BIAS = NEURON_PARAMETERS(
				NEURAL_WEB, NEURAL_WEB->WORD_NEURONS[OTHER_WORD]
			)[NEURAL_WEB->CONFIGURATION.DIMENSION];

			if (WORD_BIAS < LOWEST_BIAS)
				LOWEST_BIAS = WORD_BIAS;
		}

		NEURON_PARAMETERS(NEURAL_WEB, NEURON_ID)
		[NEURAL_WEB->CONFIGURATION.DIMENSION] = LOWEST_BIAS;
	}

	return (WORD_INDEX);
}

void
	WEB_PREPARE(WEB *NEURAL_WEB, int RUN_MODE)
{
	KERNEL_CONTEXT	*KERNEL_STATE = NEURAL_WEB->KERNEL_STATE;

	if (NEURAL_WEB->HALF_PRECISION && RUN_MODE != MODE_INFER)
	{
		fprintf(stderr, "a brain loaded for play can only think, not learn\n");
		exit(1);
	}

	if (
		(RUN_MODE == MODE_TRAIN || RUN_MODE == MODE_EVALUATE) &&
		!NEURAL_WEB->TRAINING_ENABLED
	)
		WEB_SET_TRAINING(NEURAL_WEB, 1);

	if (RUN_MODE == MODE_UPDATE && !NEURAL_WEB->OPTIMIZER_ENABLED)
		WEB_SET_OPTIMIZER(NEURAL_WEB, 1);

	KERNEL_STATE->MODE = RUN_MODE;
	KERNEL_STATE->WORD_COUNT = NEURAL_WEB->WORD_COUNT;
	KERNEL_STATE->ACTIVATIONS = NEURAL_WEB->ACTIVATIONS;
	KERNEL_STATE->PARAMETERS = NEURAL_WEB->PARAMETERS;
	KERNEL_STATE->SERVICE_TABLE = NEURAL_WEB->SERVICE_TABLE;
	KERNEL_STATE->OWNER = NEURAL_WEB;
	KERNEL_STATE->STEP = NEURAL_WEB->STEP;
	KERNEL_STATE->PARAMETER_BYTES_USED = NEURAL_WEB->PARAMETER_BYTES_USED;
	KERNEL_STATE->WORD_BYTES_USED =
		(int64_t)NEURAL_WEB->WORD_COUNT * NEURAL_WEB->WORD_STRIDE;

	if (RUN_MODE == MODE_UPDATE)
	{
		float	GRADIENT_MULTIPLIER;

		if (NEURAL_WEB->GRADIENT_MULTIPLIER > 0)
			GRADIENT_MULTIPLIER = NEURAL_WEB->GRADIENT_MULTIPLIER;
		else
			GRADIENT_MULTIPLIER = (float)1.0;

		int64_t	OPTIMIZER_AGE =
			NEURAL_WEB->STEP - NEURAL_WEB->OPTIMIZER_START_STEP;

		if (OPTIMIZER_AGE < 1)
			OPTIMIZER_AGE = 1;

		KERNEL_STATE->FIRST_BIAS_CORRECTION = (float)1.0 /
			((float)1.0 -
				powf(KERNEL_STATE->FIRST_MOMENT_DECAY, (float)OPTIMIZER_AGE));
		KERNEL_STATE->SECOND_BIAS_CORRECTION = (float)1.0 /
			((float)1.0 -
				powf(KERNEL_STATE->SECOND_MOMENT_DECAY, (float)OPTIMIZER_AGE));
		KERNEL_STATE->FIRST_MOMENT_RATE =
			(1 - KERNEL_STATE->FIRST_MOMENT_DECAY) * GRADIENT_MULTIPLIER;
		KERNEL_STATE->SECOND_MOMENT_RATE =
			(1 - KERNEL_STATE->SECOND_MOMENT_DECAY) * GRADIENT_MULTIPLIER *
			GRADIENT_MULTIPLIER;
	}
}

int
	WEB_RUN(WEB *NEURAL_WEB, int RUN_MODE)
{
	if (RUN_MODE == MODE_UPDATE)
		NEURAL_WEB->STEP++;

	WEB_PREPARE(NEURAL_WEB, RUN_MODE);
	CODE_LOCK(NEURAL_WEB);
	WEB_RUN_KERNEL_STATE(NEURAL_WEB, NEURAL_WEB->KERNEL_STATE);

	return (0);
}

void
	WEB_RUN_KERNEL_STATE(WEB *NEURAL_WEB, KERNEL_CONTEXT *KERNEL_STATE)
{
	WEB_FUNCTION	ENTRY_FUNCTION =
		(WEB_FUNCTION)(void *)(NEURAL_WEB->EXECUTABLE +
			NEURAL_WEB
			->PIECES[PIECE_INDEX(
				NEURAL_WEB,
				NEURAL_WEB->NEURONS[NEURAL_WEB->ENTRY_ID]
				.PIECE_IDS[0]
				)]
			.OFFSET);

	ENTRY_FUNCTION(KERNEL_STATE, KERNEL_STATE, KERNEL_STATE, KERNEL_STATE);
}

void
	WEB_FREE(WEB *NEURAL_WEB)
{
	if (!NEURAL_WEB)
		return ;

	VIRTUAL_RELEASE(NEURAL_WEB->EXECUTABLE, CODE_RESERVE_BYTES);
	VIRTUAL_RELEASE(
		NEURAL_WEB->PARAMETER_SPACE.BASE,
		NEURAL_WEB->PARAMETER_SPACE.RESERVED_BYTES
	);
	VIRTUAL_RELEASE(
		NEURAL_WEB->ACTIVATION_SPACE.BASE,
		NEURAL_WEB->ACTIVATION_SPACE.RESERVED_BYTES
	);

	int32_t	PIECE_SLOT;

	for (PIECE_SLOT = 0; PIECE_SLOT < NEURAL_WEB->PIECE_COUNT; PIECE_SLOT++)
		if (NEURAL_WEB->PIECES[PIECE_SLOT].RELOCATION_COUNT > 2)
		{
			free(NEURAL_WEB->PIECES[PIECE_SLOT].RELOCATION_POSITIONS);
			free(NEURAL_WEB->PIECES[PIECE_SLOT].RELOCATION_TARGETS);
		}

	free(NEURAL_WEB->PIECES);
	free(NEURAL_WEB->PIECE_MAP);
	free(NEURAL_WEB->SEGMENTS);
	free(NEURAL_WEB->HOLES);

	int	ITEM_INDEX;

	for (ITEM_INDEX = 0; ITEM_INDEX < NEURAL_WEB->AREA_COUNT; ITEM_INDEX++)
		free(NEURAL_WEB->AREAS[ITEM_INDEX].MEMBERS);

	free(NEURAL_WEB->AREAS);
	free(NEURAL_WEB->NEURONS);
	free(NEURAL_WEB->NORM_IDS);
	free(NEURAL_WEB->WORD_NEURONS);
	free(NEURAL_WEB->KERNEL_STATE_MEMORY);
	free(NEURAL_WEB->ROTARY_TABLE);

	for (ITEM_INDEX = 0; ITEM_INDEX < NEURAL_WEB->RECIPE_COUNT; ITEM_INDEX++)
		RECIPE_FREE(&NEURAL_WEB->RECIPES[ITEM_INDEX]);

	free(NEURAL_WEB->RECIPES);
	free(NEURAL_WEB);
}

static void
	WRITE_PLANE(
		WEB *NEURAL_WEB, FILE *STREAM, int PLANE_INDEX, int STORE_AS_HALF
	)
{
	int64_t	PARAMETER_COUNT = NEURAL_WEB->PARAMETER_BYTES_USED / 4;
	int64_t	WORD_VALUE_COUNT =
		(int64_t)NEURAL_WEB->WORD_COUNT * NEURAL_WEB->WORD_STRIDE / 4;
	float	*PARAMETER_BLOCK = (float *)((uint8_t *)NEURAL_WEB->PARAMETERS +
		PLANE_INDEX * PARAMETER_PLANE);
	float	*WORD_BLOCK =
		(float *)((uint8_t *)NEURAL_WEB->PARAMETERS +
			PLANE_INDEX * PARAMETER_PLANE + WORD_PLANE_OFFSET);
	int		PART_INDEX;

	for (PART_INDEX = 0; PART_INDEX < 2; PART_INDEX++)
	{
		float	*SOURCE;

		if (PART_INDEX)
			SOURCE = WORD_BLOCK;
		else
			SOURCE = PARAMETER_BLOCK;

		int64_t	VALUE_COUNT;

		if (PART_INDEX)
			VALUE_COUNT = WORD_VALUE_COUNT;
		else
			VALUE_COUNT = PARAMETER_COUNT;

		if (!STORE_AS_HALF)
		{
			fwrite(SOURCE, 4, VALUE_COUNT, STREAM);
			continue ;
		}

		uint16_t	BUFFER[4096];
		int64_t		CHUNK_START;

		for (CHUNK_START = 0; CHUNK_START < VALUE_COUNT; CHUNK_START += 4096)
		{
			int64_t	CHUNK_COUNT;

			if (VALUE_COUNT - CHUNK_START < 4096)
				CHUNK_COUNT = VALUE_COUNT - CHUNK_START;
			else
				CHUNK_COUNT = 4096;

			int64_t	CHUNK_INDEX;

			for (CHUNK_INDEX = 0; CHUNK_INDEX < CHUNK_COUNT; CHUNK_INDEX++)
				BUFFER[CHUNK_INDEX] =
					FLOAT_TO_HALF(SOURCE[CHUNK_START + CHUNK_INDEX]);

			fwrite(BUFFER, 2, CHUNK_COUNT, STREAM);
		}
	}
}

