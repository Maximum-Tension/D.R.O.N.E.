static void
	SPACE_INITIALIZE(SPACE *ADDRESS_SPACE, int64_t RESERVE_SIZE)
{
	memset(ADDRESS_SPACE, 0, sizeof *ADDRESS_SPACE);
	ADDRESS_SPACE->BASE = VIRTUAL_RESERVE(RESERVE_SIZE);

	if (!ADDRESS_SPACE->BASE)
	{
		fprintf(
			stderr, "cannot reserve %lld bytes of address space\n",
			(long long)RESERVE_SIZE
		);
		exit(1);
	}

	ADDRESS_SPACE->RESERVED_BYTES = RESERVE_SIZE;
}

static void
	SPACE_ENSURE(
		SPACE *ADDRESS_SPACE, int SLOT_INDEX, int64_t START_OFFSET,
		int64_t NEEDED_LENGTH
	)
{
	int64_t	COMMIT_LENGTH = ROUND_UP(NEEDED_LENGTH, CODE_SEGMENT_BYTES);

	if (COMMIT_LENGTH <= ADDRESS_SPACE->COMMITTED_BYTES[SLOT_INDEX])
		return ;

	if (
		VIRTUAL_COMMIT(
			ADDRESS_SPACE->BASE + START_OFFSET +
				ADDRESS_SPACE->COMMITTED_BYTES[SLOT_INDEX],
			COMMIT_LENGTH - ADDRESS_SPACE->COMMITTED_BYTES[SLOT_INDEX], 0
		)
	)
	{
		fprintf(stderr, "cannot commit memory\n");
		exit(1);
	}

	ADDRESS_SPACE->COMMITTED_BYTES[SLOT_INDEX] = COMMIT_LENGTH;
}

static void
	COMMIT_SPACES(
		WEB *NEURAL_WEB, SPACE *PARAMETER_SPACE, SPACE *ACTIVATION_SPACE,
		int TRAINING_ENABLED, int OPTIMIZER_ENABLED
	)
{
	int64_t	WORD_PLANE_BYTES =
		(int64_t)NEURAL_WEB->WORD_COUNT * NEURAL_WEB->WORD_STRIDE;

	if (NEURAL_WEB->HALF_PRECISION)
		SPACE_ENSURE(
			PARAMETER_SPACE, 8, WORD_PLANE_OFFSET / 2, WORD_PLANE_BYTES / 2
		);

	int	PLANE_INDEX;

	for (PLANE_INDEX = 0; PLANE_INDEX < 4; PLANE_INDEX++)
	{
		if (PLANE_INDEX == 1 && !TRAINING_ENABLED)
			continue ;

		if (PLANE_INDEX >= 2 && !OPTIMIZER_ENABLED)
			continue ;

		SPACE_ENSURE(
			PARAMETER_SPACE, 2 * PLANE_INDEX, PLANE_INDEX * PARAMETER_PLANE,
			NEURAL_WEB->PARAMETER_BYTES_USED
		);
		SPACE_ENSURE(
			PARAMETER_SPACE, 2 * PLANE_INDEX + 1,
			PLANE_INDEX * PARAMETER_PLANE + WORD_PLANE_OFFSET, WORD_PLANE_BYTES
		);
	}

	SPACE_ENSURE(ACTIVATION_SPACE, 0, 0, NEURAL_WEB->ACTIVATION_BYTES_USED);
	SPACE_ENSURE(
		ACTIVATION_SPACE, 4, LAST_LOGITS_OFFSET,
		(int64_t)NEURAL_WEB->CONFIGURATION.MAXIMUM_WORDS * 4
	);

	if (TRAINING_ENABLED)
	{
		SPACE_ENSURE(
			ACTIVATION_SPACE, 1, ACTIVATION_PLANE,
			NEURAL_WEB->ACTIVATION_BYTES_USED
		);
		SPACE_ENSURE(
			ACTIVATION_SPACE, 2, ACTIVATION_PLANE + TRAINING_REGION_OFFSET,
			NEURAL_WEB->TRAINING_BYTES_USED
		);
		SPACE_ENSURE(
			ACTIVATION_SPACE, 3, LOGITS_OFFSET,
			(int64_t)NEURAL_WEB->WORD_COUNT *
				NEURAL_WEB->CONFIGURATION.MAXIMUM_LENGTH * 4
		);
	}
}

static void
	WEB_COMMIT(WEB *NEURAL_WEB)
{
	COMMIT_SPACES(
		NEURAL_WEB, &NEURAL_WEB->PARAMETER_SPACE, &NEURAL_WEB->ACTIVATION_SPACE,
		NEURAL_WEB->TRAINING_ENABLED, NEURAL_WEB->OPTIMIZER_ENABLED
	);
}

void
	WEB_SET_TRAINING(WEB *NEURAL_WEB, int ENABLE_TRAINING)
{
	NEURAL_WEB->TRAINING_ENABLED = ENABLE_TRAINING;

	if (ENABLE_TRAINING)
		WEB_COMMIT(NEURAL_WEB);
}

void
	WEB_SET_OPTIMIZER(WEB *NEURAL_WEB, int ENABLE_OPTIMIZER)
{
	if (ENABLE_OPTIMIZER && !NEURAL_WEB->OPTIMIZER_ENABLED)
		NEURAL_WEB->OPTIMIZER_START_STEP = NEURAL_WEB->STEP;

	NEURAL_WEB->OPTIMIZER_ENABLED = ENABLE_OPTIMIZER;

	if (ENABLE_OPTIMIZER)
	{
		NEURAL_WEB->TRAINING_ENABLED = 1;
		WEB_COMMIT(NEURAL_WEB);
	}
}

static int64_t
	ALLOCATE_PARAMETERS(WEB *NEURAL_WEB, int64_t FLOAT_COUNT)
{
	int64_t	OFFSET = NEURAL_WEB->PARAMETER_BYTES_USED;

	NEURAL_WEB->PARAMETER_BYTES_USED += ROUND_UP(FLOAT_COUNT * 4, 32);

	if (NEURAL_WEB->PARAMETER_BYTES_USED > WORD_PLANE_OFFSET)
	{
		fprintf(stderr, "brain too large for its weight plane\n");
		exit(1);
	}

	WEB_COMMIT(NEURAL_WEB);

	return (OFFSET);
}

static int64_t
	ALLOCATE_ACTIVATIONS(WEB *NEURAL_WEB, int64_t BYTE_COUNT)
{
	int64_t	OFFSET = NEURAL_WEB->ACTIVATION_BYTES_USED;

	NEURAL_WEB->ACTIVATION_BYTES_USED += ROUND_UP(BYTE_COUNT, 64);

	if (NEURAL_WEB->ACTIVATION_BYTES_USED > TRAINING_REGION_OFFSET)
	{
		fprintf(stderr, "activation plane full\n");
		exit(1);
	}

	WEB_COMMIT(NEURAL_WEB);

	return (OFFSET);
}

static int64_t
	ALLOCATE_TRAINING(WEB *NEURAL_WEB, int64_t BYTE_COUNT)
{
	int64_t	OFFSET = NEURAL_WEB->TRAINING_BYTES_USED;
	int64_t	NEW_USED_BYTES = OFFSET + ROUND_UP(BYTE_COUNT, 64);

	if (NEW_USED_BYTES > LOGITS_OFFSET - TRAINING_REGION_OFFSET)
	{
		fprintf(stderr, "training plane full\n");
		exit(1);
	}

	NEURAL_WEB->TRAINING_BYTES_USED = NEW_USED_BYTES;
	WEB_COMMIT(NEURAL_WEB);

	return (ACTIVATION_PLANE + TRAINING_REGION_OFFSET + OFFSET);
}

static void
	CODE_UNLOCK(WEB *NEURAL_WEB)
{
	if (NEURAL_WEB->CODE_WRITABLE || !NEURAL_WEB->EXECUTABLE_USED)
	{
		NEURAL_WEB->CODE_WRITABLE = 1;
		return ;
	}

	VIRTUAL_PROTECT(NEURAL_WEB->EXECUTABLE, NEURAL_WEB->EXECUTABLE_USED, 1);
	NEURAL_WEB->CODE_WRITABLE = 1;
}

static void
	CODE_LOCK(WEB *NEURAL_WEB)
{
	if (!NEURAL_WEB->CODE_WRITABLE)
		return ;

	if (NEURAL_WEB->EXECUTABLE_USED)
		VIRTUAL_PROTECT(NEURAL_WEB->EXECUTABLE, NEURAL_WEB->EXECUTABLE_USED, 0);

	NEURAL_WEB->CODE_WRITABLE = 0;
}

static int
	CODE_GROUP_OF(NEURON *NEURON_RECORD)
{
	if (NEURON_RECORD->KIND == KIND_WORD)
		return (1);

	if (NEURON_RECORD->KIND == KIND_ORGAN)
		return (2);

	if (
		(
			NEURON_RECORD->KIND == KIND_FEED_FORWARD ||
			NEURON_RECORD->KIND == KIND_ATTENTION_HEAD ||
			NEURON_RECORD->KIND == KIND_RECIPE ||
			NEURON_RECORD->KIND == KIND_TREE
		) &&
		NEURON_RECORD->AREA_INDEX >= 0
	)
		return (3 + NEURON_RECORD->AREA_INDEX);

	return (0);
}

static int32_t
	CODE_ALLOCATE(
		WEB *NEURAL_WEB, int CODE_GROUP, int32_t CODE_LENGTH,
		int32_t *SEGMENT_RESULT
	)
{
	CODE_LENGTH = (int32_t)ROUND_UP(CODE_LENGTH, 16);

	int	ENTRY_INDEX;

	for (ENTRY_INDEX = 0; ENTRY_INDEX < NEURAL_WEB->HOLE_COUNT; ENTRY_INDEX++)
	{
		HOLE	*FREE_HOLE = &NEURAL_WEB->HOLES[ENTRY_INDEX];

		if (
			NEURAL_WEB->SEGMENTS[FREE_HOLE->SEGMENT_INDEX].GROUP !=
				CODE_GROUP ||
			FREE_HOLE->LENGTH < CODE_LENGTH
		)
			continue ;

		int32_t	CODE_OFFSET = FREE_HOLE->OFFSET;

		*SEGMENT_RESULT = FREE_HOLE->SEGMENT_INDEX;
		FREE_HOLE->OFFSET += CODE_LENGTH;
		FREE_HOLE->LENGTH -= CODE_LENGTH;

		if (FREE_HOLE->LENGTH < 16)
			NEURAL_WEB->HOLES[ENTRY_INDEX] =
				NEURAL_WEB->HOLES[--NEURAL_WEB->HOLE_COUNT];

		return (CODE_OFFSET);
	}

	for (
		ENTRY_INDEX = NEURAL_WEB->SEGMENT_COUNT - 1;
		ENTRY_INDEX >= 0;
		ENTRY_INDEX--
	)
	{
		SEGMENT	*CODE_SEGMENT = &NEURAL_WEB->SEGMENTS[ENTRY_INDEX];

		if (CODE_SEGMENT->GROUP != CODE_GROUP)
			continue ;

		if (CODE_SEGMENT->BYTE_SIZE - CODE_SEGMENT->BYTES_USED >= CODE_LENGTH)
		{
			int32_t	CODE_OFFSET =
				CODE_SEGMENT->OFFSET + CODE_SEGMENT->BYTES_USED;

			CODE_SEGMENT->BYTES_USED += CODE_LENGTH;
			*SEGMENT_RESULT = ENTRY_INDEX;
			return (CODE_OFFSET);
		}

		break ;
	}

	int64_t	SEGMENT_BYTES = ROUND_UP(CODE_LENGTH, CODE_SEGMENT_BYTES);

	if (NEURAL_WEB->EXECUTABLE_USED + SEGMENT_BYTES > CODE_RESERVE_BYTES)
	{
		fprintf(stderr, "code space full\n");
		exit(1);
	}

	if (
		VIRTUAL_COMMIT(
			NEURAL_WEB->EXECUTABLE + NEURAL_WEB->EXECUTABLE_USED, SEGMENT_BYTES,
			1
		)
	)
	{
		fprintf(stderr, "cannot commit code segment\n");
		exit(1);
	}

	if (NEURAL_WEB->SEGMENT_COUNT >= NEURAL_WEB->SEGMENT_CAPACITY)
	{
		if (NEURAL_WEB->SEGMENT_CAPACITY)
			NEURAL_WEB->SEGMENT_CAPACITY = NEURAL_WEB->SEGMENT_CAPACITY * 2;
		else
			NEURAL_WEB->SEGMENT_CAPACITY = 64;

		NEURAL_WEB->SEGMENTS = realloc(
			NEURAL_WEB->SEGMENTS, NEURAL_WEB->SEGMENT_CAPACITY * sizeof(SEGMENT)
		);
	}

	SEGMENT	*CODE_SEGMENT = &NEURAL_WEB->SEGMENTS[NEURAL_WEB->SEGMENT_COUNT];

	CODE_SEGMENT->GROUP = CODE_GROUP;
	CODE_SEGMENT->OFFSET = (int32_t)NEURAL_WEB->EXECUTABLE_USED;
	CODE_SEGMENT->BYTE_SIZE = (int32_t)SEGMENT_BYTES;
	CODE_SEGMENT->BYTES_USED = CODE_LENGTH;
	NEURAL_WEB->EXECUTABLE_USED += SEGMENT_BYTES;
	NEURAL_WEB->CODE_WRITABLE = 1;
	*SEGMENT_RESULT = NEURAL_WEB->SEGMENT_COUNT++;

	return (CODE_SEGMENT->OFFSET);
}

static void
	CODE_FREE(WEB *NEURAL_WEB, CODE_PIECE *FREED_PIECE)
{
	if (FREED_PIECE->LENGTH <= 0)
		return ;

	CODE_UNLOCK(NEURAL_WEB);

	if (NEURAL_WEB->HOLE_COUNT >= NEURAL_WEB->HOLE_CAPACITY)
	{
		if (NEURAL_WEB->HOLE_CAPACITY)
			NEURAL_WEB->HOLE_CAPACITY = NEURAL_WEB->HOLE_CAPACITY * 2;
		else
			NEURAL_WEB->HOLE_CAPACITY = 256;

		NEURAL_WEB->HOLES = realloc(
			NEURAL_WEB->HOLES, NEURAL_WEB->HOLE_CAPACITY * sizeof(HOLE)
		);
	}

	HOLE	*NEW_HOLE = &NEURAL_WEB->HOLES[NEURAL_WEB->HOLE_COUNT++];

	NEW_HOLE->SEGMENT_INDEX = FREED_PIECE->SEGMENT_INDEX;
	NEW_HOLE->OFFSET = FREED_PIECE->OFFSET;
	NEW_HOLE->LENGTH = (int32_t)ROUND_UP(FREED_PIECE->LENGTH, 16);
	memset(
		NEURAL_WEB->EXECUTABLE + FREED_PIECE->OFFSET, 0XCC, FREED_PIECE->LENGTH
	);
}

int64_t
	WEB_CODE_BYTES(WEB *NEURAL_WEB)
{
	int64_t	TOTAL_BYTES = 0;
	int32_t	PIECE_SLOT;

	for (PIECE_SLOT = 0; PIECE_SLOT < NEURAL_WEB->PIECE_COUNT; PIECE_SLOT++)
		if (NEURAL_WEB->NEURONS[NEURAL_WEB->PIECES[PIECE_SLOT].ID / 4].ALIVE)
			TOTAL_BYTES += NEURAL_WEB->PIECES[PIECE_SLOT].LENGTH;

	return (TOTAL_BYTES);
}

