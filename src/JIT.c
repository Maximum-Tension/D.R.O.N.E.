void
	ASSEMBLER_INITIALIZE(ASSEMBLER *ASSEMBLY)
{
	memset(ASSEMBLY, 0, sizeof *ASSEMBLY);
}

void
	ASSEMBLER_FREE(ASSEMBLER *ASSEMBLY)
{
	free(ASSEMBLY->BYTES);
	free(ASSEMBLY->LABELS);
	free(ASSEMBLY->FIXUPS);
	free(ASSEMBLY->EXTERNAL_TARGETS);
	free(ASSEMBLY->EXTERNAL_POSITIONS);
	memset(ASSEMBLY, 0, sizeof *ASSEMBLY);
}

void
	ASSEMBLER_RESET(ASSEMBLER *ASSEMBLY)
{
	ASSEMBLY->BYTE_COUNT = 0;
	ASSEMBLY->LABEL_COUNT = 0;
	ASSEMBLY->FIXUP_COUNT = 0;
	ASSEMBLY->EXTERNAL_COUNT = 0;
}

void
	ASSEMBLER_EMIT_BYTE(ASSEMBLER *ASSEMBLY, int BYTE_VALUE)
{
	if (ASSEMBLY->BYTE_COUNT >= ASSEMBLY->BYTE_CAPACITY)
	{
		if (ASSEMBLY->BYTE_CAPACITY)
			ASSEMBLY->BYTE_CAPACITY = ASSEMBLY->BYTE_CAPACITY * 2;
		else
			ASSEMBLY->BYTE_CAPACITY = 4096;

		ASSEMBLY->BYTES = realloc(ASSEMBLY->BYTES, ASSEMBLY->BYTE_CAPACITY);
	}

	ASSEMBLY->BYTES[ASSEMBLY->BYTE_COUNT++] = (uint8_t)BYTE_VALUE;
}

void
	ASSEMBLER_EMIT_INTEGER32(ASSEMBLER *ASSEMBLY, int32_t VALUE)
{
	int	BYTE_INDEX;

	for (BYTE_INDEX = 0; BYTE_INDEX < 4; BYTE_INDEX++)
		ASSEMBLER_EMIT_BYTE(ASSEMBLY, (VALUE >> (8 * BYTE_INDEX)) & 255);
}

static void
	WRITE_INTEGER32(uint8_t *DESTINATION, int32_t VALUE)
{
	int	BYTE_INDEX;

	for (BYTE_INDEX = 0; BYTE_INDEX < 4; BYTE_INDEX++)
		DESTINATION[BYTE_INDEX] = (uint8_t)((VALUE >> (8 * BYTE_INDEX)) & 255);
}

int
	ASSEMBLER_NEW_LABEL(ASSEMBLER *ASSEMBLY)
{
	if (ASSEMBLY->LABEL_COUNT >= ASSEMBLY->LABEL_CAPACITY)
	{
		if (ASSEMBLY->LABEL_CAPACITY)
			ASSEMBLY->LABEL_CAPACITY = ASSEMBLY->LABEL_CAPACITY * 2;
		else
			ASSEMBLY->LABEL_CAPACITY = 64;

		ASSEMBLY->LABELS = realloc(
			ASSEMBLY->LABELS, ASSEMBLY->LABEL_CAPACITY * sizeof(int32_t)
		);
	}

	ASSEMBLY->LABELS[ASSEMBLY->LABEL_COUNT] = -1;

	return (ASSEMBLY->LABEL_COUNT++);
}

void
	ASSEMBLER_BIND_LABEL(ASSEMBLER *ASSEMBLY, int LABEL)
{
	ASSEMBLY->LABELS[LABEL] = ASSEMBLY->BYTE_COUNT;
}

static void
	ADD_JUMP_FIXUP(ASSEMBLER *ASSEMBLY, int LABEL)
{
	if (ASSEMBLY->FIXUP_COUNT >= ASSEMBLY->FIXUP_CAPACITY)
	{
		if (ASSEMBLY->FIXUP_CAPACITY)
			ASSEMBLY->FIXUP_CAPACITY = ASSEMBLY->FIXUP_CAPACITY * 2;
		else
			ASSEMBLY->FIXUP_CAPACITY = 64;

		ASSEMBLY->FIXUPS = realloc(
			ASSEMBLY->FIXUPS, ASSEMBLY->FIXUP_CAPACITY * sizeof(JUMP_FIXUP)
		);
	}

	ASSEMBLY->FIXUPS[ASSEMBLY->FIXUP_COUNT].POSITION = ASSEMBLY->BYTE_COUNT;
	ASSEMBLY->FIXUPS[ASSEMBLY->FIXUP_COUNT].TARGET_LABEL = LABEL;
	ASSEMBLY->FIXUP_COUNT++;
	ASSEMBLER_EMIT_INTEGER32(ASSEMBLY, 0);
}

int
	ASSEMBLER_FINISH(ASSEMBLER *ASSEMBLY)
{
	int	FIXUP_INDEX;

	for (FIXUP_INDEX = 0; FIXUP_INDEX < ASSEMBLY->FIXUP_COUNT; FIXUP_INDEX++)
	{
		int32_t	TARGET_OFFSET =
			ASSEMBLY->LABELS[ASSEMBLY->FIXUPS[FIXUP_INDEX].TARGET_LABEL];

		if (TARGET_OFFSET < 0)
			return (-1);

		WRITE_INTEGER32(
			ASSEMBLY->BYTES + ASSEMBLY->FIXUPS[FIXUP_INDEX].POSITION,
			TARGET_OFFSET - (ASSEMBLY->FIXUPS[FIXUP_INDEX].POSITION + 4)
		);
	}

	return (0);
}

static void
	ENCODE_MEMORY_OPERAND(
		ASSEMBLER *ASSEMBLY, int REGISTER_FIELD, MEMORY_OPERAND OPERAND
	)
{
	int	USES_SIB = (OPERAND.BASE & 7) == 4 || OPERAND.INDEX >= 0;

	ASSEMBLER_EMIT_BYTE(
		ASSEMBLY,
		0X80 | ((REGISTER_FIELD & 7) << 3) | (USES_SIB ? 4 : (OPERAND.BASE & 7))
	);

	if (USES_SIB)
	{
		int	SCALE_BITS;

		if (OPERAND.SCALE == 8)
			SCALE_BITS = 3;
		else if (OPERAND.SCALE == 4)
			SCALE_BITS = 2;
		else if (OPERAND.SCALE == 2)
			SCALE_BITS = 1;
		else
			SCALE_BITS = 0;

		int	INDEX_BITS;

		if (OPERAND.INDEX >= 0)
			INDEX_BITS = (OPERAND.INDEX & 7);
		else
			INDEX_BITS = 4;

		ASSEMBLER_EMIT_BYTE(
			ASSEMBLY, (SCALE_BITS << 6) | (INDEX_BITS << 3) | (OPERAND.BASE & 7)
		);
	}

	ASSEMBLER_EMIT_INTEGER32(ASSEMBLY, OPERAND.DISPLACEMENT);
}

static void
	REGISTER_EXTENSION_PREFIX(
		ASSEMBLER *ASSEMBLY, int WIDE, int REGISTER_FIELD, int INDEX_REGISTER,
		int BASE_REGISTER, int FORCE_PREFIX
	)
{
	int	PREFIX_BYTE = 0X40 | (WIDE << 3) | ((REGISTER_FIELD >> 3) << 2) |
		((INDEX_REGISTER >> 3) << 1) | (BASE_REGISTER >> 3);

	if (PREFIX_BYTE != 0X40 || FORCE_PREFIX)
		ASSEMBLER_EMIT_BYTE(ASSEMBLY, PREFIX_BYTE);
}

static void
	GENERAL_MEMORY_FORM(
		ASSEMBLER *ASSEMBLY, int WIDE, const uint8_t *OPCODE_BYTES,
		int OPCODE_COUNT, int REGISTER_FIELD, MEMORY_OPERAND OPERAND
	)
{
	REGISTER_EXTENSION_PREFIX(
		ASSEMBLY, WIDE, REGISTER_FIELD & 8,
		OPERAND.INDEX >= 0 ? (OPERAND.INDEX & 8) : 0, OPERAND.BASE & 8, 0
	);

	int	BYTE_INDEX;

	for (BYTE_INDEX = 0; BYTE_INDEX < OPCODE_COUNT; BYTE_INDEX++)
		ASSEMBLER_EMIT_BYTE(ASSEMBLY, OPCODE_BYTES[BYTE_INDEX]);

	ENCODE_MEMORY_OPERAND(ASSEMBLY, REGISTER_FIELD, OPERAND);
}

static void
	GENERAL_REGISTER_FORM(
		ASSEMBLER *ASSEMBLY, int WIDE, const uint8_t *OPCODE_BYTES,
		int OPCODE_COUNT, int REGISTER_FIELD, int RM_REGISTER
	)
{
	REGISTER_EXTENSION_PREFIX(
		ASSEMBLY, WIDE, REGISTER_FIELD & 8, 0, RM_REGISTER & 8, 0
	);

	int	BYTE_INDEX;

	for (BYTE_INDEX = 0; BYTE_INDEX < OPCODE_COUNT; BYTE_INDEX++)
		ASSEMBLER_EMIT_BYTE(ASSEMBLY, OPCODE_BYTES[BYTE_INDEX]);

	ASSEMBLER_EMIT_BYTE(
		ASSEMBLY, 0XC0 | ((REGISTER_FIELD & 7) << 3) | (RM_REGISTER & 7)
	);
}

