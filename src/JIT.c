void
	*EXECUTABLE_ALLOCATE(size_t BYTE_COUNT)
{
#ifdef _WIN32
	return (
		VirtualAlloc(
			NULL, BYTE_COUNT, MEM_COMMIT | MEM_RESERVE, PAGE_EXECUTE_READWRITE
		)
	);
#else
	void	*ADDRESS = mmap(
		NULL, BYTE_COUNT, PROT_READ | PROT_WRITE | PROT_EXEC,
		MAP_PRIVATE | MAP_ANONYMOUS, -1, 0
	);

	if (ADDRESS == MAP_FAILED)
		return (NULL);

	return (ADDRESS);
#endif
}

void
	EXECUTABLE_FREE(void *ADDRESS, size_t BYTE_COUNT)
{
	if (!ADDRESS)
		return ;
#ifdef _WIN32
	(void)BYTE_COUNT;
	VirtualFree(ADDRESS, 0, MEM_RELEASE);
#else
	munmap(ADDRESS, BYTE_COUNT);
#endif
}

void
	*VIRTUAL_RESERVE(size_t BYTE_COUNT)
{
#ifdef _WIN32
	return (VirtualAlloc(NULL, BYTE_COUNT, MEM_RESERVE, PAGE_NOACCESS));
#else
	void	*ADDRESS = mmap(
		NULL, BYTE_COUNT, PROT_NONE,
		MAP_PRIVATE | MAP_ANONYMOUS | MAP_NORESERVE, -1, 0
	);

	if (ADDRESS == MAP_FAILED)
		return (NULL);

	return (ADDRESS);
#endif
}

int
	VIRTUAL_COMMIT(void *ADDRESS, size_t BYTE_COUNT, int EXECUTABLE)
{
#ifdef _WIN32
	if (
		VirtualAlloc(
			ADDRESS, BYTE_COUNT, MEM_COMMIT,
			EXECUTABLE ? PAGE_EXECUTE_READWRITE : PAGE_READWRITE
		)
	)
		return (0);

	return (-1);
#else
	return (
		mprotect(
			ADDRESS, BYTE_COUNT,
			PROT_READ | PROT_WRITE | (EXECUTABLE ? PROT_EXEC : 0)
		)
	);
#endif
}

int
	VIRTUAL_PROTECT(void *ADDRESS, size_t BYTE_COUNT, int WRITABLE)
{
#ifdef _WIN32
	DWORD	OLD_PROTECTION;

	if (
		VirtualProtect(
			ADDRESS, BYTE_COUNT,
			WRITABLE ? PAGE_EXECUTE_READWRITE : PAGE_EXECUTE_READ,
			&OLD_PROTECTION
		)
	)
		return (0);

	return (-1);
#else
	return (
		mprotect(
			ADDRESS, BYTE_COUNT,
			PROT_READ | PROT_EXEC | (WRITABLE ? PROT_WRITE : 0)
		)
	);
#endif
}

void
	VIRTUAL_RELEASE(void *ADDRESS, size_t BYTE_COUNT)
{
	if (!ADDRESS)
		return ;
#ifdef _WIN32
	(void)BYTE_COUNT;
	VirtualFree(ADDRESS, 0, MEM_RELEASE);
#else
	munmap(ADDRESS, BYTE_COUNT);
#endif
}

int
	CPU_SUPPORTED(void)
{
	unsigned	CPUID_EAX;
	unsigned	CPUID_EBX;
	unsigned	CPUID_ECX;
	unsigned	CPUID_EDX;

	if (!__get_cpuid(1, &CPUID_EAX, &CPUID_EBX, &CPUID_ECX, &CPUID_EDX))
		return (0);

	if (
		!(CPUID_ECX & ((unsigned int)1 << 12)) ||
		!(CPUID_ECX & ((unsigned int)1 << 27)) ||
		!(CPUID_ECX & ((unsigned int)1 << 28)) ||
		!(CPUID_ECX & ((unsigned int)1 << 29))
	)
		return (0);

	unsigned	STATE_MASK_LOW;
	unsigned	STATE_MASK_HIGH;

	__asm__ volatile("xgetbv"
		: "=a"(STATE_MASK_LOW), "=d"(STATE_MASK_HIGH)
		: "c"(0));

	if ((STATE_MASK_LOW & 6) != 6)
		return (0);

	if (
		!__get_cpuid_count(7, 0, &CPUID_EAX, &CPUID_EBX, &CPUID_ECX, &CPUID_EDX)
	)
		return (0);

	return ((CPUID_EBX & ((unsigned int)1 << 5)) != 0);
}
