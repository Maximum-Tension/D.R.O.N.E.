	int32_t	NEXT_RESIDUAL_OFFSET;
	int32_t	NORMALIZED_OFFSET;
	int32_t	NORMALIZED_GRADIENT_OFFSET;
	int32_t	RESIDUAL_GRADIENT_OFFSET;
	int32_t	NEXT_RESIDUAL_GRADIENT;
	int32_t	GRADIENT_PLANE;
	int		IS_LAST;
