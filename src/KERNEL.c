static int
	GENERATE_STUB(
		ASSEMBLER *ASSEMBLY, WEB *NEURAL_WEB, NEURON *STUB_NEURON, int PASS_ROLE
	)
{
	int32_t	ORGAN_INDEX = WEB_ORGAN(
		NEURAL_WEB, ORGAN_KEY(STUB_NEURON->KIND, STUB_NEURON->KIND_DETAIL),
		STUB_NEURON->AREA_INDEX
	);
	int64_t	ACTIVATION_ADDRESS;

	if (STUB_NEURON->KIND == KIND_WORD)
		ACTIVATION_ADDRESS = LOGITS_OFFSET +
			(int64_t)STUB_NEURON->KIND_DETAIL *
				NEURAL_WEB->CONFIGURATION.MAXIMUM_LENGTH * 4;
	else
		ACTIVATION_ADDRESS = STUB_NEURON->ACTIVATION_OFFSET;

	LOAD_ADDRESS(
		ASSEMBLY, R12,
		WEIGHT_OPERAND(R13, -1, (int32_t)STUB_NEURON->PARAMETER_OFFSET)
	);
	STORE_IMMEDIATE64(
		ASSEMBLY, STATE_FIELD(NEURON_ACTIVATION_OFFSET),
		(int32_t)ACTIVATION_ADDRESS
	);

	if (STUB_NEURON->KIND == KIND_WORD && PASS_ROLE == ROLE_FORWARD)
		STORE_IMMEDIATE64(
			ASSEMBLY, STATE_FIELD(INFERENCE_LOGIT_OFFSET),
			(int32_t)(LAST_LOGITS_OFFSET + (int64_t)STUB_NEURON->KIND_DETAIL * 4
			)
		);

	LOAD_RELATIVE_ADDRESS(ASSEMBLY, RBP);

	int	PATCH_POSITION = ASSEMBLY->BYTE_COUNT - 4;

	JUMP_TO_PIECE(ASSEMBLY, ORGAN_INDEX * 4 + PASS_ROLE);

	return (PATCH_POSITION);
}

int
	GENERATE_PIECE(
		WEB *NEURAL_WEB, ASSEMBLER *ASSEMBLY, NEURON *CURRENT_NEURON,
		int PASS_ROLE
	)
{
	HALF_WEIGHTS = NEURAL_WEB->HALF_PRECISION;

	switch (CURRENT_NEURON->KIND)
	{
		case KIND_ENTRY:
		{
			GENERATE_ENTRY(ASSEMBLY, NEURAL_WEB);
			return (-1);
		}
		case KIND_EXIT:
		{
			GENERATE_EXIT(ASSEMBLY);
			return (-2);
		}
		case KIND_UPDATE_START:
		{
			return (-1);
		}
		case KIND_INFERENCE_GATE:
		{
			MOVE_FROM_MEMORY(ASSEMBLY, RAX, STATE_FIELD(MODE));
			COMPARE_IMMEDIATE(ASSEMBLY, RAX, MODE_INFER);
			BRANCH_TO_PIECE(ASSEMBLY, CC_E, NEURAL_WEB->EXIT_ID * 4);
			return (-1);
		}
		case KIND_EVALUATION_GATE:
		{
			MOVE_FROM_MEMORY(ASSEMBLY, RAX, STATE_FIELD(MODE));
			COMPARE_IMMEDIATE(ASSEMBLY, RAX, MODE_EVALUATE);
			BRANCH_TO_PIECE(ASSEMBLY, CC_E, NEURAL_WEB->EXIT_ID * 4);
			return (-1);
		}
		case KIND_GROW:
		{
			GENERATE_GROW(ASSEMBLY);
			return (-1);
		}
		case KIND_ADAM:
		{
			GENERATE_ADAM(ASSEMBLY);
			return (-1);
		}
		case KIND_LOSS:
		{
			GENERATE_LOSS(ASSEMBLY, NEURAL_WEB);
			return (-1);
		}
		case KIND_EMBEDDING:
		{
			GENERATE_EMBED(ASSEMBLY, NEURAL_WEB, CURRENT_NEURON, PASS_ROLE);
			return (-1);
		}
		case KIND_NORMALIZATION:
		{
			GENERATE_NORM(ASSEMBLY, NEURAL_WEB, CURRENT_NEURON, PASS_ROLE);
			return (-1);
		}
		case KIND_COPY:
		{
			GENERATE_COPY(ASSEMBLY, NEURAL_WEB, CURRENT_NEURON, PASS_ROLE);
			return (-1);
		}
		case KIND_FEED_FORWARD:
		case KIND_ATTENTION_HEAD:
		case KIND_WORD:
		case KIND_RECIPE:
		case KIND_TREE:
		{
			return (
				GENERATE_STUB(ASSEMBLY, NEURAL_WEB, CURRENT_NEURON, PASS_ROLE)
			);
		}
		case KIND_ORGAN:
		{
			if (CURRENT_NEURON->KIND_DETAIL >= ORGAN_RECIPE_BASE)
				GENERATE_RECIPE(
					ASSEMBLY, NEURAL_WEB, CURRENT_NEURON, PASS_ROLE
				);
			else if (
				CURRENT_NEURON->KIND_DETAIL >= ORGAN_TREE_BASE &&
				CURRENT_NEURON->KIND_DETAIL < ORGAN_ROTARY_HEAD
			)
				GENERATE_TREE(ASSEMBLY, NEURAL_WEB, CURRENT_NEURON, PASS_ROLE);
			else if (CURRENT_NEURON->KIND_DETAIL == KIND_FEED_FORWARD)
				GENERATE_FEED_FORWARD(
					ASSEMBLY, NEURAL_WEB, CURRENT_NEURON, PASS_ROLE
				);
			else if (
				CURRENT_NEURON->KIND_DETAIL == KIND_ATTENTION_HEAD ||
				CURRENT_NEURON->KIND_DETAIL == ORGAN_ROTARY_HEAD
			)
			{
				USE_ROTARY = CURRENT_NEURON->KIND_DETAIL == ORGAN_ROTARY_HEAD;
				GENERATE_HEAD(ASSEMBLY, NEURAL_WEB, CURRENT_NEURON, PASS_ROLE);
				USE_ROTARY = 0;
			}
			else
				GENERATE_WORD(ASSEMBLY, NEURAL_WEB, CURRENT_NEURON, PASS_ROLE);

			return (-2);
		}
		default:
		{
			return (-1);
		}
	}
}
