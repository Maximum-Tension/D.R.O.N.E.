static void
	ADAM_CHUNK(
		ASSEMBLER *ASSEMBLY, void *BODY_STATE, int INDEX_REGISTER,
		int32_t OFFSET
	)
{
	(void)BODY_STATE;

	int32_t	PLANE_SIZE = (int32_t)PARAMETER_PLANE;

	VECTOR_LOAD(
		ASSEMBLY, 1, 0, OPERAND_AT(RSI, INDEX_REGISTER, OFFSET + PLANE_SIZE)
	);
	VECTOR_LOAD(
		ASSEMBLY, 1, 1, OPERAND_AT(RSI, INDEX_REGISTER, OFFSET + 2 * PLANE_SIZE)
	);
	VECTOR_MATH(ASSEMBLY, 1, OPCODE_MULTIPLY, 1, 1, 8);
	MULTIPLY_ADD(ASSEMBLY, 1, 1, 0, 9);
	VECTOR_LOAD(
		ASSEMBLY, 1, 2, OPERAND_AT(RSI, INDEX_REGISTER, OFFSET + 3 * PLANE_SIZE)
	);
	VECTOR_MATH(ASSEMBLY, 1, OPCODE_MULTIPLY, 2, 2, 10);
	VECTOR_MATH(ASSEMBLY, 1, OPCODE_MULTIPLY, 3, 0, 0);
	MULTIPLY_ADD(ASSEMBLY, 1, 2, 3, 11);
	VECTOR_STORE(
		ASSEMBLY, 1, OPERAND_AT(RSI, INDEX_REGISTER, OFFSET + 2 * PLANE_SIZE), 1
	);
	VECTOR_STORE(
		ASSEMBLY, 1, OPERAND_AT(RSI, INDEX_REGISTER, OFFSET + 3 * PLANE_SIZE), 2
	);
	VECTOR_STORE(
		ASSEMBLY, 1, OPERAND_AT(RSI, INDEX_REGISTER, OFFSET + PLANE_SIZE), 6
	);
	VECTOR_MATH(ASSEMBLY, 1, OPCODE_MULTIPLY, 3, 2, 13);
	VECTOR_MATH(ASSEMBLY, 1, OPCODE_SQUARE_ROOT, 3, 0, 3);
	VECTOR_MATH(ASSEMBLY, 1, OPCODE_ADD, 3, 3, 14);
	VECTOR_MATH(ASSEMBLY, 1, OPCODE_MULTIPLY, 4, 1, 12);
	VECTOR_MATH(ASSEMBLY, 1, OPCODE_DIVIDE, 4, 4, 3);
	VECTOR_LOAD(ASSEMBLY, 1, 5, OPERAND_AT(RSI, INDEX_REGISTER, OFFSET));
	MULTIPLY_ADD(ASSEMBLY, 1, 4, 5, 7);
	VECTOR_MATH(ASSEMBLY, 1, OPCODE_MULTIPLY, 4, 4, 15);
	VECTOR_MATH(ASSEMBLY, 1, OPCODE_SUBTRACT, 5, 5, 4);
	VECTOR_STORE(ASSEMBLY, 1, OPERAND_AT(RSI, INDEX_REGISTER, OFFSET), 5);
}

static void
	GENERATE_ADAM(ASSEMBLER *ASSEMBLY)
{
	BROADCAST_MEMORY(ASSEMBLY, 1, 8, STATE_FIELD(FIRST_MOMENT_DECAY));
	BROADCAST_MEMORY(ASSEMBLY, 1, 9, STATE_FIELD(FIRST_MOMENT_RATE));
	BROADCAST_MEMORY(ASSEMBLY, 1, 10, STATE_FIELD(SECOND_MOMENT_DECAY));
	BROADCAST_MEMORY(ASSEMBLY, 1, 11, STATE_FIELD(SECOND_MOMENT_RATE));
	BROADCAST_MEMORY(ASSEMBLY, 1, 12, STATE_FIELD(FIRST_BIAS_CORRECTION));
	BROADCAST_MEMORY(ASSEMBLY, 1, 13, STATE_FIELD(SECOND_BIAS_CORRECTION));
	BROADCAST_MEMORY(ASSEMBLY, 1, 14, STATE_FIELD(EPSILON));
	BROADCAST_MEMORY(ASSEMBLY, 1, 15, STATE_FIELD(LEARNING_RATE));
	BROADCAST_MEMORY(ASSEMBLY, 1, 7, STATE_FIELD(WEIGHT_DECAY));
	ZERO_VECTOR(ASSEMBLY, 6);

	int	PART_INDEX;

	for (PART_INDEX = 0; PART_INDEX < 2; PART_INDEX++)
	{
		int	LOOP_TOP = ASSEMBLER_NEW_LABEL(ASSEMBLY);
		int	LOOP_DONE = ASSEMBLER_NEW_LABEL(ASSEMBLY);

		if (PART_INDEX == 0)
			MOVE_REGISTER(ASSEMBLY, RSI, R13);
		else
			LOAD_ADDRESS(
				ASSEMBLY, RSI, MEMORY_AT(R13, (int32_t)WORD_PLANE_OFFSET)
			);

		MOVE_IMMEDIATE(ASSEMBLY, R11, 0);
		ASSEMBLER_BIND_LABEL(ASSEMBLY, LOOP_TOP);
		COMPARE_MEMORY(
			ASSEMBLY, R11,
			PART_INDEX == 0 ? STATE_FIELD(PARAMETER_BYTES_USED)
							: STATE_FIELD(WORD_BYTES_USED)
		);
		BRANCH_TO_LABEL(ASSEMBLY, CC_GE, LOOP_DONE);
		ADAM_CHUNK(ASSEMBLY, NULL, R11, 0);
		ADD_IMMEDIATE(ASSEMBLY, R11, 32);
		JUMP_TO_LABEL(ASSEMBLY, LOOP_TOP);
		ASSEMBLER_BIND_LABEL(ASSEMBLY, LOOP_DONE);
	}
}

static void
	GENERATE_ENTRY(ASSEMBLER *ASSEMBLY, WEB *NEURAL_WEB)
{
	int	SAVED_REGISTERS[8] = { RBX, RBP, RDI, RSI, R12, R13, R14, R15 };
	int	REGISTER_INDEX;

	for (REGISTER_INDEX = 0; REGISTER_INDEX < 8; REGISTER_INDEX++)
		PUSH_REGISTER(ASSEMBLY, SAVED_REGISTERS[REGISTER_INDEX]);

	SUBTRACT_IMMEDIATE(ASSEMBLY, RSP, 200);

	for (REGISTER_INDEX = 0; REGISTER_INDEX < 10; REGISTER_INDEX++)
		VECTOR_STORE(
			ASSEMBLY, 0, MEMORY_AT(RSP, 32 + 16 * REGISTER_INDEX),
			6 + REGISTER_INDEX
		);

	MOVE_REGISTER(ASSEMBLY, R15, RCX);
	MOVE_FROM_MEMORY(ASSEMBLY, R14, STATE_FIELD(ACTIVATIONS));
	MOVE_FROM_MEMORY(ASSEMBLY, R13, STATE_FIELD(PARAMETERS));
	MOVE_FROM_MEMORY(ASSEMBLY, RBX, STATE_FIELD(SERVICE_TABLE));
	MOVE_FROM_MEMORY(ASSEMBLY, RAX, STATE_FIELD(MODE));
	COMPARE_IMMEDIATE(ASSEMBLY, RAX, MODE_UPDATE);
	BRANCH_TO_PIECE(ASSEMBLY, CC_E, NEURAL_WEB->UPDATE_START_ID * 4);
}

static void
	GENERATE_EXIT(ASSEMBLER *ASSEMBLY)
{
	int	SAVED_REGISTERS[8] = { RBX, RBP, RDI, RSI, R12, R13, R14, R15 };

	CLEAR_UPPER_HALVES(ASSEMBLY);

	int	REGISTER_INDEX;

	for (REGISTER_INDEX = 0; REGISTER_INDEX < 10; REGISTER_INDEX++)
		VECTOR_LOAD(
			ASSEMBLY, 0, 6 + REGISTER_INDEX,
			MEMORY_AT(RSP, 32 + 16 * REGISTER_INDEX)
		);

	ADD_IMMEDIATE(ASSEMBLY, RSP, 200);

	for (REGISTER_INDEX = 7; REGISTER_INDEX >= 0; REGISTER_INDEX--)
		POP_REGISTER(ASSEMBLY, SAVED_REGISTERS[REGISTER_INDEX]);

	RETURN_INSTRUCTION(ASSEMBLY);
}

static void
	GENERATE_GROW(ASSEMBLER *ASSEMBLY)
{
	int	SKIP_LABEL = ASSEMBLER_NEW_LABEL(ASSEMBLY);

	MOVE_FROM_MEMORY(ASSEMBLY, RAX, STATE_FIELD(REQUEST_AREA));
	TEST_REGISTER(ASSEMBLY, RAX, RAX);
	BRANCH_TO_LABEL(ASSEMBLY, CC_S, SKIP_LABEL);
	MOVE_REGISTER(ASSEMBLY, RCX, R15);
	MOVE_REGISTER(ASSEMBLY, RDI, R15);
	CALL_MEMORY(ASSEMBLY, MEMORY_AT(RBX, SERVICE_CREATE * 8));
	MOVE_FROM_MEMORY(ASSEMBLY, R14, STATE_FIELD(ACTIVATIONS));
	MOVE_FROM_MEMORY(ASSEMBLY, R13, STATE_FIELD(PARAMETERS));
	MOVE_FROM_MEMORY(ASSEMBLY, RBX, STATE_FIELD(SERVICE_TABLE));
	ASSEMBLER_BIND_LABEL(ASSEMBLY, SKIP_LABEL);
}

