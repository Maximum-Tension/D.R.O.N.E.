static TIME_LOOP
	BEGIN_TIME_LOOP(ASSEMBLER *ASSEMBLY, int FROM_START_TIME)
{
	TIME_LOOP	STEP_LOOP = {
		ASSEMBLER_NEW_LABEL(ASSEMBLY), ASSEMBLER_NEW_LABEL(ASSEMBLY)
	};

	if (FROM_START_TIME)
		MOVE_FROM_MEMORY(ASSEMBLY, RAX, STATE_FIELD(START_POSITION));
	else
		MOVE_IMMEDIATE(ASSEMBLY, RAX, 0);

	ASSEMBLER_BIND_LABEL(ASSEMBLY, STEP_LOOP.TOP_LABEL);
	COMPARE_MEMORY(ASSEMBLY, RAX, STATE_FIELD(SEQUENCE_LENGTH));
	BRANCH_TO_LABEL(ASSEMBLY, CC_GE, STEP_LOOP.END_LABEL);

	return (STEP_LOOP);
}

static void
	END_TIME_LOOP(ASSEMBLER *ASSEMBLY, TIME_LOOP STEP_LOOP)
{
	ADD_IMMEDIATE(ASSEMBLY, RAX, 1);
	JUMP_TO_LABEL(ASSEMBLY, STEP_LOOP.TOP_LABEL);
	ASSEMBLER_BIND_LABEL(ASSEMBLY, STEP_LOOP.END_LABEL);
}

