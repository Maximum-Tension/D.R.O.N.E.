static void
	NORM_FORWARD_CHUNK(
		ASSEMBLER *ASSEMBLY, void *BODY_STATE, int INDEX_REGISTER,
		int32_t OFFSET
	)
{
	NORM_LAYOUT	*NORM_STATE = BODY_STATE;

	VECTOR_LOAD(
		ASSEMBLY, 1, 2,
		OPERAND_AT(RSI, INDEX_REGISTER, NORM_STATE->RESIDUAL_OFFSET + OFFSET)
	);

	if (!NORM_STATE->IS_LAST)
		VECTOR_STORE(
			ASSEMBLY, 1,
			OPERAND_AT(
				RSI, INDEX_REGISTER, NORM_STATE->NEXT_RESIDUAL_OFFSET + OFFSET
			),
			2
		);

	VECTOR_MATH(ASSEMBLY, 1, OPCODE_MULTIPLY, 2, 2, 1);
	WEIGHT_MATH(
		ASSEMBLY, OPCODE_MULTIPLY, 2, 2,
		WEIGHT_OPERAND(RDI, INDEX_REGISTER, OFFSET)
	);
	VECTOR_STORE(
		ASSEMBLY, 1,
		OPERAND_AT(RSI, INDEX_REGISTER, NORM_STATE->NORMALIZED_OFFSET + OFFSET),
		2
	);
}

